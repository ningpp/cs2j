    private static SolidColorBrush named(int a, int r, int g, int b) {
        return new SolidColorBrush(Color.fromArgb(a, r, g, b));
    }

    /**
     * Looks up a named brush by (case-insensitive, spaces ignored) name; null if unknown.
     */
    public static SolidColorBrush fromName(String name) {
        if (name == null) return null;
        String key = name.toLowerCase(java.util.Locale.ROOT).replace(" ", "");
        try {
            for (java.lang.reflect.Field field : Brushes.class.getFields()) {
                if (!java.lang.reflect.Modifier.isStatic(field.getModifiers())) continue;
                if (!SolidColorBrush.class.isAssignableFrom(field.getType())) continue;
                // field names mirror the WPF brush names: match on the lower-cased, space-stripped name.
                String fieldKey = field.getName().toLowerCase(java.util.Locale.ROOT).replace(" ", "");
                if (fieldKey.equals(key)) {
                    return (SolidColorBrush) field.get(null);
                }
            }
        } catch (ReflectiveOperationException ignored) {
            return null;
        }
        return null;
    }
