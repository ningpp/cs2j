public class PropertyTransformer : IMemberTransformer {
private const JavaModifiers Visibility = JavaModifiers.Public | JavaModifiers.Protected | JavaModifiers.Private; 
public JavaSyntaxNode Transform(MemberDeclarationSyntax node, ConversionContext ctx) {
if (node is not PropertyDeclarationSyntax p) throw new ArgumentException($"Expected PropertyDeclarationSyntax, got {node.GetType()}");
ctx.IsInAsyncContext = false; var result = new List<JavaSyntaxNode>();  var typeSyntax = p.Type is RefTypeSyntax rt ? rt.Type : p.Type;
var typeInfo = ctx.GetTypeInfo(typeSyntax);
var propType = typeInfo.Type is null ? ctx.MapTypeFromSyntax(typeSyntax) : ctx.MapType(typeInfo.Type);
var sym = ctx.GetDeclaredSymbol(p) as IPropertySymbol; var explicitImpl = p.ExplicitInterfaceSpecifier != null;
var name = ConversionContext.EscapeJavaKeyword(explicitImpl ? p.Identifier.Text : sym?.Name ?? p.Identifier.Text);
var fieldName = sym != null
? JavaNaming.GetAutoPropertyBackingFieldName(sym) : ConversionContext.EscapeJavaKeyword(Camel(name)); 
var isStatic = p.Modifiers.Any(m => m.IsKind(StaticKeyword)); var baseMods = ConvertModifiers(p.Modifiers, isStatic);
var oldStatic = ctx.IsInStaticMember; if (isStatic) ctx.IsInStaticMember = true;
var comments = ctx.GetDeclarationComments(p, sym).ToCombinedComment();
var specialEncoding = sym is { Name: "Preamble", ContainingType: { } enc } && IsEncodingType(enc); 
var getAccessor = p.AccessorList?.Accessors.FirstOrDefault(a => a.IsKind(GetAccessorDeclaration));
var setAccessor = p.AccessorList?.Accessors.FirstOrDefault(a => a.IsKind(SetAccessorDeclaration) || a.IsKind(InitAccessorDeclaration));
var hasGetter = getAccessor != null || p.AccessorList == null; var hasSetter = setAccessor != null;
var isAuto = p.ExpressionBody == null && IsEmpty(getAccessor) && (setAccessor == null || IsEmpty(setAccessor));
var isHiding = IsHiding(sym); var pureBase = isHiding && IsPureBaseDelegation(p);
var isAbstract = p.Modifiers.Any(m => m.IsKind(AbstractKeyword));
var needsField = (isAuto || p.Initializer != null) && !isAbstract && !ctx.IsInInterfaceBody; 
var field = new JavaFieldDeclaration { Name = fieldName, Type = propType, Modifiers = JavaModifiers.Private | (isStatic ? JavaModifiers.Static : JavaModifiers.None) };
InitDefault(field, p, sym, typeInfo, propType, fieldName, isStatic, needsField, ctx);
if (p.Initializer != null) InitExpression(field, p, sym, fieldName, isStatic, ctx);
if (needsField) { ApplyXml(p, field, ctx); result.Add(field); } var emit = !isHiding || pureBase || (needsField && IsAutoProperty(p)); 
JavaMethodDeclaration BuildGetter() { var src = p.ExpressionBody?.Expression ?? getAccessor?.ExpressionBody?.Expression;
var m = new JavaMethodDeclaration { Name = specialEncoding ? "getPreambleSpan" : JavaNaming.GetPropertyGetterName(name) + HidingSuffix(sym),
ReturnType = propType, Modifiers = AccessorModifiers(p.Modifiers, getAccessor?.Modifiers ?? default, baseMods, false, ctx),
LeadingComment = comments, Body = p.ExpressionBody != null ? Expr(p.ExpressionBody.Expression, ctx)
: getAccessor?.ExpressionBody != null ? Expr(getAccessor.ExpressionBody.Expression, ctx)
: StructCloneHelper.IsUserDefinedStruct(typeInfo.Type) ? $"return {fieldName}.clone();" : $"return {fieldName};",
IsBodyExpression = src != null, IsAutoGenerated = true, IsExplicitInterfaceImplementation = explicitImpl };
// A property that implements an interface property (e.g. IEnumerator<T>.Current
// on an iterator state machine) must use the boxed Java return type: the mapped
// interface declares CSharpGenericEnumerator<T>.getCurrent() : T, so an `int`
// return cannot override Integer. The `return field;` body still compiles via
// autoboxing.
if (sym != null && NeedsBoxedInterfaceReturn(sym))
    m.ReturnType = BoxJavaPrimitive(m.ReturnType);
AddGetterAnnotations(m, sym, typeInfo, ctx);  if (src != null) {
if (specialEncoding && typeInfo.Type?.ToDisplayString() == "System.ReadOnlySpan<byte>")
{ ctx.AddImport("io.github.ningpp.compat.MemoryExtensions"); m.Body = $"MemoryExtensions.asSpan({m.Body})"; }
m.Body = MethodTransformer.WrapExpressionBodyForIterableReturn(m.Body!, src, p.Type, ctx);
m.Body = StructCloneHelper.CloneStructValueIfNeeded(src, m.Body!, typeInfo.Type, ctx);
if (ctx.HasPendingPreStatements || ctx.HasPendingPostStatements) {
var lines = new List<string>(ctx.DrainPreStatements().Select(s => s.TrimEnd(';') + ";")); if (ctx.HasPendingPostStatements) {
var r = ctx.GenerateSyntheticName("_ret"); lines.Add($"var {r} = {m.Body};");
lines.AddRange(ctx.DrainPostStatements().Select(s => s.TrimEnd(';') + ";")); lines.Add($"return {r};"); }
else lines.Add($"return {m.Body!.TrimEnd(';')};"); m.Body = string.Join("\n", lines); m.IsBodyExpression = false; } } 
if (getAccessor?.Body != null) { ctx.ReturnsCSharpGenericIterable = m.ReturnType.StartsWith("CSharpGenericIterable<");
var st = new Transformers.Statement.StatementTransformer(); if (getAccessor.Body.DescendantNodes().OfType<YieldStatementSyntax>().Any()) {
ctx.IsInYieldMethod = true; ctx.AddImport("io.github.ningpp.compat.CSharpList"); var elem = YieldElementType(propType) ?? "Object";
if (propType.StartsWith("CSharpGenericIterable<") || propType.StartsWith("CSharpICollection<") || propType.StartsWith("CSharpGenericIList<"))
{ ctx.AddImport("io.github.ningpp.compat.CSharpGenericIterable"); m.ReturnType = $"CSharpGenericIterable<{elem}>"; }
else { ctx.AddImport("java.util.List"); m.ReturnType = $"List<{elem}>"; } var body = st.TransformBlock(getAccessor.Body, ctx);
m.Body = $"CSharpList<{elem}> _yieldResult = new CSharpList<{elem}>();\n        {body}\n        return _yieldResult;";
ctx.IsInYieldMethod = false; } else m.StructuredBody = st.TransformBlockToStructuredBody(getAccessor.Body, ctx); m.IsBodyExpression = false;
} StaticMemberTypeParameterHelper.PromoteReferencedEnclosingTypeParameters(m, p, isStatic, sym, ctx); return m; }  JavaMethodDeclaration BuildSetter() {
string? bodyExpr = setAccessor?.ExpressionBody != null ? Expr(setAccessor.ExpressionBody.Expression, ctx) : null;
var isExpr = bodyExpr != null; var hoisted = isExpr && (ctx.HasPendingPreStatements || ctx.HasPendingPostStatements);
var m = new JavaMethodDeclaration { Name = "set" + Pascal(name) + HidingSuffix(sym), ReturnType = "void",
Modifiers = AccessorModifiers(p.Modifiers, setAccessor?.Modifiers ?? default, baseMods, true, ctx),
LeadingComment = hasGetter ? null : comments, Parameters = { new JavaParameter(propType, "value") },
Body = bodyExpr ?? (StructCloneHelper.IsUserDefinedStruct(typeInfo.Type)
? isStatic ? $"{fieldName} = value.clone();" : $"this.{fieldName} = value.clone();"
: isStatic ? $"{fieldName} = value;" : $"this.{fieldName} = value;"),
IsBodyExpression = isExpr, IsAutoGenerated = true, IsExplicitInterfaceImplementation = explicitImpl && !hoisted }; 
if (sym != null && JavaNaming.IsIncompatibleTypeHidingProperty(sym)) AddAnnotation(m, $"CompatPropertyName(\"{sym.Name}\")", ctx);
if (!hoisted && sym != null && !HasJsonInclude(sym) && !IsPublicAccessor(sym.SetMethod)) AddAnnotation(m, "CompatNonPublicAccessor", ctx); 
if (hoisted) { var stmts = new List<JavaStatement>(ctx.DrainPreStatements().Select(s => new JavaRawStatement(s.TrimEnd(';') + ";")));
if (!IsBareRead(bodyExpr!)) stmts.Add(new JavaRawStatement(bodyExpr!.TrimEnd(';') + ";"));
stmts.AddRange(ctx.DrainPostStatements().Select(s => new JavaRawStatement(s.TrimEnd(';') + ";")));
m.StructuredBody = new JavaMethodBody(stmts); m.Body = null; } else if (setAccessor?.Body != null) {
m.StructuredBody = new Transformers.Statement.StatementTransformer().TransformBlockToStructuredBody(setAccessor.Body, ctx);
m.IsBodyExpression = false; } if (setAccessor?.IsKind(InitAccessorDeclaration) == true)
m.LeadingComment = ConvertedCommentSet.JoinComments(m.LeadingComment, "/** @implNote Set during construction only (C# init accessor). */");
StaticMemberTypeParameterHelper.PromoteReferencedEnclosingTypeParameters(m, p, isStatic, sym, ctx); return m; }  if (emit && hasGetter) result.Add(BuildGetter()); if (emit && hasSetter) result.Add(BuildSetter());
var hoistedLocals = new Queue<LocalFunctionStatementSyntax>(ctx.MethodState.DrainHoistedLocalFunctions()); while (hoistedLocals.Count > 0) {
var local = hoistedLocals.Dequeue(); result.Add(MethodTransformer.TransformLocalFunction(local, ctx));
foreach (var nested in ctx.MethodState.DrainHoistedLocalFunctions()) hoistedLocals.Enqueue(nested); }
ctx.IsInStaticMember = oldStatic; return new JavaMemberCollection(result); } 
private JavaModifiers ConvertModifiers(SyntaxTokenList tokens, bool isStatic) {
var r = tokens.Aggregate(JavaModifiers.None, (a, m) => a | ((SyntaxKind)m.RawKind) switch {
PublicKeyword => JavaModifiers.Public, ProtectedKeyword => JavaModifiers.Protected,
PrivateKeyword => JavaModifiers.Private, InternalKeyword => JavaModifiers.Public,
StaticKeyword => JavaModifiers.Static, OverrideKeyword => JavaModifiers.Override,
NewKeyword => JavaModifiers.Override, AbstractKeyword => JavaModifiers.Abstract,
SealedKeyword => JavaModifiers.Final, _ => JavaModifiers.None }); if (isStatic) r |= JavaModifiers.Static;
if (r.HasFlag(JavaModifiers.Protected) && r.HasFlag(JavaModifiers.Public)) r &= ~JavaModifiers.Public; return r; } 
private JavaModifiers AccessorModifiers(SyntaxTokenList propertyTokens, SyntaxTokenList accessorTokens, JavaModifiers modifiers, bool isSetter, ConversionContext ctx)
{ if (!HasVisibility(propertyTokens)) modifiers = JavaModifiers.Public | (modifiers & ~Visibility); if (HasVisibility(accessorTokens))
{ var a = ConvertModifiers(accessorTokens, false); modifiers = (modifiers & ~Visibility) | (a & Visibility); }
var propertyIsPublic = propertyTokens.Any(m => m.IsKind(PublicKeyword)) || !HasVisibility(propertyTokens);
return SingleAccess(modifiers, isSetter && propertyIsPublic, isSetter); } 
private static JavaModifiers SingleAccess(JavaModifiers m, bool propertyIsPublic = false, bool javaTarget = true) {
if (m.HasFlag(JavaModifiers.Private) && m.HasFlag(JavaModifiers.Protected)) return m & ~JavaModifiers.Public & ~JavaModifiers.Private;
if (javaTarget && propertyIsPublic && m.HasFlag(JavaModifiers.Private) && !m.HasFlag(JavaModifiers.Public) && !m.HasFlag(JavaModifiers.Protected))
return (m & ~JavaModifiers.Private) | JavaModifiers.Protected;
if (m.HasFlag(JavaModifiers.Private)) return m & ~JavaModifiers.Public & ~JavaModifiers.Protected;
if (m.HasFlag(JavaModifiers.Protected)) return m & ~JavaModifiers.Public; return m; } 
private static bool HasVisibility(SyntaxTokenList t) => t.Any(m =>
m.IsKind(PublicKeyword) || m.IsKind(ProtectedKeyword) || m.IsKind(PrivateKeyword) || m.IsKind(InternalKeyword));
private static string Camel(string n) => n.Length == 0 ? n : char.ToLower(n[0]) + n[1..];
private static string Pascal(string n) => n.Length == 0 ? n : char.ToUpperInvariant(n[0]) + n[1..];
private static string HidingSuffix(IPropertySymbol? p) => p != null && JavaNaming.IsIncompatibleTypeHidingProperty(p) ? "_newSlot" : "";
private static string Expr(ExpressionSyntax e, ConversionContext c) => ExpressionTransformerFacade.Instance.Transform(e, c);
private static bool IsEmpty(AccessorDeclarationSyntax? a) => a?.Body == null && a?.ExpressionBody == null;
private static bool IsAutoProperty(PropertyDeclarationSyntax p) => p.AccessorList != null && p.AccessorList.Accessors.All(a => a.Body == null && a.ExpressionBody == null);
private static bool IsEncodingType(ITypeSymbol type) { for (var t = type; t != null; t = t.BaseType) if (t.ToDisplayString() == "System.Text.Encoding") return true; return false; }
private static string? YieldElementType(string t) {
var match = System.Text.RegularExpressions.Regex.Match(t, @"^(?:Iterable|Iterator|List|ArrayList|Collection|IEnumerable|CSharpGenericIterable|CSharpGenericEnumerator|CSharpICollection|CSharpGenericIList|CSharpList|CSharpEnumerator)<(.+)>$");
return match.Success ? match.Groups[1].Value : null; }
private static bool NeedsBoxedInterfaceReturn(IPropertySymbol property)
{
// Only value-type implementations can require boxing.
if (property.Type.IsReferenceType) return false;
var containing = property.ContainingType;
if (containing == null) return false;
foreach (var iface in containing.AllInterfaces)
{
foreach (var member in iface.GetMembers())
{
if (member is not IPropertySymbol interfaceProperty) continue;
var impl = containing.FindImplementationForInterfaceMember(interfaceProperty);
if (impl == null
|| (!SymbolEqualityComparer.Default.Equals(impl, property)
&& !SymbolEqualityComparer.Default.Equals(impl, property.OriginalDefinition)))
continue;
// A generic interface member (e.g. IEnumerator<T>.Current, whose original
// type is the type parameter T) maps to a Java generic return T that erases
// to a reference type (Integer when instantiated); a value-type implementation
// must declare the boxed return type to satisfy the override. Non-generic
// members such as ICollection.IsSynchronized (bool) map to boolean and must
// keep their primitive return type.
if (interfaceProperty.OriginalDefinition.Type is ITypeParameterSymbol)
return true;
}
}
return false;
}
private static string BoxJavaPrimitive(string typeName) => typeName switch
{
"int" => "Integer", "long" => "Long", "short" => "Short", "byte" => "Byte",
"float" => "Float", "double" => "Double", "char" => "Character",
"boolean" => "Boolean", _ => typeName
};
private static bool IsHiding(ISymbol? symbol) {
if (symbol is not IPropertySymbol p || p.IsOverride || p.IsStatic) return false;
for (var bt = p.ContainingType.BaseType; bt != null; bt = bt.BaseType) foreach (var m in bt.GetMembers(p.Name))
if (m.DeclaredAccessibility != Accessibility.Private && m is IPropertySymbol bp && SymbolEqualityComparer.Default.Equals(p.Type, bp.Type)) return true;
return false; }  private static bool IsPureBaseDelegation(PropertyDeclarationSyntax p) { if (p.AccessorList == null) return false;
var get = p.AccessorList.Accessors.FirstOrDefault(a => a.IsKind(GetAccessorDeclaration));
var set = p.AccessorList.Accessors.FirstOrDefault(a => a.IsKind(SetAccessorDeclaration) || a.IsKind(InitAccessorDeclaration));
return (get == null || ReadsBase(get, p.Identifier.Text)) && (set == null || WritesBase(set, p.Identifier.Text)); } 
private static AssignmentExpressionSyntax? SimpleAssign(ExpressionSyntax? e) => e is AssignmentExpressionSyntax a && a.IsKind(SimpleAssignmentExpression) ? a : null;
private static bool BaseAccess(MemberAccessExpressionSyntax m, string n) => m.Expression is BaseExpressionSyntax && m.Name.Identifier.Text == n;
private static bool ReadsBase(AccessorDeclarationSyntax a, string n) =>
(a.ExpressionBody?.Expression is MemberAccessExpressionSyntax m && BaseAccess(m, n)) ||
(a.Body?.Statements.Count == 1 && a.Body.Statements[0] is ReturnStatementSyntax { Expression: MemberAccessExpressionSyntax m2 } && BaseAccess(m2, n));
private static bool WritesBase(AccessorDeclarationSyntax a, string n) {
if (SimpleAssign(a.ExpressionBody?.Expression) is { } x && x.Right is IdentifierNameSyntax { Identifier: { Text: "value" } }
&& x.Left is MemberAccessExpressionSyntax m && BaseAccess(m, n)) return true;
return a.Body?.Statements.Count == 1 && a.Body.Statements[0] is ExpressionStatementSyntax { Expression: var e }
&& SimpleAssign(e) is { } y && y.Right is IdentifierNameSyntax { Identifier: { Text: "value" } }
&& y.Left is MemberAccessExpressionSyntax m2 && BaseAccess(m2, n); } 
private static void InitDefault(JavaFieldDeclaration field, PropertyDeclarationSyntax p, IPropertySymbol? sym, TypeInfo typeInfo, string propType, string fieldName, bool isStatic, bool needsField, ConversionContext ctx)
{ if (!needsField || p.Initializer != null) return; if (typeInfo.Type?.SpecialType == SpecialType.System_Decimal)
{ ctx.AddImport("io.github.ningpp.compat.Decimal"); field.Initializer = "Decimal.ZERO"; }
else if (StructCloneHelper.IsUserDefinedStruct(typeInfo.Type)) {
field.Initializer = $"new {propType}()"; } else if (sym?.Type is INamedTypeSymbol { TypeKind: TypeKind.Enum } enumType) {
field.Initializer = $"{ctx.MapType(enumType)}.values()[0]"; } } 
private static void InitExpression(JavaFieldDeclaration field, PropertyDeclarationSyntax p, IPropertySymbol? sym, string fieldName, bool isStatic, ConversionContext ctx)
{ field.Initializer = Expr(p.Initializer!.Value, ctx); if (sym?.Type is INamedTypeSymbol iter
&& (iter.OriginalDefinition?.ToDisplayString() == "System.Collections.Generic.IEnumerable<T>" || iter.ToDisplayString() == "System.Collections.IEnumerable")
&& ctx.SemanticModel != null && ctx.GetTypeInfo(p.Initializer.Value).Type is IArrayTypeSymbol && ctx.HasPendingPreStatements) {
var stmts = ctx.DrainBranchScopedPreStatements().Concat(ctx.DrainPreStatements()).ToList();
stmts.Add($"{(isStatic ? fieldName : $"this.{fieldName}")} = {field.Initializer};");
field.InitializerStatements = stmts; field.Initializer = null; } } 
private static void ApplyXml(PropertyDeclarationSyntax p, JavaFieldDeclaration field, ConversionContext ctx) => ApplyXmlAttributes(p.AttributeLists.SelectMany(l => l.Attributes), field, ctx);
/// <summary>
/// 把 [XmlAttribute]/[XmlIgnore]/[XmlArray]/[XmlArrayItem] 落成 compat 注解。属性与
/// 普通字段共用（真实链 serializer-tests 的 POCO：特性挂在 public 字段上，
/// 属性是 member-desugar 展开的 get_X/set_X 方法——只处理属性声明会让特性凭空消失，
/// XmlSerializer 于是把该字段当普通成员或整类序列化成空）。
/// </summary>
internal static void ApplyXmlAttributes(IEnumerable<AttributeSyntax> attributes, JavaFieldDeclaration field, ConversionContext ctx) {
foreach (var attr in attributes) { var info = ctx.GetSymbolInfo(attr);
var typeName = info.Symbol is IMethodSymbol ctor ? ctor.ContainingType?.ToDisplayString() : info.Symbol?.ContainingType?.ToDisplayString();
if (typeName == null) continue; var args = attr.ArgumentList?.Arguments;
var first = args is { Count: > 0 } ? args.Value[0].Expression.ToString() : null;
(string Ann, string Import, string Key)? mapped = typeName switch {
"System.Xml.Serialization.XmlAttributeAttribute" => ("XmlAttribute", "io.github.ningpp.compat.xml.XmlAttribute", "name"),
"System.Xml.Serialization.XmlIgnoreAttribute" => ("XmlIgnore", "io.github.ningpp.compat.xml.XmlIgnore", ""),
"System.Xml.Serialization.XmlArrayAttribute" => ("XmlArray", "io.github.ningpp.compat.xml.XmlArray", "elementName"),
"System.Xml.Serialization.XmlArrayItemAttribute" => ("XmlArrayItem", "io.github.ningpp.compat.xml.XmlArrayItem", "elementName"), _ => null
}; if (mapped == null) continue; ctx.AddImport(mapped.Value.Import); var annotation = new JavaAnnotation(mapped.Value.Ann);
if (first != null && mapped.Value.Key != "") annotation.Values[mapped.Value.Key] = first; field.Annotations.Add(annotation); } } 
private void AddGetterAnnotations(JavaMethodDeclaration m, IPropertySymbol? sym, TypeInfo typeInfo, ConversionContext ctx) {
if (sym == null) return; var attrs = sym.GetAttributes();
if (JavaNaming.IsIncompatibleTypeHidingProperty(sym)) AddAnnotation(m, $"CompatPropertyName(\"{sym.Name}\")", ctx);
if (attrs.Any(a => a.AttributeClass?.Name == "JsonExtensionDataAttribute")) AddAnnotation(m, "CompatJsonExtensionData", ctx);
if (attrs.FirstOrDefault(a => a.AttributeClass?.Name == "JsonIgnoreAttribute") is { } ignore)
{ var c = ignore.NamedArguments.FirstOrDefault(a => a.Key == "Condition").Value.Value; AddAnnotation(m, c is int v ? $"CompatJsonIgnore({v})" : "CompatJsonIgnore", ctx); }
if (attrs.FirstOrDefault(a => a.AttributeClass?.Name == "JsonNumberHandlingAttribute") is { ConstructorArguments.Length: > 0 } number
&& number.ConstructorArguments[0].Value != null) AddAnnotation(m, $"CompatJsonNumberHandling({number.ConstructorArguments[0].Value})", ctx);
if (typeInfo.Type is IArrayTypeSymbol { ElementType.SpecialType: SpecialType.System_SByte }) AddAnnotation(m, "CompatSByteArray", ctx);
if (attrs.FirstOrDefault(a => a.AttributeClass?.Name == "DebuggerBrowsableAttribute") is { ConstructorArguments: [{ Value: int state }] })
AddAnnotation(m, $"DebuggerBrowsable({state})", ctx);
if (attrs.Any(a => a.AttributeClass?.Name == "JsonIncludeAttribute")) AddAnnotation(m, "CompatJsonInclude", ctx);
if (attrs.FirstOrDefault(a => a.AttributeClass?.Name == "JsonPropertyNameAttribute") is { ConstructorArguments: [{ Value: string jsonName }] })
AddAnnotation(m, $"CompatJsonPropertyName(\"{jsonName}\")", ctx);
if (TryGetJsonConverterType(sym, out var converter)) AddAnnotation(m, $"CompatJsonConverter({converter}.class)", ctx);
if (!IsPublicAccessor(sym.GetMethod) && !IsPublicAccessor(sym.SetMethod)) AddAnnotation(m, "CompatNonPublicProperty", ctx);
if (!HasJsonInclude(sym) && !IsPublicAccessor(sym.GetMethod)) AddAnnotation(m, "CompatNonPublicAccessor", ctx); } 
private static void AddAnnotation(JavaMethodDeclaration method, string text, ConversionContext ctx) {
var n = text; var i = n.IndexOf('('); if (i >= 0) n = n[..i];
method.Annotations.Add(new JavaAnnotation(text)); ctx.AddImport($"io.github.ningpp.compat.{n}"); } 
private static bool IsBareRead(string expr) { if (string.IsNullOrWhiteSpace(expr)) return false; var t = expr.Trim();
return t.EndsWith(".value", StringComparison.Ordinal) || t.Split('.').All(IsIdentifierSegment); }
private static bool IsIdentifierSegment(string s) => s.Length > 0 && (char.IsLetter(s[0]) || s[0] == '_' || s[0] == '$') && s.All(c => char.IsLetterOrDigit(c) || c == '_' || c == '$');
private static bool IsPublicAccessor(IMethodSymbol? a) => a?.DeclaredAccessibility == Accessibility.Public;
private static bool HasJsonInclude(IPropertySymbol p) => p.GetAttributes().Any(a => a.AttributeClass?.Name == "JsonIncludeAttribute"); 
internal static bool TryGetJsonConverterType(ISymbol? member, out string converterTypeName) {
converterTypeName = string.Empty; if (member == null) return false; foreach (var attr in member.GetAttributes())
for (var c = attr.AttributeClass; c != null; c = c.BaseType) { if (c.Name != "JsonConverterAttribute") continue;
foreach (var arg in attr.ConstructorArguments) if (arg.Value is INamedTypeSymbol t) { converterTypeName = t.Name; return true; }
if (TryGetConverterFromInitializer(attr.AttributeClass, out converterTypeName)) return true; } return false; } 
private static bool TryGetConverterFromInitializer(INamedTypeSymbol? attrClass, out string converterTypeName) {
converterTypeName = string.Empty; if (attrClass == null) return false; foreach (var reference in attrClass.DeclaringSyntaxReferences)
if (reference.GetSyntax() is TypeDeclarationSyntax type) foreach (var ctor in type.Members.OfType<ConstructorDeclarationSyntax>())
if (ctor.Initializer != null && ctor.Initializer.ThisOrBaseKeyword.IsKind(BaseKeyword))
foreach (var arg in ctor.Initializer.ArgumentList.Arguments) {
if (arg.Expression.IsKind(NullLiteralExpression)) { converterTypeName = "Void"; return true; }
if (arg.Expression is TypeOfExpressionSyntax typeOf) { converterTypeName = typeOf.Type.ToString();
var dot = converterTypeName.LastIndexOf('.'); if (dot >= 0) converterTypeName = converterTypeName[(dot + 1)..];
return converterTypeName.Length > 0; } } return false; } }
