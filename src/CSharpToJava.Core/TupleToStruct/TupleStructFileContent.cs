using System.Text;
using System.Text.RegularExpressions;

namespace CSharpToJava.Core.TupleToStruct;

/// <summary>
/// 生成共享的元组 struct 文件（写到中间源码树根目录，经 Compile Include + Link
/// 挂到每个编译了被改写源文件的项目）。文件内容刻意只使用最保守的 C# 结构
/// （struct、可变字段、构造器、Deconstruct、Equals/GetHashCode/ToString），
/// 保证其自身能被后续流水线阶段与转换器正确处理。
/// struct 刻意声明为可变（非 readonly、字段无 readonly）：System.ValueTuple
/// 本身就是可变值类型，源码中的字段赋值（t.Item1 = x）、复合赋值（--t.Item2）
/// 与 ref/out 传递（ref t.Item1）必须保持合法；生成 readonly struct 会把这些
/// 站点打成 CS0191/CS0192。
/// </summary>
internal static partial class TupleStructFileContent
{
    [GeneratedRegex(@"\{(\d+)\}")]
    private static partial Regex SlotRegex();

    public static string Generate(IReadOnlyList<TupleShape> shapes, string namespaceName)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("//   Generated by the cs2j tuple-to-struct preprocessor.");
        sb.AppendLine("//   One mutable struct per distinct tuple shape; element order matches");
        sb.AppendLine("//   ValueTuple layout (8+ tuples nest via Rest).");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("#nullable disable");
        sb.AppendLine($"namespace {namespaceName}");
        sb.AppendLine("{");
        foreach (var shape in shapes)
        {
            AppendStruct(sb, shape, namespaceName);
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void AppendStruct(StringBuilder sb, TupleShape shape, string namespaceName)
    {
        var selfRef = QualifiedName(namespaceName, shape.Name, shape.GenericArity, "__P");
        var genericParams = shape.GenericArity > 0
            ? "<" + string.Join(", ", Enumerable.Range(0, shape.GenericArity).Select(i => $"__P{i}")) + ">"
            : string.Empty;

        // 元素类型含 internal/嵌套非公开类型时必须是 internal struct，否则 C# 报
        // CS0052/CS0051（字段/方法参数的可访问性高于类型本身）。
        var accessibility = shape.IsPubliclyAccessible ? "public" : "internal";

        sb.AppendLine();
        sb.Append("    ").Append(accessibility).Append(" struct ")
            .Append(shape.Name).Append(genericParams)
            .Append(" : global::System.IEquatable<").Append(selfRef).AppendLine(">");
        sb.AppendLine("    {");

        var fieldCount = Math.Min(shape.Arity, 7);
        var hasTail = shape.Arity > 7;

        // ---- 字段（可变：镜像 System.ValueTuple 的 public 字段）----
        for (var i = 0; i < fieldCount; i++)
        {
            sb.Append("        public ")
                .Append(RenderFieldType(shape, i))
                .Append(" Item").Append(i + 1).AppendLine(";");
        }

        if (hasTail)
        {
            sb.Append("        public ")
                .Append(RenderTailFieldType(shape))
                .AppendLine(" Rest;");
        }

        // ---- 构造器 ----
        sb.AppendLine();
        sb.Append("        public ").Append(shape.Name).Append('(');
        var ctorParams = new List<string>();
        for (var i = 0; i < fieldCount; i++)
        {
            ctorParams.Add(RenderFieldType(shape, i) + " item" + (i + 1));
        }

        if (hasTail)
        {
            ctorParams.Add(RenderTailFieldType(shape) + " rest");
        }

        sb.Append(string.Join(", ", ctorParams)).AppendLine(")");
        sb.AppendLine("        {");
        for (var i = 0; i < fieldCount; i++)
        {
            sb.Append("            Item").Append(i + 1).Append(" = item").Append(i + 1).AppendLine(";");
        }

        if (hasTail)
        {
            sb.AppendLine("            Rest = rest;");
        }

        sb.AppendLine("        }");

        // ---- Deconstruct（扁平化全部逻辑元素）----
        var flattened = FlattenElements(shape).ToList();
        sb.AppendLine();
        sb.Append("        public void Deconstruct(");
        var outParams = flattened
            .Select((e, i) => "out " + RenderTemplate(e.Display, shape) + " item" + (i + 1))
            .ToList();
        sb.Append(flattened.Count == 0
            ? string.Join("", outParams)
            : string.Join(", ", outParams));
        sb.AppendLine(")");
        sb.AppendLine("        {");
        for (var i = 0; i < flattened.Count; i++)
        {
            sb.Append("            item").Append(i + 1).Append(" = ")
                .Append(FlattenedAccess(flattened[i].Path)).AppendLine(";");
        }

        sb.AppendLine("        }");

        // ---- Equals ----
        sb.AppendLine();
        sb.Append("        public global::System.Boolean Equals(").Append(selfRef).AppendLine(" other)");
        sb.AppendLine("        {");
        sb.Append("            return ");
        var equalityFields = new List<string>();
        for (var i = 0; i < fieldCount; i++)
        {
            equalityFields.Add(EqualExpr(RenderFieldType(shape, i), "Item" + (i + 1)));
        }

        if (hasTail)
        {
            equalityFields.Add(EqualExpr(RenderTailFieldType(shape), "Rest"));
        }

        if (equalityFields.Count == 0)
        {
            sb.Append("true");
        }
        else
        {
            sb.Append(string.Join($"{Environment.NewLine}                && ", equalityFields));
        }

        sb.AppendLine(";");
        sb.AppendLine("        }");

        sb.AppendLine();
        sb.AppendLine("        public override global::System.Boolean Equals(global::System.Object obj)");
        sb.AppendLine("        {");
        sb.Append("            return obj is ").Append(selfRef).AppendLine(" other && Equals(other);");
        sb.AppendLine("        }");

        // ---- GetHashCode ----
        sb.AppendLine();
        sb.AppendLine("        public override global::System.Int32 GetHashCode()");
        sb.AppendLine("        {");
        sb.AppendLine("            global::System.Int32 hash = 17;");
        for (var i = 0; i < fieldCount; i++)
        {
            sb.Append("            hash = hash * 31 + ")
                .Append(HashExpr(RenderFieldType(shape, i), "Item" + (i + 1)))
                .AppendLine(";");
        }

        if (hasTail)
        {
            sb.Append("            hash = hash * 31 + ")
                .Append(HashExpr(RenderTailFieldType(shape), "Rest"))
                .AppendLine(";");
        }

        sb.AppendLine("            return hash;");
        sb.AppendLine("        }");

        // ---- ToString ----
        sb.AppendLine();
        sb.AppendLine("        public override global::System.String ToString()");
        sb.AppendLine("        {");
        sb.Append("            return ");
        if (flattened.Count == 0)
        {
            sb.Append("\"()\"");
        }
        else
        {
            sb.Append("\"(\"");
            for (var i = 0; i < flattened.Count; i++)
            {
                if (i > 0)
                {
                    sb.Append(" + \", \"");
                }

                sb.Append(" + ").Append(FlattenedAccess(flattened[i].Path));
            }

            sb.Append(" + \")\"");
        }

        sb.AppendLine(";");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
    }

    private static string EqualExpr(string fieldType, string field) =>
        $"global::System.Collections.Generic.EqualityComparer<{fieldType}>.Default.Equals({field}, other.{field})";

    private static string HashExpr(string fieldType, string field) =>
        $"global::System.Collections.Generic.EqualityComparer<{fieldType}>.Default.GetHashCode({field})";

    private static string QualifiedName(
        string namespaceName,
        string structName,
        int genericArity,
        string paramPrefix) =>
        "global::" + namespaceName + "." + structName +
        (genericArity > 0
            ? "<" + string.Join(", ", Enumerable.Range(0, genericArity).Select(i => paramPrefix + i)) + ">"
            : string.Empty);

    /// <summary>struct 自身泛型参数替换：{slot} → __P{slot}。</summary>
    private static string RenderTemplate(string template, TupleShape shape) =>
        SlotRegex().Replace(template, m => "__P" + m.Groups[1].Value);

    private static string RenderFieldType(TupleShape shape, int elementIndex)
    {
        var element = shape.Elements[elementIndex];
        if (element.IsTuple)
        {
            return RenderNestedInstantiation(element.NestedShape!, element.NestedArgSlots);
        }

        return RenderTemplate(element.FieldDisplayTemplate, shape);
    }

    private static string RenderTailFieldType(TupleShape shape)
        => RenderNestedInstantiation(shape.Tail!, shape.TailArgSlots);

    /// <summary>嵌套 struct 实例化：把嵌套局部槽位绑定到外层 __P 参数。</summary>
    private static string RenderNestedInstantiation(TupleShape nested, IReadOnlyList<int> argSlots)
    {
        if (nested.GenericArity == 0)
        {
            return nested.Name;
        }

        var args = Enumerable.Range(0, nested.GenericArity)
            .Select(i => i < argSlots.Count ? "__P" + argSlots[i] : "__P0");
        return nested.Name + "<" + string.Join(", ", args) + ">";
    }

    private sealed record FlattenedElement(string Display, IReadOnlyList<string> Path);

    /// <summary>
    /// 扁平化全部逻辑元素（嵌套元组展开），Display 中统一使用外层 struct 的槽位。
    /// </summary>
    private static IEnumerable<FlattenedElement> FlattenElements(
        TupleShape shape,
        IReadOnlyList<string>? prefix = null)
    {
        for (var i = 0; i < shape.Arity; i++)
        {
            var path = (prefix ?? Array.Empty<string>())
                .Concat(TupleModelAccess.ItemAccessPath(shape, i + 1))
                .ToArray();
            var element = shape.Elements[i];
            if (element.IsTuple)
            {
                foreach (var sub in FlattenElements(element.NestedShape!, path))
                {
                    yield return sub with
                    {
                        Display = SubstituteSlots(sub.Display, element.NestedArgSlots),
                    };
                }
            }
            else
            {
                yield return new FlattenedElement(element.FieldDisplayTemplate, path);
            }
        }
    }

    private static string SubstituteSlots(string template, IReadOnlyList<int> mapping) =>
        SlotRegex().Replace(template, m =>
        {
            var slot = int.Parse(m.Groups[1].Value);
            return slot < mapping.Count ? "{" + mapping[slot] + "}" : m.Value;
        });

    private static string FlattenedAccess(IReadOnlyList<string> path) =>
        path.Count == 0 ? "this" : string.Join(".", path);
}
