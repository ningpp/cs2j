using System.Text;
using System.Text.RegularExpressions;

namespace CSharpToJava.Core.AnonymousTypeLift;

/// <summary>
/// 生成共享的匿名形状 class 文件（写到中间源码树根目录，经 Compile Include + Link
/// 挂到每个编译了被改写源文件的项目）。
///
/// 每个形状生成一个 internal sealed class，成员顺序固定：
/// 只读自动属性 → 全参构造器 → override Equals → override GetHashCode → override
/// ToString（设计 D1/D5/D6/D7）。刻意只使用最保守的 C# 子集（is 模式、
/// EqualityComparer、String.Concat、整数字面量），禁止 LINQ/插值字符串 handler/
/// switch 表达式，保证其自身能被后续流水线阶段处理。
/// </summary>
internal static partial class AnonymousTypeFileContent
{
    [GeneratedRegex(@"\{(\d+)\}")]
    private static partial Regex SlotRegex();

    public static string Generate(IReadOnlyList<AnonymousShape> shapes, string namespaceName)
    {
        // 输出前按 shape.Key 排序，保证多文件/多运行的生成内容字节级稳定（D2）。
        var ordered = shapes.OrderBy(s => s.Key, StringComparer.Ordinal).ToList();

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("//   Generated by the cs2j anonymous-type-lift preprocessor.");
        sb.AppendLine("//   One internal sealed immutable class per distinct anonymous shape.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("#nullable disable");
        sb.AppendLine($"namespace {namespaceName}");
        sb.AppendLine("{");
        foreach (var shape in ordered)
        {
            AppendClass(sb, shape, namespaceName);
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void AppendClass(StringBuilder sb, AnonymousShape shape, string namespaceName)
    {
        var genericParameters = shape.GenericArity > 0
            ? "<" + string.Join(", ", Enumerable.Range(0, shape.GenericArity).Select(i => $"__P{i}")) + ">"
            : string.Empty;

        var propertyTypes = shape.Properties
            .Select(p => RenderPropertyType(p))
            .ToArray();
        var parameterNames = BuildCtorParameterNames(shape);

        sb.AppendLine();
        sb.AppendLine("    [global::System.CodeDom.Compiler.GeneratedCode(\"cs2j-anonymous-type-lift\", \"1.0\")]");
        sb.AppendLine("    [global::System.Runtime.CompilerServices.CompilerGenerated]");
        sb.Append("    internal sealed class ").Append(shape.Name).AppendLine(genericParameters);

        foreach (var clause in RenderConstraintClauses(shape))
        {
            sb.Append("        ").AppendLine(clause);
        }

        sb.AppendLine("    {");

        // ---- 只读自动属性（零属性形状也合法）----
        for (var i = 0; i < shape.Properties.Count; i++)
        {
            sb.Append("        public ")
                .Append(propertyTypes[i])
                .Append(' ')
                .Append(shape.Properties[i].Name)
                .AppendLine(" { get; }");
        }

        // ---- 全参构造器 ----
        sb.AppendLine();
        sb.Append("        public ").Append(shape.Name).Append('(');
        sb.Append(string.Join(", ", shape.Properties.Select((p, i) =>
            propertyTypes[i] + " " + parameterNames[i])));
        sb.AppendLine(")");
        sb.AppendLine("        {");
        for (var i = 0; i < shape.Properties.Count; i++)
        {
            sb.Append("            ").Append(shape.Properties[i].Name)
                .Append(" = ").Append(parameterNames[i]).AppendLine(";");
        }

        sb.AppendLine("        }");

        // 自引用全限定名：泛型时带 <__P0, …>；is 精确运行时类型保证不同形状永不等（D5）。
        var selfReference = "global::" + namespaceName + "." + shape.Name + genericParameters;

        AppendEquals(sb, shape, propertyTypes, selfReference);
        AppendGetHashCode(sb, shape, propertyTypes);
        AppendToString(sb, shape);

        sb.AppendLine("    }");
    }

    /// <summary>
    /// Equals（D5）：<c>obj is 全限定自身类型 other &amp;&amp; EqualityComparer&lt;P&gt;
    /// .Default.Equals(P, other.P) &amp;&amp; …</c>，逐属性按声明顺序；零属性形状只保留
    /// 精确类型检查。绝不生成 IEquatable&lt;T&gt;、==/!= 运算符。
    /// </summary>
    private static void AppendEquals(
        StringBuilder sb,
        AnonymousShape shape,
        IReadOnlyList<string> propertyTypes,
        string selfReference)
    {
        sb.AppendLine();
        sb.AppendLine("        public override global::System.Boolean Equals(global::System.Object obj)");
        sb.AppendLine("        {");
        sb.Append("            return obj is ").Append(selfReference).Append(" other");
        for (var i = 0; i < shape.Properties.Count; i++)
        {
            sb.Append(" && global::System.Collections.Generic.EqualityComparer<")
                .Append(propertyTypes[i])
                .Append(">.Default.Equals(")
                .Append(shape.Properties[i].Name)
                .Append(", other.")
                .Append(shape.Properties[i].Name)
                .Append(')');
        }

        sb.AppendLine(";");
        sb.AppendLine("        }");
    }

    /// <summary>
    /// GetHashCode（D6）：固定种子 17、逐字段 <c>hash = hash * 31 +
    /// EqualityComparer&lt;P&gt;.Default.GetHashCode(P)</c>；零属性形状直接返回 17。
    /// 与 E06 生成 struct 同一算法。
    /// </summary>
    private static void AppendGetHashCode(
        StringBuilder sb,
        AnonymousShape shape,
        IReadOnlyList<string> propertyTypes)
    {
        sb.AppendLine();
        sb.AppendLine("        public override global::System.Int32 GetHashCode()");
        sb.AppendLine("        {");
        if (shape.Properties.Count == 0)
        {
            sb.AppendLine("            return 17;");
        }
        else
        {
            sb.AppendLine("            global::System.Int32 hash = 17;");
            for (var i = 0; i < shape.Properties.Count; i++)
            {
                sb.Append("            hash = hash * 31 + ")
                    .Append("global::System.Collections.Generic.EqualityComparer<")
                    .Append(propertyTypes[i])
                    .Append(">.Default.GetHashCode(")
                    .Append(shape.Properties[i].Name)
                    .AppendLine(");");
            }

            sb.AppendLine("            return hash;");
        }

        sb.AppendLine("        }");
    }

    /// <summary>
    /// ToString（D7）：<c>String.Concat("{ P0 = ", P0, ", P1 = ", P1, " }")</c>。
    /// params object?[] 重载的 null→空串语义精确匹配 C# 匿名类型；值类型实参由重载
    /// 正常装箱，嵌套形状递归自然命中其 ToString。零属性形状返回 "{ }"。
    /// </summary>
    private static void AppendToString(StringBuilder sb, AnonymousShape shape)
    {
        sb.AppendLine();
        sb.AppendLine("        public override global::System.String ToString()");
        sb.AppendLine("        {");
        if (shape.Properties.Count == 0)
        {
            sb.AppendLine("            return \"{ }\";");
        }
        else
        {
            sb.Append("            return global::System.String.Concat(");
            for (var i = 0; i < shape.Properties.Count; i++)
            {
                if (i > 0)
                {
                    sb.Append(", ");
                }

                var name = shape.Properties[i].Name;
                sb.Append("\"").Append(i == 0 ? "{ " : ", ").Append(name).Append(" = \", ")
                    .Append(name);
            }

            sb.AppendLine(", \" }\");");
        }

        sb.AppendLine("        }");
    }

    /// <summary>
    /// 逐形状渲染 where 子句：class/struct/unmanaged/notnull 在前，其次约束类型
    /// 模板（{slot} → __P），new() 最后；无约束的形参不输出子句。
    /// </summary>
    private static IEnumerable<string> RenderConstraintClauses(AnonymousShape shape)
    {
        foreach (var constraint in shape.Constraints)
        {
            var tokens = new List<string>();
            if (constraint.HasClass)
            {
                tokens.Add("class");
            }

            if (constraint.HasStruct)
            {
                tokens.Add("struct");
            }

            if (constraint.HasUnmanaged)
            {
                tokens.Add("unmanaged");
            }

            if (constraint.HasNotNull)
            {
                tokens.Add("notnull");
            }

            tokens.AddRange(constraint.ConstraintTypeTemplates.Select(RenderTemplate));

            if (constraint.HasNew)
            {
                tokens.Add("new()");
            }

            if (tokens.Count > 0)
            {
                yield return "where __P" + constraint.Slot + " : " + string.Join(", ", tokens);
            }
        }
    }

    /// <summary>class 自身泛型参数替换：{slot} → __P{slot}。</summary>
    private static string RenderTemplate(string template) =>
        SlotRegex().Replace(template, m => "__P" + m.Groups[1].Value);

    private static string RenderPropertyType(AnonymousPropertySpec property)
    {
        if (property.IsAnonymous)
        {
            return RenderNestedInstantiation(property.NestedShape!, property.NestedArgSlots);
        }

        return RenderTemplate(property.DisplayTemplate);
    }

    /// <summary>嵌套 class 实例化：把嵌套局部槽位绑定到外层 __P 参数。</summary>
    private static string RenderNestedInstantiation(AnonymousShape nested, IReadOnlyList<int> argSlots)
    {
        if (nested.GenericArity == 0)
        {
            return nested.Name;
        }

        var args = Enumerable.Range(0, nested.GenericArity)
            .Select(i => i < argSlots.Count ? "__P" + argSlots[i] : "__P0");
        return nested.Name + "<" + string.Join(", ", args) + ">";
    }

    /// <summary>
    /// 构造参数名 = 属性名首字母小写（ToCamel）；与属性名、类型形参 __P{i} 或先
    /// 前参数碰撞时追加下划线并在声明空间内探测（D16，确定性）。
    /// </summary>
    private static IReadOnlyList<string> BuildCtorParameterNames(AnonymousShape shape)
    {
        var taken = new HashSet<string>(StringComparer.Ordinal);
        foreach (var property in shape.Properties)
        {
            taken.Add(property.Name);
        }

        for (var i = 0; i < shape.GenericArity; i++)
        {
            taken.Add("__P" + i);
        }

        var result = new List<string>(shape.Properties.Count);
        foreach (var property in shape.Properties)
        {
            var candidate = ToCamelCase(property.Name);
            while (!taken.Add(candidate))
            {
                candidate += "_";
            }

            result.Add(candidate);
        }

        return result;
    }

    private static string ToCamelCase(string name)
    {
        if (name.Length == 0)
        {
            return name;
        }

        return char.ToLowerInvariant(name[0]) + name[1..];
    }
}
