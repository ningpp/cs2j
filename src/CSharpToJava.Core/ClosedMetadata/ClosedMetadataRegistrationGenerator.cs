using System.Text;

namespace CSharpToJava.Core.ClosedMetadata;

/// <summary>
/// Generates the per-project closed-type registration file (design D6 / A1 bootstrap):
/// one deterministic bootstrap method plus a self-contained, lock-guarded registry
/// class. The registry is pure C# — it references no Java/compat names; mapping the
/// registration calls to compat <c>TypeHelper.registerClosedType</c> is the converter's
/// D2 contract and lands in a separate PR. Records arrive already deduplicated and
/// key-sorted, so the emitted registration order is a deterministic snapshot
/// (CM-REG: never enumeration order).
/// </summary>
public static class ClosedMetadataRegistrationGenerator
{
    public const string GeneratedFileStem = "_Cs2jClosedTypes";

    public const string BootstrapMethodName = "__cs2j_register_closed_types";

    public const string RegistryTypePrefix = "__Cs2jClosedTypes_";

    private const string RegisterCallPrefix = "__cs2j_register_closed(\"";

    private const string CompilerGeneratedAttributeName =
        "global::System.Runtime.CompilerServices.CompilerGenerated";

    /// <summary>
    /// Holder type name for a project. The holder is <b>public</b> because CM-LINK
    /// guards in consumer projects (D8 serializer entry sites, D6 reach-through-project
    /// references) invoke the bootstrap across assembly boundaries. Project file names
    /// may contain characters illegal in C# identifiers (e.g. dashes), so everything
    /// outside [A-Za-z0-9_] collapses to '_'. The linker derives the exact same name
    /// through this method — never by raw concatenation.
    /// </summary>
    public static string HolderTypeName(string projectName)
        => RegistryTypePrefix + SanitizeIdentifier(projectName);

    private static string SanitizeIdentifier(string name)
    {
        var chars = name.ToCharArray();
        for (var i = 0; i < chars.Length; i++)
        {
            var c = chars[i];
            var ok = c is (>= 'a' and <= 'z') or (>= 'A' and <= 'Z') or (>= '0' and <= '9') or '_';
            if (!ok)
            {
                chars[i] = '_';
            }
        }

        var sanitized = new string(chars);
        return sanitized.Length > 0 && char.IsDigit(sanitized[0]) ? "_" + sanitized : sanitized;
    }

    public static string Generate(string projectName, IReadOnlyList<ClosedTypeRecord> records)
    {
        var holderTypeName = HolderTypeName(projectName);
        var sb = new StringBuilder();
        sb.AppendLine($"// <auto-generated> cs2j closed-metadata (C30) closed-type registration for {projectName}. Do not edit.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine($"[{CompilerGeneratedAttributeName}]");
        sb.AppendLine($"public static class {holderTypeName}");
        sb.AppendLine("{");
        sb.AppendLine("    private static readonly object __cs2j_gate = new object();");
        sb.AppendLine("    private static readonly global::System.Collections.Generic.Dictionary<string, global::System.Type> __cs2j_registered =");
        sb.AppendLine("        new global::System.Collections.Generic.Dictionary<string, global::System.Type>();");
        sb.AppendLine("    private static bool __cs2j_bootstrapped;");
        sb.AppendLine();
        sb.AppendLine("    // Idempotent registration slot: one normalized key only ever lands once (putIfAbsent semantics).");
        sb.AppendLine("    private static void __cs2j_register_closed(string __cs2j_key, global::System.Type __cs2j_closed)");
        sb.AppendLine("    {");
        sb.AppendLine("        lock (__cs2j_gate)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (!__cs2j_registered.ContainsKey(__cs2j_key))");
        sb.AppendLine("            {");
        sb.AppendLine("                __cs2j_registered.Add(__cs2j_key, __cs2j_closed);");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    // Explicit bootstrap (D1/D6): invoked before the first serialization entry; Java has no <Module> initializer equivalent.");
        sb.AppendLine("    // Idempotent under repeated and concurrent entry (lock double-check, CM-LINK) — consumer sites call freely.");
        sb.AppendLine($"    public static void {BootstrapMethodName}()");
        sb.AppendLine("    {");
        sb.AppendLine("        if (__cs2j_bootstrapped)");
        sb.AppendLine("        {");
        sb.AppendLine("            return;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        lock (__cs2j_gate)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (__cs2j_bootstrapped)");
        sb.AppendLine("            {");
        sb.AppendLine("                return;");
        sb.AppendLine("            }");
        for (var i = 0; i < records.Count; i++)
        {
            sb.AppendLine($"            global::System.Type __cs2j_closed_{i} = typeof({records[i].TypeText});");
            sb.AppendLine($"            {RegisterCallPrefix}{EscapeKeyText(records[i].Key.SortText)}\", __cs2j_closed_{i});");
        }

        sb.AppendLine();
        sb.AppendLine("            __cs2j_bootstrapped = true;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string EscapeKeyText(string keyText)
        => keyText.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal);
}
