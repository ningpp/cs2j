using System.Text;
using CSharpToJava.Core.Java;

namespace CSharpToJava.Core.TypeScript.Rewriters;

/// <summary>
/// 类属性访问器重组角色（Task 16）：由 TsPropertyReconstructionRewriter 在发射前
/// 标记到方法上，TsTypeWriter.EmitClass 据此发射 TS 字段/访问器。
/// </summary>
public enum TsAccessorRole
{
    /// <summary>自动 get;set; 双访问器 → TS 字段（简化，访问器方法已从 IR 移除）</summary>
    Field,
    /// <summary>只读 getter（含表达式体属性、抽象 getter）→ TS getter 访问器</summary>
    Getter,
    /// <summary>getter + 受限 setter（private/protected）或抽象对 → TS getter + setter 访问器</summary>
    GetterSetter,
    /// <summary>只写属性（仅 setter）→ 维持方法发射 + 诊断注释</summary>
    WriteOnly,
}

/// <summary>
/// 属性访问器重组 rewriter（M2，Task 16 + 双审修复）：类自动属性 getX()/setX(value)
/// （PropertyTransformer 产出，IsAutoGenerated = true）重组为 TS 字段/访问器，并同步
/// 改写全部调用点。
///
/// 重组规则（以 IR 实测为准，见计划文档 Task 16 注记）：
/// - 自动 get;set; 双访问器（非表达式体、非 struct、非 override、有 camelCase 后备字段、
///   setter 非受限可见性）→ 字段简化：后备字段改名为属性名（PascalCase）、可见性取 getter、
///   访问器方法移除；
/// - 只读 { get; } / 表达式体 { get => expr; } → TS getter 访问器；
/// - getter + 受限 setter（private/protected，含表达式体对）→ TS getter + setter 访问器；
/// - 抽象访问器 → abstract get/set 访问器（与派生 override 访问器形态匹配，I4）；
/// - override 访问器不做字段简化（保持访问器对，与基类抽象/访问器形态匹配，I4）；
/// - 只写 { set; } → 维持方法发射 + 诊断注释（无 TS 对应形态）；
/// - 显式接口实现访问器 / 非自动生成方法 → 不重组（维持方法发射）。
/// 接口访问器（Task 15 已合并发射为 readonly/普通属性）：仅注册调用点改写名，不产生 roles。
///
/// 调用点改写覆盖两类形态：
/// - 结构化 IR（JavaMethodCallExpression 等表达式节点）；
/// - raw 文本（JavaRawStatement.Code、方法/构造器 Body 字符串、JavaRawExpression.Code、
///   字段初始化器、静态初始化块语句）——前端大部分语句以 Java 文本直通（Task 9 注记），
///   文本改写跳过字符串/字符字面量与注释。
/// 解析策略（C1 保守：宁可不改，不可误改合法代码）：
/// - 裸/this/super 调用 → 按当前类型 + 基类链解析（静态补类名.，实例补 this.；
///   super 落到 this，TS 无 super 属性访问 TS2855）；
/// - dot-target 调用 → 仅当目标类型可解析（方法参数/局部变量/当前类字段/类型名，见
///   ResolveIdentifierType）且该类型的上下文注册了该访问器名时才改写；无类型信息或
///   目标类型未注册 → 保持方法调用（用户方法与重建属性重名的场景不再误改）。
///
/// 访问器方法体额外做字段限定（P1/I5）：TS 类体内裸字段标识符非法（tsc TS2663，
/// "Did you mean the instance member 'this.x'?"），对当前类字段名的裸引用补 this./类名. 前缀；
/// 排除 setter 参数（value）与结构化局部变量（P1：参数与字段同名不得误限）。
/// </summary>
public sealed class TsPropertyReconstructionRewriter : JavaSyntaxRewriter
{
    private readonly Dictionary<JavaMethodDeclaration, TsAccessorRole> _roles = new();

    /// <summary>
    /// 访问器方法角色侧表。字段简化（Field）的方法已从 IR 移除但键保留（供测试/诊断）；
    /// 发射按 cls.Methods 迭代，已移除方法不参与。其余角色键为仍在 IR 中的方法节点。
    /// 接口访问器不进本表（发射由 TsTypeWriter.EmitInterface 的 Task 15 合并负责）。
    /// </summary>
    public IReadOnlyDictionary<JavaMethodDeclaration, TsAccessorRole> Roles => _roles;

    /// <summary>类节点 → 类上下文（节点键控，避免同名单类互串）。</summary>
    private readonly Dictionary<JavaClassDeclaration, ClassContext> _classContexts = new();
    /// <summary>接口节点 → 接口上下文（调用点改写用，不产生 roles）。</summary>
    private readonly Dictionary<JavaInterfaceDeclaration, ClassContext> _interfaceContexts = new();
    /// <summary>类型名 → 上下文（类 + 接口；基类链与 dot-target 类型解析；同名单类可能覆盖，L3 兜底）。</summary>
    private readonly Dictionary<string, ClassContext> _typeContextsByName = new(StringComparer.Ordinal);

    /// <summary>当前类型上下文栈（嵌套类型各自独立）。</summary>
    private readonly Stack<ClassContext> _classStack = new();
    /// <summary>当前方法上下文栈（参数/局部变量：目标类型解析 + 字段限定排除）。</summary>
    private readonly Stack<MethodContext> _methodStack = new();
    /// <summary>正在遍历访问器方法体（触发裸字段限定，P1/I5）。</summary>
    private bool _qualifyingAccessorBody;
    /// <summary>结构化 lambda 参数遮蔽栈（I8：lambda 参数与字段同名不得限定）。</summary>
    private readonly Stack<HashSet<string>> _shadowStack = new();
    /// <summary>本单元内被 override 的属性名集合（R1：继承参与的属性统一禁字段简化）。</summary>
    private readonly HashSet<string> _inheritedPropertyNames = new(StringComparer.Ordinal);

    /// <summary>
    /// 访问器注册信息：属性名/静态性/声明类型/角色（super 形态判定 R2）/属性类型（链式解析 C2）。
    /// </summary>
    private sealed record AccessorInfo(
        string PropertyName, bool IsStatic, string OwnerClassName, TsAccessorRole Role, string? Type);

    private sealed class ClassContext
    {
        public required string ClassName { get; init; }
        /// <summary>基类型名（类：ExtendedType；接口：ExtendedTypes 列表）。</summary>
        public required List<string> BaseTypeNames { get; init; }
        public required Dictionary<string, string> InstanceFieldTypes { get; init; }
        public required Dictionary<string, string> StaticFieldTypes { get; init; }
        /// <summary>本类型注册的访问器方法名集合（this./裸调用按当前类型 + 基类链解析）。</summary>
        public Dictionary<string, AccessorInfo> AccessorMap { get; } = new(StringComparer.Ordinal);
        /// <summary>本类型方法签名键（方法名 + 参数个数）→ 返回类型（R-2：链式调用段解析用户
        /// 方法返回类型；R-6：同名重载按参数个数消诧，同名同参个数的歧义重载不登记）。</summary>
        public Dictionary<string, string> MethodReturnTypes { get; } = new(StringComparer.Ordinal);
    }

    private sealed class MethodContext
    {
        /// <summary>参数 + 结构化局部变量名（字段限定排除集）。</summary>
        public required HashSet<string> NonFieldNames { get; init; }
        /// <summary>变量名 → 类型（dot-target 目标类型解析）。</summary>
        public required Dictionary<string, string> VariableTypes { get; init; }
    }

    // ─── 类型遍历 ─────────────────────────────────────────────────────

    public override JavaCompilationUnit VisitCompilationUnit(JavaCompilationUnit node)
    {
        // 两阶段：先全量分析（所有类/接口/嵌套类型的重组决策与注册），再遍历改写调用点。
        // 保证基类在派生类之后声明时，派生类内的裸调用也能解析到基类属性。
        foreach (var type in node.TypeDeclarations)
        {
            CollectInheritedPropertyNames(type);
        }
        foreach (var type in node.TypeDeclarations)
        {
            AnalyzeTypesRecursive(type);
        }
        return base.VisitCompilationUnit(node);
    }

    /// <summary>
    /// 收集本单元内全部 override 访问器的属性名（R1：基类 virtual 属性在 IR 中无 virtual
    /// 标记——PropertyTransformer 映射为 None——只能经派生 override 反向推断"继承参与"）。
    /// </summary>
    private void CollectInheritedPropertyNames(JavaTypeDeclaration type)
    {
        switch (type)
        {
            case JavaClassDeclaration cls:
                foreach (var method in cls.Methods)
                {
                    if ((method.Modifiers & JavaModifiers.Override) != 0 && IsAutoAccessorCandidate(method))
                    {
                        _inheritedPropertyNames.Add(method.Name.Substring(3));
                    }
                }
                foreach (var nested in cls.NestedTypes) CollectInheritedPropertyNames(nested);
                break;
            case JavaInterfaceDeclaration iface:
                foreach (var nested in iface.NestedTypes) CollectInheritedPropertyNames(nested);
                break;
        }
    }

    private void AnalyzeTypesRecursive(JavaTypeDeclaration type)
    {
        switch (type)
        {
            case JavaClassDeclaration cls:
                var context = CreateClassContext(cls.Name, BaseTypeNamesFor(cls), cls.Fields);
                _classContexts[cls] = context;
                _typeContextsByName[cls.Name] = context;
                RecordMethodReturnTypes(context, cls.Methods);
                AnalyzeClass(cls, context);
                foreach (var nested in cls.NestedTypes) AnalyzeTypesRecursive(nested);
                break;
            case JavaInterfaceDeclaration iface:
                var ifaceContext = CreateClassContext(iface.Name, iface.ExtendedTypes, iface.Fields);
                _interfaceContexts[iface] = ifaceContext;
                _typeContextsByName[iface.Name] = ifaceContext;
                RecordMethodReturnTypes(ifaceContext, iface.Methods);
                AnalyzeInterface(iface, ifaceContext);
                foreach (var nested in iface.NestedTypes) AnalyzeTypesRecursive(nested);
                break;
        }
    }

    private static List<string> SingleOrEmpty(string? value)
        => value == null ? new List<string>() : new List<string> { value };

    /// <summary>类上下文基类型名 = 基类 + 实现接口（R-1：接口属性经中间基类解析）。</summary>
    private static List<string> BaseTypeNamesFor(JavaClassDeclaration cls)
    {
        var names = SingleOrEmpty(cls.ExtendedType);
        foreach (var implemented in cls.ImplementedTypes)
        {
            if (!names.Contains(implemented, StringComparer.Ordinal)) names.Add(implemented);
        }
        return names;
    }

    /// <summary>登记方法签名键 → 返回类型（R-2；void/空返回不登记，链式解析无意义）。
    /// R-6：同名同参数个数的多个重载（仅参数类型不同）静态无法判定 → 移除键，调用点保守不改写
    /// （宁可不改不可误改）；同键同返回类型保留。</summary>
    private static void RecordMethodReturnTypes(ClassContext context, IEnumerable<JavaMethodDeclaration> methods)
    {
        foreach (var method in methods)
        {
            if (string.IsNullOrEmpty(method.ReturnType) || method.ReturnType == "void") continue;
            var key = MethodReturnKey(method.Name, method.Parameters.Count);
            if (!context.MethodReturnTypes.TryAdd(key, method.ReturnType))
            {
                if (context.MethodReturnTypes[key] != method.ReturnType)
                {
                    context.MethodReturnTypes.Remove(key);
                }
            }
        }
    }

    /// <summary>方法返回类型键 = 方法名 + 参数个数（R-6：同名重载不同返回类型不得互相覆盖）。</summary>
    private static string MethodReturnKey(string methodName, int argCount)
        => methodName + "(" + argCount + ")";

    private static ClassContext CreateClassContext(
        string name, List<string> baseTypes, List<JavaFieldDeclaration> fields)
    {
        var instance = new Dictionary<string, string>(StringComparer.Ordinal);
        var statics = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var field in fields)
        {
            var target = (field.Modifiers & JavaModifiers.Static) != 0 ? statics : instance;
            target[field.Name] = field.Type;
        }
        return new ClassContext
        {
            ClassName = name,
            BaseTypeNames = baseTypes,
            InstanceFieldTypes = instance,
            StaticFieldTypes = statics,
        };
    }

    public override JavaClassDeclaration VisitClassDeclaration(JavaClassDeclaration node)
    {
        // 复用分析阶段建立的上下文（含 AccessorMap 与字段集合；防御性兜底新建）
        if (!_classContexts.TryGetValue(node, out var context))
        {
            context = CreateClassContext(node.Name, BaseTypeNamesFor(node), node.Fields);
        }
        _classStack.Push(context);
        try
        {
            var result = base.VisitClassDeclaration(node);
            // JavaSyntaxRewriter 不遍历静态初始化块（TsTypeWriter 直接发射 Statements），
            // 这里补改其中的属性访问器调用
            foreach (var block in node.StaticInitializers)
            {
                for (var i = 0; i < block.Statements.Count; i++)
                {
                    block.Statements[i] = RewriteAccessorCalls(block.Statements[i]);
                }
            }
            return result;
        }
        finally
        {
            _classStack.Pop();
        }
    }

    public override JavaInterfaceDeclaration VisitInterfaceDeclaration(JavaInterfaceDeclaration node)
    {
        if (!_interfaceContexts.TryGetValue(node, out var context))
        {
            context = CreateClassContext(node.Name, node.ExtendedTypes, node.Fields);
        }
        _classStack.Push(context);
        try
        {
            return base.VisitInterfaceDeclaration(node);
        }
        finally
        {
            _classStack.Pop();
        }
    }

    public override JavaMethodDeclaration VisitMethodDeclaration(JavaMethodDeclaration node)
    {
        var methodContext = BuildMethodContext(node);
        var isAccessor = _roles.TryGetValue(node, out var role)
            && role is TsAccessorRole.Getter or TsAccessorRole.GetterSetter or TsAccessorRole.WriteOnly;
        _methodStack.Push(methodContext);
        var previousQualifying = _qualifyingAccessorBody;
        _qualifyingAccessorBody = isAccessor;
        try
        {
            node = base.VisitMethodDeclaration(node);

            // raw Body 字符串（表达式体/自动访问器等）同样可能含属性访问器调用；
            // 访问器方法体还额外做字段限定（TS2663；P1：排除参数/局部变量）。
            // 结构化 body 的语句/表达式在遍历中由 VisitRawStatement/VisitExpression 覆盖。
            if (!string.IsNullOrEmpty(node.Body))
            {
                node.Body = RewriteAccessorCalls(node.Body);
                if (isAccessor)
                {
                    node.Body = QualifyFieldReferences(node.Body);
                }
            }
            return node;
        }
        finally
        {
            _qualifyingAccessorBody = previousQualifying;
            _methodStack.Pop();
        }
    }

    public override JavaConstructorDeclaration VisitConstructorDeclaration(JavaConstructorDeclaration node)
    {
        var methodContext = new MethodContext
        {
            NonFieldNames = node.Parameters.Select(p => p.Name).ToHashSet(StringComparer.Ordinal),
            VariableTypes = node.Parameters.ToDictionary(p => p.Name, p => p.Type, StringComparer.Ordinal),
        };
        _methodStack.Push(methodContext);
        try
        {
            node = base.VisitConstructorDeclaration(node);
            if (!string.IsNullOrEmpty(node.Body))
            {
                node.Body = RewriteAccessorCalls(node.Body);
            }
            return node;
        }
        finally
        {
            _methodStack.Pop();
        }
    }

    public override JavaFieldDeclaration VisitFieldDeclaration(JavaFieldDeclaration node)
    {
        if (!string.IsNullOrEmpty(node.Initializer))
        {
            node.Initializer = RewriteAccessorCalls(node.Initializer);
        }
        return base.VisitFieldDeclaration(node);
    }

    public override JavaRawStatement VisitRawStatement(JavaRawStatement node)
    {
        if (!string.IsNullOrEmpty(node.Code))
        {
            node.Code = RewriteAccessorCalls(node.Code);
            if (_qualifyingAccessorBody)
            {
                node.Code = QualifyFieldReferences(node.Code);
            }
        }
        return base.VisitRawStatement(node);
    }

    public override JavaExpression VisitExpression(JavaExpression node)
    {
        if (node is JavaLambdaExpression lambda)
        {
            // I8：结构化 lambda 参数遮蔽字段——body 内同名标识符不得限定
            _shadowStack.Push(new HashSet<string>(lambda.Parameters, StringComparer.Ordinal));
            try
            {
                if (lambda.ExpressionBody != null)
                {
                    lambda.ExpressionBody = VisitExpression(lambda.ExpressionBody);
                }
                if (lambda.BlockBody != null)
                {
                    lambda.BlockBody = VisitBlockStatement(lambda.BlockBody);
                }
                return lambda;
            }
            finally
            {
                _shadowStack.Pop();
            }
        }
        if (node is JavaMethodCallExpression call)
        {
            call = base.VisitMethodCallExpression(call);
            return TryRewriteCall(call, out var replacement) ? replacement : call;
        }
        if (node is JavaIdentifierExpression ident && _qualifyingAccessorBody)
        {
            // 结构化语句中的裸字段引用 → this./类名. 前缀（TS2663）；排除参数/局部变量（P1/I5）
            return QualifyIdentifier(ident.Name) ?? ident;
        }
        if (node is JavaRawExpression raw)
        {
            raw.Code = RewriteAccessorCalls(raw.Code);
            if (_qualifyingAccessorBody)
            {
                raw.Code = QualifyFieldReferences(raw.Code);
            }
            return raw;
        }
        if (node is JavaMemberAccessExpression access)
        {
            access = base.VisitMemberAccessExpression(access);
            return access;
        }
        return base.VisitExpression(node);
    }

    // ─── 方法上下文（参数/局部变量收集） ───────────────────────────────

    private static MethodContext BuildMethodContext(JavaMethodDeclaration method)
    {
        var variables = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var parameter in method.Parameters)
        {
            variables[parameter.Name] = parameter.Type;
        }
        if (method.StructuredBody != null)
        {
            CollectStructuredLocals(method.StructuredBody.Statements, variables);
        }
        return new MethodContext
        {
            NonFieldNames = variables.Keys.ToHashSet(StringComparer.Ordinal),
            VariableTypes = variables,
        };
    }

    private static void CollectStructuredLocals(
        IReadOnlyList<JavaStatement> statements, Dictionary<string, string> variables)
    {
        foreach (var statement in statements)
        {
            switch (statement)
            {
                case JavaVariableDeclarationStatement declaration:
                    variables[declaration.Name] = declaration.Type;
                    break;
                case JavaForEachStatement forEach:
                    if (!string.IsNullOrEmpty(forEach.VariableName))
                        variables[forEach.VariableName] = forEach.VariableType;
                    CollectStructuredLocalsFromStatement(forEach.Body, variables);
                    break;
                case JavaBlockStatement block:
                    CollectStructuredLocals(block.Statements, variables);
                    break;
                case JavaIfStatement ifStatement:
                    CollectStructuredLocalsFromStatement(ifStatement.ThenBody, variables);
                    if (ifStatement.ElseBody != null)
                        CollectStructuredLocalsFromStatement(ifStatement.ElseBody, variables);
                    break;
                case JavaWhileStatement whileStatement:
                    CollectStructuredLocalsFromStatement(whileStatement.Body, variables);
                    break;
                case JavaDoWhileStatement doWhile:
                    CollectStructuredLocalsFromStatement(doWhile.Body, variables);
                    break;
                case JavaForStatement forStatement:
                    // I7：for-init 声明变量（含多声明）并入局部变量集，遮蔽字段不得限定
                    CollectForInitDeclarations(forStatement.Initializer, variables);
                    CollectStructuredLocalsFromStatement(forStatement.Body, variables);
                    break;
                case JavaTryCatchStatement tryCatch:
                    CollectStructuredLocals(tryCatch.TryBody.Statements, variables);
                    foreach (var catchClause in tryCatch.CatchClauses)
                    {
                        if (!string.IsNullOrEmpty(catchClause.VariableName))
                            variables[catchClause.VariableName] = catchClause.ExceptionType;
                        CollectStructuredLocals(catchClause.Body.Statements, variables);
                    }
                    if (tryCatch.FinallyBody != null)
                        CollectStructuredLocals(tryCatch.FinallyBody.Statements, variables);
                    break;
                case JavaSwitchStatement switchStatement:
                    foreach (var section in switchStatement.Sections)
                    {
                        CollectStructuredLocals(section.Statements, variables);
                    }
                    break;
            }
        }
    }

    private static void CollectStructuredLocalsFromStatement(
        JavaStatement statement, Dictionary<string, string> variables)
    {
        switch (statement)
        {
            case JavaBlockStatement block:
                CollectStructuredLocals(block.Statements, variables);
                break;
            case JavaVariableDeclarationStatement declaration:
                variables[declaration.Name] = declaration.Type;
                break;
            case JavaForEachStatement forEach:
                if (!string.IsNullOrEmpty(forEach.VariableName))
                    variables[forEach.VariableName] = forEach.VariableType;
                CollectStructuredLocalsFromStatement(forEach.Body, variables);
                break;
            case JavaIfStatement ifStatement:
                CollectStructuredLocalsFromStatement(ifStatement.ThenBody, variables);
                if (ifStatement.ElseBody != null)
                    CollectStructuredLocalsFromStatement(ifStatement.ElseBody, variables);
                break;
            case JavaWhileStatement whileStatement:
                CollectStructuredLocalsFromStatement(whileStatement.Body, variables);
                break;
            case JavaDoWhileStatement doWhile:
                CollectStructuredLocalsFromStatement(doWhile.Body, variables);
                break;
            case JavaForStatement forStatement:
                CollectStructuredLocalsFromStatement(forStatement.Body, variables);
                break;
            case JavaTryCatchStatement tryCatch:
                CollectStructuredLocals(tryCatch.TryBody.Statements, variables);
                foreach (var catchClause in tryCatch.CatchClauses)
                {
                    if (!string.IsNullOrEmpty(catchClause.VariableName))
                        variables[catchClause.VariableName] = catchClause.ExceptionType;
                    CollectStructuredLocals(catchClause.Body.Statements, variables);
                }
                if (tryCatch.FinallyBody != null)
                    CollectStructuredLocals(tryCatch.FinallyBody.Statements, variables);
                break;
            case JavaSwitchStatement switchStatement:
                foreach (var section in switchStatement.Sections)
                {
                    CollectStructuredLocals(section.Statements, variables);
                }
                break;
        }
    }

    // ─── for-init 声明解析（I7） ───────────────────────────────────────

    /// <summary>
    /// 提取 for-init 文本（"int i = 0, j = 1"）中的声明变量名，并入变量表
    /// （类型未知用 "var" 占位：链式类型解析查不到该类型时保守不改写）。
    /// </summary>
    private static void CollectForInitDeclarations(string? initializer, Dictionary<string, string> variables)
    {
        if (string.IsNullOrEmpty(initializer)) return;
        var declaredType = false;
        foreach (var segment in SplitTopLevelByComma(initializer))
        {
            // 多声明延续段（"int i = 0, j = 1" 的 j）无类型前缀：前一声明带类型时视为声明
            var name = TryParseDeclarationName(segment, out var hasType);
            if (name != null && (hasType || declaredType)) variables[name] = "var";
            declaredType |= hasType;
        }
    }

    /// <summary>按顶层逗号分段（跳过括号/尖括号/字符串）。</summary>
    private static IEnumerable<string> SplitTopLevelByComma(string text)
    {
        var depth = 0;
        var start = 0;
        for (var i = 0; i < text.Length; i++)
        {
            var ch = text[i];
            if (ch == '"' || ch == '\'')
            {
                i = SkipQuotedLiteral(text, i) - 1;
                continue;
            }
            switch (ch)
            {
                case '(':
                case '[':
                case '{':
                case '<':
                    depth++;
                    break;
                case ')':
                case ']':
                case '}':
                case '>':
                    if (depth > 0) depth--;
                    break;
                case ',' when depth == 0:
                    yield return text[start..i];
                    start = i + 1;
                    break;
            }
        }
        yield return text[start..];
    }

    /// <summary>
    /// 解析声明段文本提取变量名："int i = 0" → (i, true)；"j"（多声明延续）→ (j, false)；
    /// 支持限定类型名/泛型/数组类型。hasType 表示段首为类型声明（延续段是否收集由调用方
    /// 依据前序声明判定，避免把 for (j = 1; ...) 的赋值形态误当声明）。
    /// </summary>
    private static string? TryParseDeclarationName(string segment, out bool hasType)
    {
        hasType = false;
        var text = segment.Trim();
        if (text.Length == 0) return null;
        var i = 0;
        var first = ReadIdentifier(text, ref i);
        if (first == null) return null;
        SkipWhitespace(text, ref i);
        while (i < text.Length && (text[i] == '.' || text[i] == '<' || text[i] == '['))
        {
            if (text[i] == '.')
            {
                i++;
                ReadIdentifier(text, ref i);
            }
            else if (text[i] == '<')
            {
                i = SkipBalancedForward(text, i, '<', '>');
            }
            else
            {
                i = SkipBalancedForward(text, i, '[', ']');
            }
            SkipWhitespace(text, ref i);
        }
        var name = ReadIdentifier(text, ref i);
        if (name != null)
        {
            hasType = true;   // 段首为类型，第二标识符是变量名
            return name;
        }
        return first;         // 无类型：变量名（延续声明或赋值段，由调用方判定）
    }

    /// <summary>跳过空白后读取标识符；无标识符返回 null。</summary>
    private static string? ReadIdentifier(string text, ref int i)
    {
        SkipWhitespace(text, ref i);
        if (i >= text.Length || !IsIdentifierStart(text[i])) return null;
        var start = i;
        i++;
        while (i < text.Length && IsIdentifierChar(text[i])) i++;
        return text[start..i];
    }

    private static void SkipWhitespace(string text, ref int i)
    {
        while (i < text.Length && char.IsWhiteSpace(text[i])) i++;
    }

    /// <summary>从 open 位置起跳过平衡的 open…close 区域，返回 close 后一位置。</summary>
    private static int SkipBalancedForward(string text, int i, char open, char close)
    {
        var depth = 0;
        for (; i < text.Length; i++)
        {
            if (text[i] == '"' || text[i] == '\'')
            {
                i = SkipQuotedLiteral(text, i) - 1;
                continue;
            }
            if (text[i] == open) depth++;
            else if (text[i] == close)
            {
                depth--;
                if (depth == 0) return i + 1;
            }
        }
        return text.Length;
    }

    /// <summary>返回文本中第一个顶层分号下标；无则返回 -1。</summary>
    private static int IndexOfTopLevelSemicolon(string text)
    {
        var depth = 0;
        for (var i = 0; i < text.Length; i++)
        {
            var ch = text[i];
            if (ch == '"' || ch == '\'')
            {
                i = SkipQuotedLiteral(text, i) - 1;
                continue;
            }
            switch (ch)
            {
                case '(':
                case '[':
                case '{':
                case '<':
                    depth++;
                    break;
                case ')':
                case ']':
                case '}':
                case '>':
                    if (depth > 0) depth--;
                    break;
                case ';' when depth == 0:
                    return i;
            }
        }
        return -1;
    }

    /// <summary>i 处是否为 lambda 箭头（-> 或 =>）。</summary>
    private static bool IsLambdaArrow(string text, int i)
        => (text[i] == '-' && text[i + 1] == '>') || (text[i] == '=' && text[i + 1] == '>');

