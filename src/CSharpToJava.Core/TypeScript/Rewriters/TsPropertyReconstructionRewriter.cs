using System.Text;
using CSharpToJava.Core.Java;

namespace CSharpToJava.Core.TypeScript.Rewriters;

/// <summary>
/// 类属性访问器重组角色（Task 16）：由 TsPropertyReconstructionRewriter 在发射前
/// 标记到方法上，TsTypeWriter.EmitClass 据此发射 TS 字段/访问器。
/// </summary>
public enum TsAccessorRole
{
    /// <summary>自动 get;set; 双访问器 → TS 字段（简化，访问器方法已从 IR 移除）</summary>
    Field,
    /// <summary>只读 getter（含表达式体属性、抽象 getter）→ TS getter 访问器</summary>
    Getter,
    /// <summary>getter + 受限 setter（private/protected）或抽象对 → TS getter + setter 访问器</summary>
    GetterSetter,
    /// <summary>只写属性（仅 setter）→ 维持方法发射 + 诊断注释</summary>
    WriteOnly,
}

/// <summary>
/// 属性访问器重组 rewriter（M2，Task 16 + 双审修复）：类自动属性 getX()/setX(value)
/// （PropertyTransformer 产出，IsAutoGenerated = true）重组为 TS 字段/访问器，并同步
/// 改写全部调用点。
///
/// 重组规则（以 IR 实测为准，见计划文档 Task 16 注记）：
/// - 自动 get;set; 双访问器（非表达式体、非 struct、非 override、有 camelCase 后备字段、
///   setter 非受限可见性）→ 字段简化：后备字段改名为属性名（PascalCase）、可见性取 getter、
///   访问器方法移除；
/// - 只读 { get; } / 表达式体 { get => expr; } → TS getter 访问器；
/// - getter + 受限 setter（private/protected，含表达式体对）→ TS getter + setter 访问器；
/// - 抽象访问器 → abstract get/set 访问器（与派生 override 访问器形态匹配，I4）；
/// - override 访问器不做字段简化（保持访问器对，与基类抽象/访问器形态匹配，I4）；
/// - 只写 { set; } → 维持方法发射 + 诊断注释（无 TS 对应形态）；
/// - 显式接口实现访问器 / 非自动生成方法 → 不重组（维持方法发射）。
/// 接口访问器（Task 15 已合并发射为 readonly/普通属性）：仅注册调用点改写名，不产生 roles。
///
/// 调用点改写覆盖两类形态：
/// - 结构化 IR（JavaMethodCallExpression 等表达式节点）；
/// - raw 文本（JavaRawStatement.Code、方法/构造器 Body 字符串、JavaRawExpression.Code、
///   字段初始化器、静态初始化块语句）——前端大部分语句以 Java 文本直通（Task 9 注记），
///   文本改写跳过字符串/字符字面量与注释。
/// 解析策略（C1 保守：宁可不改，不可误改合法代码）：
/// - 裸/this/super 调用 → 按当前类型 + 基类链解析（静态补类名.，实例补 this.；
///   super 落到 this，TS 无 super 属性访问 TS2855）；
/// - dot-target 调用 → 仅当目标类型可解析（方法参数/局部变量/当前类字段/类型名，见
///   ResolveIdentifierType）且该类型的上下文注册了该访问器名时才改写；无类型信息或
///   目标类型未注册 → 保持方法调用（用户方法与重建属性重名的场景不再误改）。
///
/// 访问器方法体额外做字段限定（P1/I5）：TS 类体内裸字段标识符非法（tsc TS2663，
/// "Did you mean the instance member 'this.x'?"），对当前类字段名的裸引用补 this./类名. 前缀；
/// 排除 setter 参数（value）与结构化局部变量（P1：参数与字段同名不得误限）。
/// </summary>
public sealed class TsPropertyReconstructionRewriter : JavaSyntaxRewriter
{
    private readonly Dictionary<JavaMethodDeclaration, TsAccessorRole> _roles = new();

    /// <summary>
    /// 访问器方法角色侧表。字段简化（Field）的方法已从 IR 移除但键保留（供测试/诊断）；
    /// 发射按 cls.Methods 迭代，已移除方法不参与。其余角色键为仍在 IR 中的方法节点。
    /// 接口访问器不进本表（发射由 TsTypeWriter.EmitInterface 的 Task 15 合并负责）。
    /// </summary>
    public IReadOnlyDictionary<JavaMethodDeclaration, TsAccessorRole> Roles => _roles;

    /// <summary>类节点 → 类上下文（节点键控，避免同名单类互串）。</summary>
    private readonly Dictionary<JavaClassDeclaration, ClassContext> _classContexts = new();
    /// <summary>接口节点 → 接口上下文（调用点改写用，不产生 roles）。</summary>
    private readonly Dictionary<JavaInterfaceDeclaration, ClassContext> _interfaceContexts = new();
    /// <summary>类型名 → 上下文（类 + 接口；基类链与 dot-target 类型解析；同名单类可能覆盖，L3 兜底）。</summary>
    private readonly Dictionary<string, ClassContext> _typeContextsByName = new(StringComparer.Ordinal);

    /// <summary>当前类型上下文栈（嵌套类型各自独立）。</summary>
    private readonly Stack<ClassContext> _classStack = new();
    /// <summary>当前方法上下文栈（参数/局部变量：目标类型解析 + 字段限定排除）。</summary>
    private readonly Stack<MethodContext> _methodStack = new();
    /// <summary>正在遍历访问器方法体（触发裸字段限定，P1/I5）。</summary>
    private bool _qualifyingAccessorBody;

    private sealed record AccessorInfo(string PropertyName, bool IsStatic, string OwnerClassName);

    private sealed class ClassContext
    {
        public required string ClassName { get; init; }
        /// <summary>基类型名（类：ExtendedType；接口：ExtendedTypes 列表）。</summary>
        public required List<string> BaseTypeNames { get; init; }
        public required Dictionary<string, string> InstanceFieldTypes { get; init; }
        public required Dictionary<string, string> StaticFieldTypes { get; init; }
        /// <summary>本类型注册的访问器方法名集合（this./裸调用按当前类型 + 基类链解析）。</summary>
        public Dictionary<string, AccessorInfo> AccessorMap { get; } = new(StringComparer.Ordinal);
    }

    private sealed class MethodContext
    {
        /// <summary>参数 + 结构化局部变量名（字段限定排除集）。</summary>
        public required HashSet<string> NonFieldNames { get; init; }
        /// <summary>变量名 → 类型（dot-target 目标类型解析）。</summary>
        public required Dictionary<string, string> VariableTypes { get; init; }
    }

    // ─── 类型遍历 ─────────────────────────────────────────────────────

    public override JavaCompilationUnit VisitCompilationUnit(JavaCompilationUnit node)
    {
        // 两阶段：先全量分析（所有类/接口/嵌套类型的重组决策与注册），再遍历改写调用点。
        // 保证基类在派生类之后声明时，派生类内的裸调用也能解析到基类属性。
        foreach (var type in node.TypeDeclarations)
        {
            AnalyzeTypesRecursive(type);
        }
        return base.VisitCompilationUnit(node);
    }

    private void AnalyzeTypesRecursive(JavaTypeDeclaration type)
    {
        switch (type)
        {
            case JavaClassDeclaration cls:
                var context = CreateClassContext(cls.Name, SingleOrEmpty(cls.ExtendedType), cls.Fields);
                _classContexts[cls] = context;
                _typeContextsByName[cls.Name] = context;
                AnalyzeClass(cls, context);
                foreach (var nested in cls.NestedTypes) AnalyzeTypesRecursive(nested);
                break;
            case JavaInterfaceDeclaration iface:
                var ifaceContext = CreateClassContext(iface.Name, iface.ExtendedTypes, iface.Fields);
                _interfaceContexts[iface] = ifaceContext;
                _typeContextsByName[iface.Name] = ifaceContext;
                AnalyzeInterface(iface, ifaceContext);
                foreach (var nested in iface.NestedTypes) AnalyzeTypesRecursive(nested);
                break;
        }
    }

    private static List<string> SingleOrEmpty(string? value)
        => value == null ? new List<string>() : new List<string> { value };

    private static ClassContext CreateClassContext(
        string name, List<string> baseTypes, List<JavaFieldDeclaration> fields)
    {
        var instance = new Dictionary<string, string>(StringComparer.Ordinal);
        var statics = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var field in fields)
        {
            var target = (field.Modifiers & JavaModifiers.Static) != 0 ? statics : instance;
            target[field.Name] = field.Type;
        }
        return new ClassContext
        {
            ClassName = name,
            BaseTypeNames = baseTypes,
            InstanceFieldTypes = instance,
            StaticFieldTypes = statics,
        };
    }

    public override JavaClassDeclaration VisitClassDeclaration(JavaClassDeclaration node)
    {
        // 复用分析阶段建立的上下文（含 AccessorMap 与字段集合；防御性兜底新建）
        if (!_classContexts.TryGetValue(node, out var context))
        {
            context = CreateClassContext(node.Name, SingleOrEmpty(node.ExtendedType), node.Fields);
        }
        _classStack.Push(context);
        try
        {
            var result = base.VisitClassDeclaration(node);
            // JavaSyntaxRewriter 不遍历静态初始化块（TsTypeWriter 直接发射 Statements），
            // 这里补改其中的属性访问器调用
            foreach (var block in node.StaticInitializers)
            {
                for (var i = 0; i < block.Statements.Count; i++)
                {
                    block.Statements[i] = RewriteAccessorCalls(block.Statements[i]);
                }
            }
            return result;
        }
        finally
        {
            _classStack.Pop();
        }
    }

    public override JavaInterfaceDeclaration VisitInterfaceDeclaration(JavaInterfaceDeclaration node)
    {
        if (!_interfaceContexts.TryGetValue(node, out var context))
        {
            context = CreateClassContext(node.Name, node.ExtendedTypes, node.Fields);
        }
        _classStack.Push(context);
        try
        {
            return base.VisitInterfaceDeclaration(node);
        }
        finally
        {
            _classStack.Pop();
        }
    }

    public override JavaMethodDeclaration VisitMethodDeclaration(JavaMethodDeclaration node)
    {
        var methodContext = BuildMethodContext(node);
        var isAccessor = _roles.TryGetValue(node, out var role)
            && role is TsAccessorRole.Getter or TsAccessorRole.GetterSetter or TsAccessorRole.WriteOnly;
        _methodStack.Push(methodContext);
        var previousQualifying = _qualifyingAccessorBody;
        _qualifyingAccessorBody = isAccessor;
        try
        {
            node = base.VisitMethodDeclaration(node);

            // raw Body 字符串（表达式体/自动访问器等）同样可能含属性访问器调用；
            // 访问器方法体还额外做字段限定（TS2663；P1：排除参数/局部变量）。
            // 结构化 body 的语句/表达式在遍历中由 VisitRawStatement/VisitExpression 覆盖。
            if (!string.IsNullOrEmpty(node.Body))
            {
                node.Body = RewriteAccessorCalls(node.Body);
                if (isAccessor)
                {
                    node.Body = QualifyFieldReferences(node.Body);
                }
            }
            return node;
        }
        finally
        {
            _qualifyingAccessorBody = previousQualifying;
            _methodStack.Pop();
        }
    }

    public override JavaConstructorDeclaration VisitConstructorDeclaration(JavaConstructorDeclaration node)
    {
        var methodContext = new MethodContext
        {
            NonFieldNames = node.Parameters.Select(p => p.Name).ToHashSet(StringComparer.Ordinal),
            VariableTypes = node.Parameters.ToDictionary(p => p.Name, p => p.Type, StringComparer.Ordinal),
        };
        _methodStack.Push(methodContext);
        try
        {
            node = base.VisitConstructorDeclaration(node);
            if (!string.IsNullOrEmpty(node.Body))
            {
                node.Body = RewriteAccessorCalls(node.Body);
            }
            return node;
        }
        finally
        {
            _methodStack.Pop();
        }
    }

    public override JavaFieldDeclaration VisitFieldDeclaration(JavaFieldDeclaration node)
    {
        if (!string.IsNullOrEmpty(node.Initializer))
        {
            node.Initializer = RewriteAccessorCalls(node.Initializer);
        }
        return base.VisitFieldDeclaration(node);
    }

    public override JavaRawStatement VisitRawStatement(JavaRawStatement node)
    {
        if (!string.IsNullOrEmpty(node.Code))
        {
            node.Code = RewriteAccessorCalls(node.Code);
            if (_qualifyingAccessorBody)
            {
                node.Code = QualifyFieldReferences(node.Code);
            }
        }
        return base.VisitRawStatement(node);
    }

    public override JavaExpression VisitExpression(JavaExpression node)
    {
        if (node is JavaMethodCallExpression call)
        {
            call = base.VisitMethodCallExpression(call);
            return TryRewriteCall(call, out var replacement) ? replacement : call;
        }
        if (node is JavaIdentifierExpression ident && _qualifyingAccessorBody)
        {
            // 结构化语句中的裸字段引用 → this./类名. 前缀（TS2663）；排除参数/局部变量（P1/I5）
            return QualifyIdentifier(ident.Name) ?? ident;
        }
        if (node is JavaRawExpression raw)
        {
            raw.Code = RewriteAccessorCalls(raw.Code);
            if (_qualifyingAccessorBody)
            {
                raw.Code = QualifyFieldReferences(raw.Code);
            }
            return raw;
        }
        if (node is JavaMemberAccessExpression access)
        {
            access = base.VisitMemberAccessExpression(access);
            return access;
        }
        return base.VisitExpression(node);
    }

    // ─── 方法上下文（参数/局部变量收集） ───────────────────────────────

    private static MethodContext BuildMethodContext(JavaMethodDeclaration method)
    {
        var variables = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var parameter in method.Parameters)
        {
            variables[parameter.Name] = parameter.Type;
        }
        if (method.StructuredBody != null)
        {
            CollectStructuredLocals(method.StructuredBody.Statements, variables);
        }
        return new MethodContext
        {
            NonFieldNames = variables.Keys.ToHashSet(StringComparer.Ordinal),
            VariableTypes = variables,
        };
    }

    private static void CollectStructuredLocals(
        IReadOnlyList<JavaStatement> statements, Dictionary<string, string> variables)
    {
        foreach (var statement in statements)
        {
            switch (statement)
            {
                case JavaVariableDeclarationStatement declaration:
                    variables[declaration.Name] = declaration.Type;
                    break;
                case JavaForEachStatement forEach:
                    if (!string.IsNullOrEmpty(forEach.VariableName))
                        variables[forEach.VariableName] = forEach.VariableType;
                    CollectStructuredLocalsFromStatement(forEach.Body, variables);
                    break;
                case JavaBlockStatement block:
                    CollectStructuredLocals(block.Statements, variables);
                    break;
                case JavaIfStatement ifStatement:
                    CollectStructuredLocalsFromStatement(ifStatement.ThenBody, variables);
                    if (ifStatement.ElseBody != null)
                        CollectStructuredLocalsFromStatement(ifStatement.ElseBody, variables);
                    break;
                case JavaWhileStatement whileStatement:
                    CollectStructuredLocalsFromStatement(whileStatement.Body, variables);
                    break;
                case JavaDoWhileStatement doWhile:
                    CollectStructuredLocalsFromStatement(doWhile.Body, variables);
                    break;
                case JavaForStatement forStatement:
                    CollectStructuredLocalsFromStatement(forStatement.Body, variables);
                    break;
                case JavaTryCatchStatement tryCatch:
                    CollectStructuredLocals(tryCatch.TryBody.Statements, variables);
                    foreach (var catchClause in tryCatch.CatchClauses)
                    {
                        if (!string.IsNullOrEmpty(catchClause.VariableName))
                            variables[catchClause.VariableName] = catchClause.ExceptionType;
                        CollectStructuredLocals(catchClause.Body.Statements, variables);
                    }
                    if (tryCatch.FinallyBody != null)
                        CollectStructuredLocals(tryCatch.FinallyBody.Statements, variables);
                    break;
                case JavaSwitchStatement switchStatement:
                    foreach (var section in switchStatement.Sections)
                    {
                        CollectStructuredLocals(section.Statements, variables);
                    }
                    break;
            }
        }
    }

    private static void CollectStructuredLocalsFromStatement(
        JavaStatement statement, Dictionary<string, string> variables)
    {
        switch (statement)
        {
            case JavaBlockStatement block:
                CollectStructuredLocals(block.Statements, variables);
                break;
            case JavaVariableDeclarationStatement declaration:
                variables[declaration.Name] = declaration.Type;
                break;
            case JavaForEachStatement forEach:
                if (!string.IsNullOrEmpty(forEach.VariableName))
                    variables[forEach.VariableName] = forEach.VariableType;
                CollectStructuredLocalsFromStatement(forEach.Body, variables);
                break;
            case JavaIfStatement ifStatement:
                CollectStructuredLocalsFromStatement(ifStatement.ThenBody, variables);
                if (ifStatement.ElseBody != null)
                    CollectStructuredLocalsFromStatement(ifStatement.ElseBody, variables);
                break;
            case JavaWhileStatement whileStatement:
                CollectStructuredLocalsFromStatement(whileStatement.Body, variables);
                break;
            case JavaDoWhileStatement doWhile:
                CollectStructuredLocalsFromStatement(doWhile.Body, variables);
                break;
            case JavaForStatement forStatement:
                CollectStructuredLocalsFromStatement(forStatement.Body, variables);
                break;
            case JavaTryCatchStatement tryCatch:
                CollectStructuredLocals(tryCatch.TryBody.Statements, variables);
                foreach (var catchClause in tryCatch.CatchClauses)
                {
                    if (!string.IsNullOrEmpty(catchClause.VariableName))
                        variables[catchClause.VariableName] = catchClause.ExceptionType;
                    CollectStructuredLocals(catchClause.Body.Statements, variables);
                }
                if (tryCatch.FinallyBody != null)
                    CollectStructuredLocals(tryCatch.FinallyBody.Statements, variables);
                break;
            case JavaSwitchStatement switchStatement:
                foreach (var section in switchStatement.Sections)
                {
                    CollectStructuredLocals(section.Statements, variables);
                }
                break;
        }
    }

    // ─── 识别与标记 ───────────────────────────────────────────────────

    /// <summary>
    /// 逐类扫描自动生成访问器方法（get/set + 首字母大写）并按属性名配对，执行重组决策
    /// （字段简化 / getter / getter+setter / 只写 / 抽象），并注册调用点改写所需的方法名集合。
    /// </summary>
    private void AnalyzeClass(JavaClassDeclaration cls, ClassContext context)
    {
        var candidates = cls.Methods.Where(IsAutoAccessorCandidate).ToList();
        foreach (var group in candidates.GroupBy(m => m.Name.Substring(3)))
        {
            var propName = group.Key;
            var getter = group.FirstOrDefault(m => m.Name.StartsWith("get"));
            var setter = group.FirstOrDefault(m => m.Name.StartsWith("set"));

            if (getter == null)
            {
                // 只写属性（仅 setter）：无 TS 对应形态 → 维持方法发射 + 诊断注释
                if (setter != null && !setter.IsExplicitInterfaceImplementation)
                {
                    // WriteOnly 不注册任何方法名：setter 调用点保持方法形态（无 TS 属性可赋）
                    _roles[setter] = TsAccessorRole.WriteOnly;
                }
                continue;
            }

            if (getter.IsExplicitInterfaceImplementation) continue;
            if (setter != null && setter.IsExplicitInterfaceImplementation) continue;

            var isAbstract = (getter.Modifiers & JavaModifiers.Abstract) != 0
                          || (setter?.Modifiers & JavaModifiers.Abstract) != 0;

            if (isAbstract)
            {
                // 抽象访问器（I4）：发射 abstract get/set（无体），注册方法名供类链调用改写；
                // 抽象属性无后备字段，不做字段简化
                if (setter == null)
                {
                    _roles[getter] = TsAccessorRole.Getter;
                    RegisterAccessorNames(getter, context, registerSetter: false);
                }
                else
                {
                    _roles[getter] = TsAccessorRole.GetterSetter;
                    _roles[setter] = TsAccessorRole.GetterSetter;
                    RegisterAccessorNames(getter, context, registerSetter: true);
                }
                continue;
            }

            if (setter == null)
            {
                // 只读属性（自动或表达式体）→ getter 访问器
                _roles[getter] = TsAccessorRole.Getter;
                RegisterAccessorNames(getter, context, registerSetter: false);
                continue;
            }

            var isRestrictedSetter = (setter.Modifiers & (JavaModifiers.Private | JavaModifiers.Protected)) != 0;
            var isTrivialAutoPair = !getter.IsBodyExpression && getter.StructuredBody == null && getter.Body != null
                                 && !setter.IsBodyExpression && setter.StructuredBody == null && setter.Body != null
                                 && (getter.Modifiers & JavaModifiers.Override) == 0;   // I4：override 保持访问器对

            if (isTrivialAutoPair && !isRestrictedSetter && !cls.IsConvertedFromStruct)
            {
                // 自动 get;set; 双访问器 → 字段简化：后备字段提升为属性字段、访问器方法移除
                var backingField = cls.Fields.LastOrDefault(f =>
                    f.Name == ToCamelCase(propName) && (f.Modifiers & JavaModifiers.Static) == (getter.Modifiers & JavaModifiers.Static));
                if (backingField != null)
                {
                    backingField.Name = propName;
                    backingField.Modifiers = (backingField.Modifiers & ~(JavaModifiers.Public | JavaModifiers.Protected | JavaModifiers.Private))
                                           | (getter.Modifiers & (JavaModifiers.Public | JavaModifiers.Protected | JavaModifiers.Private));
                    _roles[getter] = TsAccessorRole.Field;
                    _roles[setter] = TsAccessorRole.Field;
                    cls.Methods.Remove(getter);
                    cls.Methods.Remove(setter);
                    RegisterAccessorNames(getter, context, registerSetter: true);
                    continue;
                }
            }

            // getter + setter（受限可见性或表达式体/无后备字段/override）→ 访问器对
            _roles[getter] = TsAccessorRole.GetterSetter;
            _roles[setter] = TsAccessorRole.GetterSetter;
            RegisterAccessorNames(getter, context, registerSetter: true);
        }
    }

    /// <summary>
    /// 接口访问器（Task 15 已合并发射为 readonly/普通属性）：仅注册调用点改写名。
    /// 只读接口属性（仅 getter）只注册 getter；get+set 接口属性注册两者；只写接口属性
    /// （仅 setter，方法形态保留）不注册。不产生 roles（发射路径仍由 EmitInterface 负责）。
    /// </summary>
    private static void AnalyzeInterface(JavaInterfaceDeclaration iface, ClassContext context)
    {
        foreach (var group in iface.Methods.Where(IsAutoAccessorCandidate).GroupBy(m => m.Name.Substring(3)))
        {
            var getter = group.FirstOrDefault(m => m.Name.StartsWith("get"));
            var setter = group.FirstOrDefault(m => m.Name.StartsWith("set"));
            if (getter == null) continue;   // 只写接口属性：setter 保持方法形态，不注册
            var isStatic = (getter.Modifiers & JavaModifiers.Static) != 0;
            var info = new AccessorInfo(group.Key, isStatic, iface.Name);
            context.AccessorMap["get" + group.Key] = info;
            if (setter != null)
            {
                context.AccessorMap["set" + group.Key] = info;
            }
        }
    }

    /// <summary>
    /// 将访问器方法名登记到调用点改写集合：getter 名（Field/Getter/GetterSetter/抽象）与
    /// setter 名（Field/GetterSetter）会改写为成员访问/赋值；WriteOnly 不登记（方法保留）。
    /// </summary>
    private void RegisterAccessorNames(JavaMethodDeclaration accessor, ClassContext context, bool registerSetter)
    {
        var propName = accessor.Name.Substring(3);
        var isStatic = (accessor.Modifiers & JavaModifiers.Static) != 0;
        var info = new AccessorInfo(propName, isStatic, context.ClassName);
        context.AccessorMap["get" + propName] = info;
        if (registerSetter)
        {
            context.AccessorMap["set" + propName] = info;
        }
    }

    /// <summary>
    /// 解析 this./super./裸调用（隐式 this）：当前类型 → 基类链（本单元内已分析）。
    /// 调用方的类型已知，不按全局集合匹配（C1：否则会误改同名跨类访问器）；基类不在
    /// 本单元内时不改写（多文件/项目模式 M5 处理，L3 兜底）。
    /// </summary>
    private bool TryResolveAccessor(string methodName, out AccessorInfo info)
    {
        info = null!;
        if (_classStack.Count == 0) return false;
        var context = _classStack.Peek();
        if (context.AccessorMap.TryGetValue(methodName, out info!))
        {
            return true;
        }
        foreach (var baseName in context.BaseTypeNames)
        {
            if (_typeContextsByName.TryGetValue(baseName, out var baseContext)
                && baseContext.AccessorMap.TryGetValue(methodName, out info!))
            {
                return true;
            }
        }
        return false;
    }

    private static bool IsAutoAccessorCandidate(JavaMethodDeclaration m)
    {
        if (!m.IsAutoGenerated || m.Name.Length <= 3) return false;
        var isGet = m.Name.StartsWith("get");
        var isSet = m.Name.StartsWith("set");
        if (!isGet && !isSet) return false;
        if (m.Name[3] is not (>= 'A' and <= 'Z')) return false;
        if (isGet && m.Parameters.Count != 0) return false;   // 索引器形态 getItem(index) 不重组
        if (isSet && m.Parameters.Count != 1) return false;
        return true;
    }

    private static string ToCamelCase(string name)
        => name.Length == 0 ? name : char.ToLowerInvariant(name[0]) + name[1..];

    // ─── 目标类型解析（C1 dot-target 保守改写） ───────────────────────

    /// <summary>
    /// 解析表达式可确定的类型名（仅本单元已知类型）：标识符（方法参数/局部变量/当前类字段/
    /// 类型名）、this（当前类型名）、new/cast/raw(ResolvedType)/括号/成员访问/数组元素。
    /// 无法解析 → null（调用点保持方法形态，保守不改写）。
    /// </summary>
    private string? ResolveExpressionType(JavaExpression expr)
    {
        switch (expr)
        {
            case JavaIdentifierExpression id:
                return ResolveIdentifierType(id.Name);
            case JavaThisExpression thisExpr when !thisExpr.IsSuper:
                return _classStack.Count > 0 ? _classStack.Peek().ClassName : null;
            case JavaNewExpression newExpr:
                return newExpr.Type;
            case JavaCastExpression cast:
                return cast.Type;
            case JavaRawExpression raw:
                return raw.ResolvedType;
            case JavaParenthesizedExpression paren:
                return ResolveExpressionType(paren.InnerExpression);
            case JavaMemberAccessExpression access:
            {
                var targetType = ResolveExpressionType(access.Target);
                if (targetType == null || !_typeContextsByName.TryGetValue(targetType, out var ctx))
                {
                    return null;
                }
                return ctx.InstanceFieldTypes.TryGetValue(access.MemberName, out var fieldType)
                    ? fieldType
                    : ctx.StaticFieldTypes.TryGetValue(access.MemberName, out fieldType) ? fieldType : null;
            }
            case JavaArrayAccessExpression arrayAccess:
            {
                var elementType = ResolveExpressionType(arrayAccess.Target);
                if (elementType != null && elementType.EndsWith("[]", StringComparison.Ordinal))
                {
                    return elementType[..^2].Trim();
                }
                return null;
            }
            default:
                return null;
        }
    }

    /// <summary>
    /// 解析标识符的类型：当前方法参数/局部变量 → 当前类型字段 → 类型名（静态访问）。
    /// </summary>
    private string? ResolveIdentifierType(string name)
    {
        if (_methodStack.Count > 0 && _methodStack.Peek().VariableTypes.TryGetValue(name, out var variableType))
        {
            return variableType;
        }
        if (_classStack.Count > 0)
        {
            var context = _classStack.Peek();
            if (context.InstanceFieldTypes.TryGetValue(name, out variableType)) return variableType;
            if (context.StaticFieldTypes.TryGetValue(name, out variableType)) return variableType;
        }
        return _typeContextsByName.ContainsKey(name) ? name : null;
    }

    // ─── 结构化调用点改写 ─────────────────────────────────────────────

    /// <summary>
    /// 结构化 JavaMethodCallExpression → 属性成员访问/赋值（仅命中重建集合的方法名）。
    /// 裸/this/super 按当前类型 + 基类链解析；dot-target 仅当目标类型可解析且该类型
    /// 注册了该访问器名时改写（C1 保守策略）。
    /// </summary>
    private bool TryRewriteCall(JavaMethodCallExpression call, out JavaExpression replacement)
    {
        replacement = null!;
        AccessorInfo info;
        JavaExpression replacementTarget;

        if (call.Target == null || call.Target is JavaThisExpression)
        {
            // 裸/this/super：按当前类型 + 基类链解析（不依赖全局名集合）
            if (!TryResolveAccessor(call.MethodName, out info)) return false;
            replacementTarget = call.Target ?? CreateBareTarget(info);
            if (call.Target is JavaThisExpression targetThis)
            {
                if (targetThis.IsSuper)
                {
                    // super → this（TS 无 super 属性访问 TS2855；静态属性经声明类名访问）
                    replacementTarget = info.IsStatic ? CreateBareTarget(info) : new JavaThisExpression { IsSuper = false };
                }
                else if (info.IsStatic)
                {
                    // this 目标访问静态属性 → 声明类名
                    replacementTarget = CreateBareTarget(info);
                }
            }
        }
        else
        {
            // dot-target：仅当目标类型可解析且该类型上下文注册了该访问器名时才改写
            var typeName = ResolveExpressionType(call.Target);
            if (typeName == null) return false;
            if (!_typeContextsByName.TryGetValue(typeName, out var typeContext)) return false;
            if (!typeContext.AccessorMap.TryGetValue(call.MethodName, out info)) return false;
            replacementTarget = call.Target;
        }

        var isGetter = call.MethodName.StartsWith("get");
        var isSetter = call.MethodName.StartsWith("set");
        if (isGetter && call.Arguments.Count != 0) return false;
        if (isSetter && call.Arguments.Count != 1) return false;

        var memberAccess = new JavaMemberAccessExpression { Target = replacementTarget, MemberName = info.PropertyName };

        if (isGetter)
        {
            replacement = memberAccess;
            return true;
        }
        replacement = new JavaAssignmentExpression
        {
            Target = memberAccess,
            Operator = "=",
            Value = call.Arguments[0],
        };
        return true;
    }

    /// <summary>
    /// 裸调用（IR Target == null，Java 隐式 this/类名目标）：实例属性 → this.X；
    /// 静态属性 → 声明类名.X。
    /// </summary>
    private static JavaExpression CreateBareTarget(AccessorInfo info)
    {
        if (info.IsStatic && info.OwnerClassName.Length > 0)
        {
            return new JavaIdentifierExpression(info.OwnerClassName);
        }
        return new JavaThisExpression();
    }

    // ─── raw 文本调用点改写 ───────────────────────────────────────────

    /// <summary>
    /// 扫描改写 raw Java 文本中的属性访问器调用：target.getX() → target.X；
    /// target.setX(v) → target.X = v（v 递归改写）；裸调用补 this./类名. 前缀，
    /// super 目标落到 this。跳过字符串/字符字面量与注释区域；getter 要求 0 参、
    /// setter 要求单个顶层实参。dot-target 仅当目标标识符类型可解析且注册过才改写（C1）。
    /// </summary>
    private string RewriteAccessorCalls(string text)
    {
        if (string.IsNullOrEmpty(text)) return text;

        var sb = new StringBuilder(text.Length);
        var pendingTargetStart = -1;
        var pendingTargetName = string.Empty;
        var i = 0;
        while (i < text.Length)
        {
            var ch = text[i];
            if (ch == '"' || ch == '\'')
            {
                var start = i;
                i = SkipQuotedLiteral(text, i);
                sb.Append(text, start, i - start);
                continue;
            }
            if (ch == '/' && i + 1 < text.Length && (text[i + 1] == '/' || text[i + 1] == '*'))
            {
                var start = i;
                i = SkipComment(text, i);
                sb.Append(text, start, i - start);
                continue;
            }
            if (IsIdentifierStart(ch) && AtIdentifierBoundaryBefore(text, i))
            {
                var nameEnd = i + 1;
                while (nameEnd < text.Length && IsIdentifierChar(text[nameEnd])) nameEnd++;
                var name = text[i..nameEnd];
                if (nameEnd < text.Length && text[nameEnd] == '('
                    && (IsThisOrSuperTarget(text, i)
                        ? TryResolveAccessor(name, out var info)
                        : TryResolveRawDotTarget(text, i, name, out info)))
                {
                    var close = FindMatchingParen(text, nameEnd);
                    if (close < 0)
                    {
                        sb.Append(ch);
                        i++;
                        continue;
                    }
                    var argText = text[(nameEnd + 1)..close];
                    var isGetter = name.StartsWith("get");
                    if (isGetter && argText.Trim().Length == 0)
                    {
                        sb.Append(BuildPropertyAccess(text, i, info, null, sb, pendingTargetStart, pendingTargetName));
                        i = close + 1;
                        continue;
                    }
                    if (name.StartsWith("set") && IsSingleTopLevelArg(argText))
                    {
                        var rewrittenArg = RewriteAccessorCalls(argText.Trim());
                        sb.Append(BuildPropertyAccess(text, i, info, rewrittenArg, sb, pendingTargetStart, pendingTargetName));
                        i = close + 1;
                        continue;
                    }
                }
                if (nameEnd < text.Length && text[nameEnd] == '.')
                {
                    // 记录点号目标段起点（super./this. 回滚用，I3）
                    pendingTargetStart = sb.Length;
                    pendingTargetName = name;
                }
            }
            sb.Append(ch);
            i++;
        }
        return sb.ToString();
    }

    /// <summary>
    /// 解析 raw 文本中 dot-target 调用的目标标识符类型并查访问器注册（C1 保守策略）：
    /// 目标为单个标识符，且其类型（方法参数/局部变量/当前类字段/类型名）可解析到本单元
    /// 已知类型且该类型注册了该方法名时才改写；否则保持方法调用。
    /// </summary>
    private bool TryResolveRawDotTarget(string text, int nameStart, string methodName, out AccessorInfo info)
    {
        info = null!;
        if (nameStart == 0 || text[nameStart - 1] != '.') return false;
        var targetEnd = nameStart - 1;
        var targetStart = targetEnd;
        while (targetStart > 0 && IsIdentifierChar(text[targetStart - 1])) targetStart--;
        if (targetStart == targetEnd || !IsIdentifierStart(text[targetStart])) return false;
        var targetName = text[targetStart..targetEnd];
        var typeName = ResolveIdentifierType(targetName);
        if (typeName == null) return false;
        if (!_typeContextsByName.TryGetValue(typeName, out var typeContext)) return false;
        return typeContext.AccessorMap.TryGetValue(methodName, out info);
    }

    /// <summary>
    /// 生成属性访问文本：target.getX() → target.X / target.setX(v) → target.X = v。
    /// 目标为点号前缀时沿用 output 中已累积的目标文本（去掉末尾点号）；super 目标回滚
    /// 已累积的 "super." 后补 this.（TS 无 super 属性访问 TS2855），this 访问静态属性
    /// 回滚后补类名；裸调用补 this./类名.。
    /// </summary>
    private string BuildPropertyAccess(string text, int nameStart, AccessorInfo info, string? rewrittenArg,
        StringBuilder output, int pendingTargetStart, string pendingTargetName)
    {
        var precededByDot = nameStart > 0 && text[nameStart - 1] == '.';
        var sb = new StringBuilder();
        if (precededByDot)
        {
            var targetName = RawTargetIdentifier(text, nameStart);
            if (targetName == "super" || (targetName == "this" && info.IsStatic))
            {
                // 回滚已累积的 "super."/"this." 目标文本，改补 this./类名. 前缀（I3）
                if (pendingTargetStart >= 0 && pendingTargetName == targetName)
                {
                    output.Length = pendingTargetStart;
                }
                sb.Append(info.IsStatic && info.OwnerClassName.Length > 0 ? info.OwnerClassName + "." : "this.");
            }
            sb.Append(info.PropertyName);
            if (rewrittenArg != null) sb.Append(" = ").Append(rewrittenArg);
            return sb.ToString();
        }
        sb.Append(info.IsStatic && info.OwnerClassName.Length > 0 ? info.OwnerClassName + "." : "this.");
        sb.Append(info.PropertyName);
        if (rewrittenArg != null) sb.Append(" = ").Append(rewrittenArg);
        return sb.ToString();
    }

    /// <summary>取 nameStart 之前紧邻点号目标的标识符（无目标返回空串）。</summary>
    private static string RawTargetIdentifier(string text, int nameStart)
    {
        if (nameStart == 0 || text[nameStart - 1] != '.') return string.Empty;
        var targetEnd = nameStart - 1;
        var targetStart = targetEnd;
        while (targetStart > 0 && IsIdentifierChar(text[targetStart - 1])) targetStart--;
        return text[targetStart..targetEnd];
    }

    // ─── 访问器体字段限定（P1/I5） ────────────────────────────────────

    /// <summary>
    /// 将访问器方法体 raw 文本中的裸字段标识符补 this./类名. 前缀（tsc TS2663）。
    /// 仅限定当前类型字段名（实例 → this.，静态 → 类名.）；排除方法参数与结构化局部变量
    /// （P1：setter 参数 value 与字段同名不得误限）；跳过点号成员名、方法调用、
    /// 字符串/字符字面量与注释。
    /// </summary>
    private string QualifyFieldReferences(string text)
    {
        if (string.IsNullOrEmpty(text) || _classStack.Count == 0) return text;

        var context = _classStack.Peek();
        var excluded = _methodStack.Count > 0 ? _methodStack.Peek().NonFieldNames : null;
        var sb = new StringBuilder(text.Length);
        var i = 0;
        while (i < text.Length)
        {
            var ch = text[i];
            if (ch == '"' || ch == '\'')
            {
                var start = i;
                i = SkipQuotedLiteral(text, i);
                sb.Append(text, start, i - start);
                continue;
            }
            if (ch == '/' && i + 1 < text.Length && (text[i + 1] == '/' || text[i + 1] == '*'))
            {
                var start = i;
                i = SkipComment(text, i);
                sb.Append(text, start, i - start);
                continue;
            }
            if (IsIdentifierStart(ch) && AtIdentifierBoundaryBefore(text, i))
            {
                var nameEnd = i + 1;
                while (nameEnd < text.Length && IsIdentifierChar(text[nameEnd])) nameEnd++;
                var name = text[i..nameEnd];
                var precededByDot = i > 0 && text[i - 1] == '.';
                var followedByParen = nameEnd < text.Length && text[nameEnd] == '(';
                if (!precededByDot && !followedByParen)
                {
                    if (excluded == null || !excluded.Contains(name))
                    {
                        if (context.InstanceFieldTypes.ContainsKey(name))
                        {
                            sb.Append("this.").Append(name);
                            i = nameEnd;
                            continue;
                        }
                        if (context.StaticFieldTypes.ContainsKey(name))
                        {
                            sb.Append(context.ClassName).Append('.').Append(name);
                            i = nameEnd;
                            continue;
                        }
                    }
                }
            }
            sb.Append(ch);
            i++;
        }
        return sb.ToString();
    }

    /// <summary>
    /// 结构化表达式中的裸字段标识符 → this./类名. 成员访问（TS2663）；排除参数/局部变量。
    /// </summary>
    private JavaExpression? QualifyIdentifier(string name)
    {
        if (_classStack.Count == 0) return null;
        var context = _classStack.Peek();
        if (_methodStack.Count > 0 && _methodStack.Peek().NonFieldNames.Contains(name)) return null;
        if (context.InstanceFieldTypes.ContainsKey(name))
        {
            return new JavaMemberAccessExpression { Target = new JavaThisExpression(), MemberName = name };
        }
        if (context.StaticFieldTypes.ContainsKey(name))
        {
            return new JavaMemberAccessExpression
            {
                Target = new JavaIdentifierExpression(context.ClassName),
                MemberName = name,
            };
        }
        return null;
    }

    // ─── 文本扫描工具 ─────────────────────────────────────────────────

    private static bool IsIdentifierStart(char c) => char.IsLetter(c) || c == '_' || c == '$';

    private static bool IsIdentifierChar(char c) => char.IsLetterOrDigit(c) || c == '_' || c == '$';

    /// <summary>调用名前的标识符边界（前一个字符不是标识符字符且不是点号）。</summary>
    private static bool AtIdentifierBoundaryBefore(string text, int index)
    {
        if (index == 0) return true;
        var prev = text[index - 1];
        return !IsIdentifierChar(prev);
    }

    /// <summary>
    /// 判断调用是否为 this./super./裸调用（隐式 this）：裸调用与非 this/super 点号目标
    /// 走不同解析路径（裸/this/super 按当前类型 + 基类链，其他按目标类型解析，C1）。
    /// </summary>
    private static bool IsThisOrSuperTarget(string text, int nameStart)
    {
        if (nameStart == 0) return true;
        if (text[nameStart - 1] != '.') return true;
        var identEnd = nameStart - 1;
        var identStart = identEnd;
        while (identStart > 0 && IsIdentifierChar(text[identStart - 1])) identStart--;
        var target = text[identStart..identEnd];
        return target == "this" || target == "super";
    }

    /// <summary>跳过自 start 起的字符串/字符字面量（含反斜杠转义），返回闭合引号后一位置。</summary>
    private static int SkipQuotedLiteral(string text, int start)
    {
        var quote = text[start];
        var i = start + 1;
        while (i < text.Length)
        {
            if (text[i] == '\\' && i + 1 < text.Length)
            {
                i += 2;
                continue;
            }
            if (text[i] == quote) return i + 1;
            i++;
        }
        return text.Length;
    }

    /// <summary>跳过自 start 起的 // 行注释或 /* */ 块注释，返回注释后一位置。</summary>
    private static int SkipComment(string text, int start)
    {
        if (start + 1 < text.Length && text[start + 1] == '/')
        {
            var end = text.IndexOf('\n', start + 2);
            return end < 0 ? text.Length : end + 1;
        }
        var close = text.IndexOf("*/", start + 2, StringComparison.Ordinal);
        return close < 0 ? text.Length : close + 2;
    }

    /// <summary>从 openIndex 起的 '(' 找匹配的 ')'（跳过字符串/字符字面量），返回下标；无匹配返回 -1。</summary>
    private static int FindMatchingParen(string text, int openIndex)
    {
        var depth = 0;
        for (var i = openIndex; i < text.Length; i++)
        {
            var ch = text[i];
            if (ch == '"' || ch == '\'')
            {
                i = SkipQuotedLiteral(text, i) - 1;
                continue;
            }
            if (ch == '(') depth++;
            else if (ch == ')')
            {
                depth--;
                if (depth == 0) return i;
            }
        }
        return -1;
    }

    /// <summary>实参文本是否为单个顶层实参（无顶层逗号）。</summary>
    private static bool IsSingleTopLevelArg(string argText)
    {
        var depth = 0;
        for (var i = 0; i < argText.Length; i++)
        {
            var ch = argText[i];
            if (ch == '"' || ch == '\'')
            {
                i = SkipQuotedLiteral(argText, i) - 1;
                continue;
            }
            switch (ch)
            {
                case '(':
                case '[':
                case '{':
                case '<':
                    depth++;
                    break;
                case ')':
                case ']':
                case '}':
                case '>':
                    depth--;
                    break;
                default:
                    if (ch == ',' && depth == 0) return false;
                    break;
            }
        }
        return true;
    }
