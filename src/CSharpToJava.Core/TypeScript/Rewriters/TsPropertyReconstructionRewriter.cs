    /// <summary>
    /// Round 17：raw 文本表达式 → 可确定类型（标识符/this.字段链/new 表达式/方法调用返回
    /// 类型/括号表达式）。递归解析链式段；任何段不可解析 → null（C1 保守）。
    /// buildVariables（Round 19）：BuildMethodContext 期间 _methodStack 尚未 push，
    /// 标识符段经调用方构建中的变量表解析（结构化 var 初始化器推断路径）。
    /// </summary>
    private string? ResolveExpressionTextType(string text, Dictionary<string, string>? buildVariables = null)
    {
        var t = text.Trim();
        if (t.Length == 0) return null;
        if (t.StartsWith('(') && t.EndsWith(')'))
        {
            var open = t.IndexOf('(');
            var close = FindMatchingParen(t, open);
            if (close == t.Length - 1) return ResolveExpressionTextType(t[(open + 1)..^1], buildVariables);
        }
        if (t.StartsWith("new ", StringComparison.Ordinal))
        {
            var typeStart = 4;
            var typeEnd = typeStart;
            while (typeEnd < t.Length && (IsIdentifierChar(t[typeEnd]) || t[typeEnd] == '.')) typeEnd++;
            if (typeEnd == typeStart) return null;
            if (typeEnd < t.Length && t[typeEnd] == '<')
            {
                var close = SkipBalancedForward(t, typeEnd, '<', '>');
                if (close < 0) return null;
                typeEnd = close + 1;
            }
            return NormalizeTypeName(t[typeStart..typeEnd]);
        }
        if (t == "this")
        {
            return _classStack.Count > 0 ? _classStack.Peek().ClassName : null;
        }
        if (t == "super") return null;
        // Round 19（TS2551 FQCN 接收者族）：raw 文本整链查扁平表——点分链逐段分解
        // （Microsoft.Msagl.Core.Geometry.Point → Microsoft 首段即失败 → 整链 null）是
        // 保守不改写的根因；结构化路径（JavaRawExpression.ResolvedType → TryGetTypeContexts）
        // 经全名键 _typeContextsByName["Microsoft.Msagl.Core.Geometry.Point"] 可命中。
        // 此处分解前先整链查表：命中返回简单名（简单名与全名同上下文时）或全名
        // （歧义时指向精确上下文），与结构化路径对齐。
        var wholeName = NormalizeTypeName(t);
        if (wholeName != null && _typeContextsByName.TryGetValue(wholeName, out var wholeCtx))
        {
            var nameDot = wholeName.LastIndexOf('.');
            if (nameDot > 0)
            {
                var simple = wholeName[(nameDot + 1)..];
                if (simple.Length > 0
                    && _typeContextsByName.TryGetValue(simple, out var simpleCtx)
                    && ReferenceEquals(simpleCtx, wholeCtx))
                {
                    return simple;
                }
            }
            return wholeName;
        }
        var lastDot = -1;
        var depth = 0;
        for (var idx = 0; idx < t.Length; idx++)
        {
            var ch = t[idx];
            if (ch == '(' || ch == '<' || ch == '[') depth++;
            else if (ch == ')' || ch == '>' || ch == ']') depth--;
            else if (ch == '.' && depth == 0) lastDot = idx;
        }
        if (lastDot < 0)
        {
            return IsSimpleIdentifier(t) ? ResolveIdentifierType(t, buildVariables) : null;
        }
        var recvText = t[..lastDot].Trim();
        var memberPart = t[(lastDot + 1)..].Trim();
        var openIdx = memberPart.IndexOf('(');
        if (openIdx >= 0 && memberPart.EndsWith(')'))
        {
            var memberName = memberPart[..openIdx];
            if (!IsSimpleIdentifier(memberName)) return null;
            var args = memberPart[(openIdx + 1)..^1];
            var argCount = CountTopLevelArgs(args);
            var recvType = ResolveExpressionTextType(recvText, buildVariables);
            if (recvType == null) return null;
            // Round 19：注册上下文（访问器/用户方法）解析不到时回退内置签名表
            // （compat 集合 get(k)/getValue()/size()... 与 Create$N 工厂），链式段续行
            if (TryGetTypeContext(recvType, out var ctx))
            {
                if (ctx.AccessorMap.TryGetValue(memberName, out var accInfo)) return accInfo.Type;
                if (ctx.MethodReturnTypes.TryGetValue(MethodReturnKey(memberName, argCount), out var retType)) return retType;
            }
            return TryResolveBuiltinMethodReturn(recvType, memberName, argCount);
        }
        if (IsSimpleIdentifier(memberPart))
        {
            var recvType = ResolveExpressionTextType(recvText, buildVariables);
            if (recvType == null || !TryGetTypeContext(recvType, out var ctx)) return null;
            return ResolveMemberTypeInContext(ctx, memberPart);
        }
        return null;
    }

    /// <summary>raw 文本中读取表达式链（标识符(.标识符)*(调用)?）；停在非法字符（C1 保守）。</summary>
    private static string? ReadRawChainText(string text, ref int i)
    {
        if (i >= text.Length || !IsIdentifierStart(text[i])) return null;
        var start = i;
        while (i < text.Length)
        {
            if (IsIdentifierChar(text[i]))
            {
                i++;
                continue;
            }
            if (text[i] == '.')
            {
                i++;
                if (i < text.Length && IsIdentifierStart(text[i])) continue;
                return null;
            }
            if (text[i] == '(')
            {
                var close = FindMatchingParen(text, i);
                if (close < 0) return null;
                i = close + 1;
                continue;
            }
            break;
        }
        return text[start..i];
    }

    /// <summary>
    /// Round 17：raw 声明初始化表达式读取（顶层 ,/;/行尾停止；跳过字符串与注释），
    /// 供非 new 初始化表达式的类型推断。
    /// </summary>
    private static string? ReadExpressionUpToDelimiter(string text, ref int i)
    {
        var start = i;
        var depth = 0;
        while (i < text.Length)
        {
            var ch = text[i];
            if (ch == '"' || ch == '\'')
            {
                var close = SkipQuotedLiteral(text, i);
                if (close < 0) return null;
                i = close;
                continue;
            }
            if (ch == '/' && i + 1 < text.Length && (text[i + 1] == '/' || text[i + 1] == '*'))
            {
                var close = SkipComment(text, i);
                if (close < 0) return null;
                i = close;
                continue;
            }
            if (ch == '(' || ch == '[' || ch == '<') depth++;
            else if (ch == ')' || ch == ']' || ch == '>') depth--;
            else if ((ch == ',' || ch == ';') && depth <= 0) break;
            else if ((ch == '\r' || ch == '\n') && depth <= 0) break;
            i++;
        }
        return text[start..i].Trim();
    }

    private static bool IsSimpleIdentifier(string s)
    {
        if (s.Length == 0 || !IsIdentifierStart(s[0])) return false;
        for (var idx = 1; idx < s.Length; idx++)
        {
            if (!IsIdentifierChar(s[idx])) return false;
        }
        return true;
    }

    // ─── for-init 声明解析（I7） ───────────────────────────────────────

    /// <summary>
    /// 提取 for-init 文本（"int i = 0, j = 1"）中的声明变量名，并入变量表
    /// （类型未知用 "var" 占位：链式类型解析查不到该类型时保守不改写）。
    /// </summary>
    private static void CollectForInitDeclarations(string? initializer, Dictionary<string, string> variables)
    {
        if (string.IsNullOrEmpty(initializer)) return;
        var declaredType = false;
        foreach (var segment in SplitTopLevelByComma(initializer))
        {
            // 多声明延续段（"int i = 0, j = 1" 的 j）无类型前缀：前一声明带类型时视为声明
            var name = TryParseDeclarationName(segment, out var hasType);
            if (name != null && (hasType || declaredType)) variables[name] = "var";
            declaredType |= hasType;
        }
    }

    /// <summary>按顶层逗号分段（跳过括号/尖括号/字符串）。</summary>
    private static IEnumerable<string> SplitTopLevelByComma(string text)
    {
        var depth = 0;
        var start = 0;
        for (var i = 0; i < text.Length; i++)
        {
            var ch = text[i];
            if (ch == '"' || ch == '\'')
            {
                i = SkipQuotedLiteral(text, i) - 1;
                continue;
            }
            switch (ch)
            {
                case '(':
                case '[':
                case '{':
                case '<':
                    depth++;
                    break;
                case ')':
                case ']':
                case '}':
                case '>':
                    if (depth > 0) depth--;
                    break;
                case ',' when depth == 0:
                    yield return text[start..i];
                    start = i + 1;
                    break;
            }
        }
        yield return text[start..];
    }

    /// <summary>
    /// 解析声明段文本提取变量名："int i = 0" → (i, true)；"j"（多声明延续）→ (j, false)；
    /// 支持限定类型名/泛型/数组类型。hasType 表示段首为类型声明（延续段是否收集由调用方
    /// 依据前序声明判定，避免把 for (j = 1; ...) 的赋值形态误当声明）。
    /// </summary>
    private static string? TryParseDeclarationName(string segment, out bool hasType)
    {
        hasType = false;
        var text = segment.Trim();
        if (text.Length == 0) return null;
        var i = 0;
        var first = ReadIdentifier(text, ref i);
        if (first == null) return null;
        SkipWhitespace(text, ref i);
        while (i < text.Length && (text[i] == '.' || text[i] == '<' || text[i] == '['))
        {
            if (text[i] == '.')
            {
                i++;
                ReadIdentifier(text, ref i);
            }
            else if (text[i] == '<')
            {
                i = SkipBalancedForward(text, i, '<', '>');
            }
            else
            {
                i = SkipBalancedForward(text, i, '[', ']');
            }
            SkipWhitespace(text, ref i);
        }
        var name = ReadIdentifier(text, ref i);
        if (name != null)
        {
            hasType = true;   // 段首为类型，第二标识符是变量名
            return name;
        }
        return first;         // 无类型：变量名（延续声明或赋值段，由调用方判定）
    }

    /// <summary>跳过空白后读取标识符；无标识符返回 null。</summary>
    private static string? ReadIdentifier(string text, ref int i)
    {
        SkipWhitespace(text, ref i);
        if (i >= text.Length || !IsIdentifierStart(text[i])) return null;
        var start = i;
        i++;
        while (i < text.Length && IsIdentifierChar(text[i])) i++;
        return text[start..i];
    }

    private static void SkipWhitespace(string text, ref int i)
    {
        while (i < text.Length && char.IsWhiteSpace(text[i])) i++;
    }

    /// <summary>从 open 位置起跳过平衡的 open…close 区域，返回 close 后一位置。</summary>
    private static int SkipBalancedForward(string text, int i, char open, char close)
    {
        var depth = 0;
        for (; i < text.Length; i++)
        {
            if (text[i] == '"' || text[i] == '\'')
            {
                i = SkipQuotedLiteral(text, i) - 1;
                continue;
            }
            if (text[i] == open) depth++;
            else if (text[i] == close)
            {
                depth--;
                if (depth == 0) return i + 1;
            }
        }
        return text.Length;
    }

    /// <summary>返回文本中第一个顶层分号下标；无则返回 -1。</summary>
    private static int IndexOfTopLevelSemicolon(string text)
    {
        var depth = 0;
        for (var i = 0; i < text.Length; i++)
        {
            var ch = text[i];
            if (ch == '"' || ch == '\'')
            {
                i = SkipQuotedLiteral(text, i) - 1;
                continue;
            }
            switch (ch)
            {
                case '(':
                case '[':
                case '{':
                case '<':
                    depth++;
                    break;
                case ')':
                case ']':
                case '}':
                case '>':
                    if (depth > 0) depth--;
                    break;
                case ';' when depth == 0:
                    return i;
            }
        }
        return -1;
    }

    /// <summary>i 处是否为 lambda 箭头（-> 或 =>）。</summary>
    private static bool IsLambdaArrow(string text, int i)
        => (text[i] == '-' && text[i + 1] == '>') || (text[i] == '=' && text[i + 1] == '>');

