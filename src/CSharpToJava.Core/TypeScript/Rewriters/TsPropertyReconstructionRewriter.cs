    /// <summary>
    /// 逐类扫描自动生成访问器方法（get/set + 首字母大写）并按属性名配对，执行重组决策
    /// （字段简化 / getter / getter+setter / 只写 / 抽象），并注册调用点改写所需的方法名集合。
    /// </summary>
    private void AnalyzeClass(JavaClassDeclaration cls, ClassContext context)
    {
        var candidates = cls.Methods.Where(IsAutoAccessorCandidate).ToList();
        foreach (var group in candidates.GroupBy(m => m.Name.Substring(3)))
        {
            var propName = group.Key;
            var getter = group.FirstOrDefault(m => m.Name.StartsWith("get"));
            var setter = group.FirstOrDefault(m => m.Name.StartsWith("set"));

            if (getter == null)
            {
                // 只写属性（仅 setter）：无 TS 对应形态 → 维持方法发射 + 诊断注释
                if (setter != null && !setter.IsExplicitInterfaceImplementation)
                {
                    // WriteOnly 不注册任何方法名：setter 调用点保持方法形态（无 TS 属性可赋）
                    _roles[setter] = TsAccessorRole.WriteOnly;
                }
                continue;
            }

            if (getter.IsExplicitInterfaceImplementation) continue;
            if (setter != null && setter.IsExplicitInterfaceImplementation) continue;

            var isAbstract = (getter.Modifiers & JavaModifiers.Abstract) != 0
                          || (setter?.Modifiers & JavaModifiers.Abstract) != 0;

            if (isAbstract)
            {
                // 抽象访问器（I4）：发射 abstract get/set（无体），注册方法名供类链调用改写；
                // 抽象属性无后备字段，不做字段简化
                if (setter == null)
                {
                    _roles[getter] = TsAccessorRole.Getter;
                    RegisterAccessorNames(getter, context, registerSetter: false, TsAccessorRole.Getter);
                }
                else
                {
                    _roles[getter] = TsAccessorRole.GetterSetter;
                    _roles[setter] = TsAccessorRole.GetterSetter;
                    RegisterAccessorNames(getter, context, registerSetter: true, TsAccessorRole.GetterSetter);
                }
                continue;
            }

            if (setter == null)
            {
                // 只读属性（自动或表达式体）→ getter 访问器
                RenameConflictingBackingField(cls, context, propName, getter, null);
                _roles[getter] = TsAccessorRole.Getter;
                RegisterAccessorNames(getter, context, registerSetter: false, TsAccessorRole.Getter);
                continue;
            }

            var isRestrictedSetter = (setter.Modifiers & (JavaModifiers.Private | JavaModifiers.Protected)) != 0;
            var isTrivialAutoPair = !getter.IsBodyExpression && getter.StructuredBody == null && getter.Body != null
                                 && !setter.IsBodyExpression && setter.StructuredBody == null && setter.Body != null
                                 && (getter.Modifiers & JavaModifiers.Override) == 0   // I4：override 保持访问器对
                                 && !_inheritedPropertyNames.Contains(propName);   // R1：继承参与的属性统一禁字段简化

            if (isTrivialAutoPair && !isRestrictedSetter && !cls.IsConvertedFromStruct)
            {
                // 自动 get;set; 双访问器 → 字段简化：后备字段提升为属性字段、访问器方法移除
                var backingField = cls.Fields.LastOrDefault(f =>
                    f.Name == ToCamelCase(propName) && (f.Modifiers & JavaModifiers.Static) == (getter.Modifiers & JavaModifiers.Static));
                if (backingField != null)
                {
                    backingField.Name = propName;
                    backingField.Modifiers = (backingField.Modifiers & ~(JavaModifiers.Public | JavaModifiers.Protected | JavaModifiers.Private))
                                           | (getter.Modifiers & (JavaModifiers.Public | JavaModifiers.Protected | JavaModifiers.Private));
                    // C2：字段改名后同步刷新上下文字段表（链式解析按新名字查）
                    var camelName = ToCamelCase(propName);
                    if ((getter.Modifiers & JavaModifiers.Static) != 0)
                    {
                        context.StaticFieldTypes.Remove(camelName);
                        context.StaticFieldTypes[propName] = backingField.Type;
                    }
                    else
                    {
                        context.InstanceFieldTypes.Remove(camelName);
                        context.InstanceFieldTypes[propName] = backingField.Type;
                    }
                    _roles[getter] = TsAccessorRole.Field;
                    _roles[setter] = TsAccessorRole.Field;
                    cls.Methods.Remove(getter);
                    cls.Methods.Remove(setter);
                    RegisterAccessorNames(getter, context, registerSetter: true, TsAccessorRole.Field);
                    continue;
                }
            }

            // getter + setter（受限可见性或表达式体/无后备字段/override）→ 访问器对
            RenameConflictingBackingField(cls, context, propName, getter, setter);
            _roles[getter] = TsAccessorRole.GetterSetter;
            _roles[setter] = TsAccessorRole.GetterSetter;
            RegisterAccessorNames(getter, context, registerSetter: true, TsAccessorRole.GetterSetter);
        }
    }

    /// <summary>
    /// 接口访问器（Task 15 已合并发射为 readonly/普通属性）：仅注册调用点改写名。
    /// 只读接口属性（仅 getter）只注册 getter；get+set 接口属性注册两者；只写接口属性
    /// （仅 setter，方法形态保留）不注册。不产生 roles（发射路径仍由 EmitInterface 负责）。
    /// </summary>
    private static void AnalyzeInterface(JavaInterfaceDeclaration iface, ClassContext context)
    {
        foreach (var group in iface.Methods.Where(IsAutoAccessorCandidate).GroupBy(m => m.Name.Substring(3)))
        {
            var getter = group.FirstOrDefault(m => m.Name.StartsWith("get"));
            var setter = group.FirstOrDefault(m => m.Name.StartsWith("set"));
            if (getter == null) continue;   // 只写接口属性：setter 保持方法形态，不注册
            var isStatic = (getter.Modifiers & JavaModifiers.Static) != 0;
            var info = new AccessorInfo(group.Key, isStatic, iface.Name, setter != null ? TsAccessorRole.GetterSetter : TsAccessorRole.Getter, getter.ReturnType);
            context.AccessorMap["get" + group.Key] = info;
            if (setter != null)
            {
                context.AccessorMap["set" + group.Key] = info;
            }
        }
    }

    /// <summary>
    /// 将访问器方法名登记到调用点改写集合：getter 名（Field/Getter/GetterSetter/抽象）与
    /// setter 名（Field/GetterSetter）会改写为成员访问/赋值；WriteOnly 不登记（方法保留）。
    /// </summary>
    private void RegisterAccessorNames(JavaMethodDeclaration accessor, ClassContext context, bool registerSetter, TsAccessorRole role)
    {
        var propName = accessor.Name.Substring(3);
        var isStatic = (accessor.Modifiers & JavaModifiers.Static) != 0;
        var info = new AccessorInfo(propName, isStatic, context.ClassName, role, accessor.ReturnType);
        context.AccessorMap["get" + propName] = info;
        if (registerSetter)
        {
            context.AccessorMap["set" + propName] = info;
        }
    }

    /// <summary>
    /// 派生访问器后备字段与基类同名字段冲突（TS2415：派生/基类同名 private 字段为硬错误，
    /// virtual + override 自动属性各自生成独立后备字段时必触发）：派生侧字段改名（camelCase
    /// 加 "_" 后缀，保持 C# 独立存储语义），同步访问器体文本与上下文字段表。
    /// </summary>
    private void RenameConflictingBackingField(JavaClassDeclaration cls, ClassContext context,
        string propName, JavaMethodDeclaration getter, JavaMethodDeclaration? setter)
    {
        var camel = ToCamelCase(propName);
        var backingField = cls.Fields.FirstOrDefault(f => f.Name == camel);
        if (backingField == null) return;
        if (!HasFieldInBaseChain(context, camel)) return;
        var newName = camel + "_";
        backingField.Name = newName;
        if (getter.Body != null) getter.Body = ReplaceIdentifier(getter.Body, camel, newName);
        if (setter?.Body != null) setter.Body = ReplaceIdentifier(setter.Body, camel, newName);
        if ((backingField.Modifiers & JavaModifiers.Static) != 0)
        {
            context.StaticFieldTypes.Remove(camel);
            context.StaticFieldTypes[newName] = backingField.Type;
        }
        else
        {
            context.InstanceFieldTypes.Remove(camel);
            context.InstanceFieldTypes[newName] = backingField.Type;
        }
    }

    /// <summary>基类链（不含当前类）是否存在同名字段（visited 防循环继承环，C1）。</summary>
    private bool HasFieldInBaseChain(ClassContext context, string fieldName, HashSet<string>? visited = null)
    {
        visited ??= new HashSet<string>(StringComparer.Ordinal);
        if (!visited.Add(context.ClassName)) return false;
        try
        {
            foreach (var baseName in context.BaseTypeNames)
            {
                if (_typeContextsByName.TryGetValue(baseName, out var baseCtx))
                {
                    if (baseCtx.InstanceFieldTypes.ContainsKey(fieldName)
                        || baseCtx.StaticFieldTypes.ContainsKey(fieldName))
                    {
                        return true;
                    }
                    if (HasFieldInBaseChain(baseCtx, fieldName, visited)) return true;
                }
            }
            return false;
        }
        finally
        {
            visited.Remove(context.ClassName);
        }
    }

    /// <summary>文本中标识符边界的名字替换（跳过字符串/注释；点号后成员名同样命中）。</summary>
    private static string ReplaceIdentifier(string text, string oldName, string newName)
    {
        var sb = new StringBuilder(text.Length);
        var i = 0;
        while (i < text.Length)
        {
            var ch = text[i];
            if (ch == '"' || ch == '\'')
            {
                var start = i;
                i = SkipQuotedLiteral(text, i);
                sb.Append(text, start, i - start);
                continue;
            }
            if (ch == '/' && i + 1 < text.Length && (text[i + 1] == '/' || text[i + 1] == '*'))
            {
                var start = i;
                i = SkipComment(text, i);
                sb.Append(text, start, i - start);
                continue;
            }
            if (IsIdentifierStart(ch) && AtIdentifierBoundaryBefore(text, i))
            {
                var nameEnd = i + 1;
                while (nameEnd < text.Length && IsIdentifierChar(text[nameEnd])) nameEnd++;
                var name = text[i..nameEnd];
                if (name == oldName)
                {
                    sb.Append(newName);
                    i = nameEnd;
                    continue;
                }
            }
            sb.Append(ch);
            i++;
        }
        return sb.ToString();
    }

    /// <summary>
    /// 解析 this./super./裸调用（隐式 this）：当前类型 → 基类链（本单元内已分析）。
    /// 调用方的类型已知，不按全局集合匹配（C1：否则会误改同名跨类访问器）；基类不在
    /// 本单元内时不改写（多文件/项目模式 M5 处理，L3 兜底）。
    /// </summary>
    private bool TryResolveAccessor(string methodName, out AccessorInfo info)
    {
        info = null!;
        if (_classStack.Count == 0) return false;
        var context = _classStack.Peek();
        if (context.AccessorMap.TryGetValue(methodName, out info!))
        {
            return true;
        }
        foreach (var baseName in context.BaseTypeNames)
        {
            if (TryResolveAccessorInContext(baseName, methodName, out info!)) return true;
        }
        return false;
    }

    /// <summary>
    /// 在基类链（不含当前类型）中解析访问器（R2：super 目标按基类成员形态改写）。
    /// </summary>
    private bool TryResolveBaseAccessor(string methodName, out AccessorInfo info)
    {
        info = null!;
        if (_classStack.Count == 0) return false;
        foreach (var baseName in _classStack.Peek().BaseTypeNames)
        {
            if (TryResolveAccessorInContext(baseName, methodName, out info!)) return true;
        }
        return false;
    }

    private bool TryResolveAccessorInContext(string typeName, string methodName, out AccessorInfo info,
        HashSet<string>? visited = null)
    {
        info = null!;
        // C1：IR 级循环继承（self-extends/互相 extends）→ 访问集合防栈溢出，解析中止于环
        visited ??= new HashSet<string>(StringComparer.Ordinal);
        if (!visited.Add(typeName)) return false;
        try
        {
            if (!_typeContextsByName.TryGetValue(typeName, out var ctx)) return false;
            if (ctx.AccessorMap.TryGetValue(methodName, out info!)) return true;
            foreach (var baseName in ctx.BaseTypeNames)
            {
                if (TryResolveAccessorInContext(baseName, methodName, out info!, visited)) return true;
            }
            return false;
        }
        finally
        {
            visited.Remove(typeName);
        }
    }

    private static bool IsAutoAccessorCandidate(JavaMethodDeclaration m)
    {
        if (!m.IsAutoGenerated || m.Name.Length <= 3) return false;
        var isGet = m.Name.StartsWith("get");
        var isSet = m.Name.StartsWith("set");
        if (!isGet && !isSet) return false;
        if (m.Name[3] is not (>= 'A' and <= 'Z')) return false;
        if (isGet && m.Parameters.Count != 0) return false;   // 索引器形态 getItem(index) 不重组
        if (isSet && m.Parameters.Count != 1) return false;
        return true;
    }

    private static string ToCamelCase(string name)
        => name.Length == 0 ? name : char.ToLowerInvariant(name[0]) + name[1..];

    // ─── 目标类型解析（C1 dot-target 保守改写） ───────────────────────

    /// <summary>
    /// 解析表达式可确定的类型名（仅本单元已知类型）：标识符（方法参数/局部变量/当前类字段/
    /// 类型名）、this（当前类型名）、new/cast/raw(ResolvedType)/括号/成员访问/数组元素。
    /// 无法解析 → null（调用点保持方法形态，保守不改写）。
    /// </summary>
    private string? ResolveExpressionType(JavaExpression expr)
    {
        switch (expr)
        {
            case JavaIdentifierExpression id:
                return ResolveIdentifierType(id.Name);
            case JavaThisExpression thisExpr when !thisExpr.IsSuper:
                return _classStack.Count > 0 ? _classStack.Peek().ClassName : null;
            case JavaNewExpression newExpr:
                return newExpr.Type;
            case JavaCastExpression cast:
                return cast.Type;
            case JavaRawExpression raw:
                return raw.ResolvedType;
            case JavaParenthesizedExpression paren:
                return ResolveExpressionType(paren.InnerExpression);
            case JavaMemberAccessExpression access:
            {
                var targetType = ResolveExpressionType(access.Target);
                if (targetType == null || !_typeContextsByName.TryGetValue(targetType, out var ctx))
                {
                    return null;
                }
                // C2：成员访问按段解析——字段 → 属性访问器（getter）→ 基类链成员（InheritedField）
                return ResolveMemberTypeInContext(ctx, access.MemberName);
            }
            case JavaMethodCallExpression call:
            {
                // R-2：结构化链方法调用段（d.getB()）——属性 getter 优先，其次用户方法返回类型；
                // 裸调用（Target == null）无类型信息，保守 null
                if (call.Target == null) return null;
                var callTargetType = ResolveExpressionType(call.Target);
                if (callTargetType == null || !_typeContextsByName.TryGetValue(callTargetType, out var callCtx)) return null;
                if (callCtx.AccessorMap.TryGetValue(call.MethodName, out var accInfo)) return accInfo.Type;
                return callCtx.MethodReturnTypes.TryGetValue(MethodReturnKey(call.MethodName, call.Arguments.Count), out var retType) ? retType : null;
            }
            case JavaArrayAccessExpression arrayAccess:
            {
                var elementType = ResolveExpressionType(arrayAccess.Target);
                if (elementType != null && elementType.EndsWith("[]", StringComparison.Ordinal))
                {
                    return elementType[..^2].Trim();
                }
                return null;
            }
            default:
                return null;
        }
    }

    /// <summary>
    /// 在类型上下文中解析成员类型（C2 链式段解析 + InheritedField）：本类字段 → 本类属性
    /// 访问器（getter 注册名）→ 基类链递归（基类字段/属性对派生类可见）。
    /// </summary>
    private string? ResolveMemberTypeInContext(ClassContext ctx, string memberName, HashSet<string>? visited = null)
    {
        // C1：循环继承环 → 访问集合防栈溢出
        visited ??= new HashSet<string>(StringComparer.Ordinal);
        if (!visited.Add(ctx.ClassName)) return null;
        try
        {
            if (ctx.InstanceFieldTypes.TryGetValue(memberName, out var fieldType)) return fieldType;
            if (ctx.StaticFieldTypes.TryGetValue(memberName, out fieldType)) return fieldType;
            if (ctx.AccessorMap.TryGetValue("get" + memberName, out var accessor)) return accessor.Type;
            foreach (var baseName in ctx.BaseTypeNames)
            {
                if (_typeContextsByName.TryGetValue(baseName, out var baseCtx))
                {
                    var baseType = ResolveMemberTypeInContext(baseCtx, memberName, visited);
                    if (baseType != null) return baseType;
                }
            }
            return null;
        }
        finally
        {
            visited.Remove(ctx.ClassName);
        }
    }

    /// <summary>
    /// 解析标识符的类型：当前方法参数/局部变量 → 当前类型字段 → 类型名（静态访问）。
    /// </summary>
    private string? ResolveIdentifierType(string name)
    {
        if (_methodStack.Count > 0 && _methodStack.Peek().VariableTypes.TryGetValue(name, out var variableType))
        {
            return variableType;
        }
        if (_classStack.Count > 0)
        {
            var context = _classStack.Peek();
            if (context.InstanceFieldTypes.TryGetValue(name, out variableType)) return variableType;
            if (context.StaticFieldTypes.TryGetValue(name, out variableType)) return variableType;
        }
        return _typeContextsByName.ContainsKey(name) ? name : null;
    }

    // ─── 结构化调用点改写 ─────────────────────────────────────────────

    /// <summary>
    /// 结构化 JavaMethodCallExpression → 属性成员访问/赋值（仅命中重建集合的方法名）。
    /// 裸/this/super 按当前类型 + 基类链解析；dot-target 仅当目标类型可解析且该类型
    /// 注册了该访问器名时改写（C1 保守策略）。
    /// </summary>
    private bool TryRewriteCall(JavaMethodCallExpression call, out JavaExpression replacement)
    {
        replacement = null!;
        AccessorInfo info;
        JavaExpression replacementTarget;

        if (call.Target == null || call.Target is JavaThisExpression)
        {
            // 裸/this/super：按当前类型 + 基类链解析（不依赖全局名集合）
            if (!TryResolveAccessor(call.MethodName, out info)) return false;
            replacementTarget = call.Target ?? CreateBareTarget(info);
            if (call.Target is JavaThisExpression targetThis)
            {
                if (targetThis.IsSuper)
                {
                    // R2：基类成员是重建后的访问器 → 保留 super（TS 允许 super 访问基类访问器）；
                    // 基类成员是简化字段 → this（TS2855 仅限基类字段）；基类不在本单元 → 保守保留 super
                    if (info.IsStatic)
                    {
                        replacementTarget = CreateBareTarget(info);
                    }
                    else if (TryResolveBaseAccessor(call.MethodName, out var baseInfo) && baseInfo.Role == TsAccessorRole.Field)
                    {
                        replacementTarget = new JavaThisExpression { IsSuper = false };
                    }
                    else
                    {
                        replacementTarget = targetThis;
                    }
                }
                else if (info.IsStatic)
                {
                    // this 目标访问静态属性 → 声明类名
                    replacementTarget = CreateBareTarget(info);
                }
            }
        }
        else
        {
            // dot-target：仅当目标类型可解析且该类型（含基类链）注册了该访问器名时才改写
            var typeName = ResolveExpressionType(call.Target);
            if (typeName == null) return false;
            if (!TryResolveAccessorInContext(typeName, call.MethodName, out info)) return false;
            replacementTarget = call.Target;
        }

        var isGetter = call.MethodName.StartsWith("get");
        var isSetter = call.MethodName.StartsWith("set");
        if (isGetter && call.Arguments.Count != 0) return false;
        if (isSetter && call.Arguments.Count != 1) return false;

        var memberAccess = new JavaMemberAccessExpression { Target = replacementTarget, MemberName = info.PropertyName };

        if (isGetter)
        {
            replacement = memberAccess;
            return true;
        }
        replacement = new JavaAssignmentExpression
        {
            Target = memberAccess,
            Operator = "=",
            Value = call.Arguments[0],
        };
        return true;
    }

    /// <summary>
    /// 裸调用（IR Target == null，Java 隐式 this/类名目标）：实例属性 → this.X；
    /// 静态属性 → 声明类名.X。
    /// </summary>
    private static JavaExpression CreateBareTarget(AccessorInfo info)
    {
        if (info.IsStatic && info.OwnerClassName.Length > 0)
        {
            return new JavaIdentifierExpression(info.OwnerClassName);
        }
        return new JavaThisExpression();
    }

    // ─── raw 文本调用点改写 ───────────────────────────────────────────

    /// <summary>
    /// 扫描改写 raw Java 文本中的属性访问器调用：target.getX() → target.X；
    /// target.setX(v) → target.X = v（v 递归改写）；裸调用补 this./类名. 前缀，
    /// super 目标落到 this。跳过字符串/字符字面量与注释区域；getter 要求 0 参、
    /// setter 要求单个顶层实参。dot-target 仅当目标标识符类型可解析且注册过才改写（C1）。
    /// </summary>
    private string RewriteAccessorCalls(string text)
    {
        if (string.IsNullOrEmpty(text)) return text;

        var sb = new StringBuilder(text.Length);
        var pendingTargetStart = -1;
        var pendingTargetName = string.Empty;
        var i = 0;
        while (i < text.Length)
        {
            var ch = text[i];
            if (ch == '"' || ch == '\'')
            {
                var start = i;
                i = SkipQuotedLiteral(text, i);
                sb.Append(text, start, i - start);
                continue;
            }
            if (ch == '/' && i + 1 < text.Length && (text[i + 1] == '/' || text[i + 1] == '*'))
            {
                var start = i;
                i = SkipComment(text, i);
                sb.Append(text, start, i - start);
                continue;
            }
            if (IsIdentifierStart(ch) && AtIdentifierBoundaryBefore(text, i))
            {
                var nameEnd = i + 1;
                while (nameEnd < text.Length && IsIdentifierChar(text[nameEnd])) nameEnd++;
                var name = text[i..nameEnd];
                if (nameEnd < text.Length && text[nameEnd] == '('
                    && (IsThisOrSuperTarget(text, i)
                        ? TryResolveAccessor(name, out var info)
                        : TryResolveRawDotTarget(text, i, name, out info)))
                {
                    var close = FindMatchingParen(text, nameEnd);
                    if (close < 0)
                    {
                        sb.Append(ch);
                        i++;
                        continue;
                    }
                    var argText = text[(nameEnd + 1)..close];
                    var isGetter = name.StartsWith("get");
                    if (isGetter && argText.Trim().Length == 0)
                    {
                        sb.Append(BuildPropertyAccess(text, i, name, info, null, sb, pendingTargetStart, pendingTargetName));
                        i = close + 1;
                        continue;
                    }
                    if (name.StartsWith("set") && IsSingleTopLevelArg(argText))
                    {
                        var rewrittenArg = RewriteAccessorCalls(argText.Trim());
                        sb.Append(BuildPropertyAccess(text, i, name, info, rewrittenArg, sb, pendingTargetStart, pendingTargetName));
                        i = close + 1;
                        continue;
                    }
                }
                if (nameEnd < text.Length && text[nameEnd] == '.')
                {
                    // 记录点号目标段起点（super./this. 回滚用，I3）
                    pendingTargetStart = sb.Length;
                    pendingTargetName = name;
                }
            }
            sb.Append(ch);
            i++;
        }
        return sb.ToString();
    }

    /// <summary>
    /// 解析 raw 文本中 dot-target 调用链并查访问器注册（C2 链式逐段解析）：
    /// "o.m.i.getX()" / "arr[0].getX()" / "b.getA().getX()" 逐段解析（参数/局部变量/
    /// 字段/属性访问器/数组元素/类型名），任何一段不可解析或末端类型未注册该访问器名
    /// → 保守保持方法调用（C1 策略延续）。
    /// </summary>
    private bool TryResolveRawDotTarget(string text, int nameStart, string methodName, out AccessorInfo info)
    {
        info = null!;
        if (nameStart == 0 || text[nameStart - 1] != '.') return false;
        var segments = ExtractRawChainSegments(text, nameStart - 1);
        if (segments == null || segments.Count == 0) return false;
        string? currentType = null;
        foreach (var segment in segments)
        {
            currentType = ResolveRawSegment(segment, currentType);
            if (currentType == null) return false;
        }
        // 末端访问器查注册：当前类型 → 基类链递归（R-1：静态属性经派生类名访问等）
        return TryResolveAccessorInContext(currentType, methodName, out info);
    }

    private sealed record RawChainSegment(string? Name, bool IsArray, bool IsCall, int ArgCount = 0);

    /// <summary>
    /// 从方法名前的点号回扫提取链段（正向顺序）：标识符段（b/a）、数组访问段（arr[0]）、
    /// 方法调用段（b.getA() 的属性 getter 链）。任何形态不可识别 → null（保守不改写）。
    /// </summary>
    private static List<RawChainSegment>? ExtractRawChainSegments(string text, int beforeName)
    {
        var reversed = new List<RawChainSegment>();
        var pos = beforeName;   // 指向方法名前的 '.'
        while (pos >= 0 && text[pos] == '.')
        {
            pos--;
            if (pos < 0) return null;
            if (text[pos] == ')')
            {
                // 调用段 getA()：反向找匹配 '('
                var open = FindMatchingOpenBackward(text, pos, '(', ')');
                if (open < 0) return null;
                var start = open;
                while (start > 0 && IsIdentifierChar(text[start - 1])) start--;
                if (start == open) return null;
                reversed.Add(new RawChainSegment(text[start..open], false, true, CountTopLevelArgs(text[(open + 1)..pos])));
                pos = start - 1;
            }
            else if (text[pos] == ']')
            {
                // 数组访问段 [expr]：反向找匹配 '['
                var openBracket = FindMatchingOpenBackward(text, pos, '[', ']');
                if (openBracket < 0) return null;
                reversed.Add(new RawChainSegment(null, true, false));
                pos = openBracket - 1;
                if (pos < 0) return null;
                if (text[pos] == ')')
                {
                    // R-7：下标作用于调用结果（getA()[0]）：'[' 前是 ')' → 先解析调用段
                    var open = FindMatchingOpenBackward(text, pos, '(', ')');
                    if (open < 0) return null;
                    var start = open;
                    while (start > 0 && IsIdentifierChar(text[start - 1])) start--;
                    if (start == open) return null;
                    reversed.Add(new RawChainSegment(text[start..open], false, true, CountTopLevelArgs(text[(open + 1)..pos])));
                    pos = start - 1;
                }
                else if (IsIdentifierChar(text[pos]))
                {
                    var end = pos + 1;
                    while (pos >= 0 && IsIdentifierChar(text[pos])) pos--;
                    reversed.Add(new RawChainSegment(text[(pos + 1)..end], false, false));
                }
                else
                {
                    return null;
                }
            }
            else if (IsIdentifierChar(text[pos]))
            {
                var end = pos + 1;
                while (pos >= 0 && IsIdentifierChar(text[pos])) pos--;
                reversed.Add(new RawChainSegment(text[(pos + 1)..end], false, false));
            }
            else
            {
                return null;
            }
        }
        reversed.Reverse();
        return reversed;
    }

    /// <summary>
    /// 解析单段类型：首段（currentType == null）为标识符（参数/局部变量/字段/类型名/
    /// this；super 链为既有缺口，保守 null）；后续段为成员（字段/属性访问器/基类成员）
    /// 或数组元素。解析失败 → null（调用点保持方法形态）。
    /// </summary>
    private string? ResolveRawSegment(RawChainSegment segment, string? currentType)
    {
        if (segment.IsArray)
        {
            if (currentType == null) return null;
            return currentType.EndsWith("[]", StringComparison.Ordinal) ? currentType[..^2].Trim() : null;
        }
        if (currentType == null)
        {
            var name = segment.Name!;
            if (name == "this")
            {
                return _classStack.Count > 0 ? _classStack.Peek().ClassName : null;
            }
            if (name == "super")
            {
                // super 链（super.A.getX()）既有缺口：基类成员逐级解析未实现，保守不改写
                return null;
            }
            return ResolveIdentifierType(name);
        }
        if (segment.IsCall)
        {
            // 调用段 getA()/getB()：属性 getter（AccessorMap）优先，其次用户方法返回类型（R-2）
            if (!_typeContextsByName.TryGetValue(currentType, out var ctx)) return null;
            if (ctx.AccessorMap.TryGetValue(segment.Name!, out var accInfo)) return accInfo.Type;
            return ctx.MethodReturnTypes.TryGetValue(MethodReturnKey(segment.Name!, segment.ArgCount), out var retType) ? retType : null;
        }
        if (!_typeContextsByName.TryGetValue(currentType, out var typeContext)) return null;
        return ResolveMemberTypeInContext(typeContext, segment.Name!);
    }

    /// <summary>
    /// 生成属性访问文本：target.getX() → target.X / target.setX(v) → target.X = v。
    /// 目标为点号前缀时沿用 output 中已累积的目标文本（去掉末尾点号）；super 目标回滚
    /// 已累积的 "super." 后补 this.（TS 无 super 属性访问 TS2855），this 访问静态属性
    /// 回滚后补类名；裸调用补 this./类名.。
    /// </summary>
    private string BuildPropertyAccess(string text, int nameStart, string methodName, AccessorInfo info, string? rewrittenArg,
        StringBuilder output, int pendingTargetStart, string pendingTargetName)
    {
        var precededByDot = nameStart > 0 && text[nameStart - 1] == '.';
        var sb = new StringBuilder();
        if (precededByDot)
        {
            var targetName = RawTargetIdentifier(text, nameStart);
            if (targetName == "super" || (targetName == "this" && info.IsStatic))
            {
                // R2：super 目标按基类成员形态改写——基类成员是重建后的访问器 → 保留
                // super（TS 允许基类访问器 super 访问；无递归）；基类成员是简化字段 →
                // this（TS2855 仅限基类字段）；基类不在本单元 → 保守保留 super（显式
                // 报错优于静默递归）。this 目标访问静态属性 → 回滚补类名。
                var keepSuper = targetName == "super" && !info.IsStatic
                    && (!TryResolveBaseAccessor(methodName, out var baseInfo) || baseInfo.Role != TsAccessorRole.Field);
                if (!keepSuper)
                {
                    // 回滚已累积的 "super."/"this." 目标文本，改补 this./类名. 前缀
                    if (pendingTargetStart >= 0 && pendingTargetName == targetName)
                    {
                        output.Length = pendingTargetStart;
                    }
                    sb.Append(info.IsStatic && info.OwnerClassName.Length > 0 ? info.OwnerClassName + "." : "this.");
                }
            }
            sb.Append(info.PropertyName);
            if (rewrittenArg != null) sb.Append(" = ").Append(rewrittenArg);
            return sb.ToString();
        }
        sb.Append(info.IsStatic && info.OwnerClassName.Length > 0 ? info.OwnerClassName + "." : "this.");
        sb.Append(info.PropertyName);
        if (rewrittenArg != null) sb.Append(" = ").Append(rewrittenArg);
        return sb.ToString();
    }

    /// <summary>取 nameStart 之前紧邻点号目标的标识符（无目标返回空串）。</summary>
    private static string RawTargetIdentifier(string text, int nameStart)
    {
        if (nameStart == 0 || text[nameStart - 1] != '.') return string.Empty;
        var targetEnd = nameStart - 1;
        var targetStart = targetEnd;
        while (targetStart > 0 && IsIdentifierChar(text[targetStart - 1])) targetStart--;
        return text[targetStart..targetEnd];
    }

    // ─── 访问器体字段限定（P1/I5） ────────────────────────────────────

    /// <summary>
    /// 将访问器方法体 raw 文本中的裸字段标识符补 this./类名. 前缀（tsc TS2663）。
    /// 仅限定当前类型字段名（实例 → this.，静态 → 类名.）；排除方法参数与结构化局部变量
    /// （P1：setter 参数 value 与字段同名不得误限）；跳过点号成员名、方法调用、
    /// 字符串/字符字面量与注释。
    /// </summary>
    private string QualifyFieldReferences(string text)
    {
        if (string.IsNullOrEmpty(text) || _classStack.Count == 0) return text;

        var context = _classStack.Peek();
        var excluded = _methodStack.Count > 0
            ? new HashSet<string>(_methodStack.Peek().NonFieldNames, StringComparer.Ordinal)
            : null;
        if (_shadowStack.Count > 0 && _shadowStack.Peek().Count > 0)
        {
            excluded ??= new HashSet<string>(StringComparer.Ordinal);
            excluded.UnionWith(_shadowStack.Peek());   // I8：结构化 lambda 参数
        }
        var sb = new StringBuilder(text.Length);
        var i = 0;
        while (i < text.Length)
        {
            var ch = text[i];
            if (ch == '"' || ch == '\'')
            {
                var start = i;
                i = SkipQuotedLiteral(text, i);
                sb.Append(text, start, i - start);
                continue;
            }
            if (ch == '/' && i + 1 < text.Length && (text[i + 1] == '/' || text[i + 1] == '*'))
            {
                var start = i;
                i = SkipComment(text, i);
                sb.Append(text, start, i - start);
                continue;
            }
            if (ch == '(' && excluded != null)
            {
                // I8：括号形态 lambda 参数 (a, b) -> / =>
                var close = FindMatchingParen(text, i);
                if (close >= 0)
                {
                    var after = close + 1;
                    SkipWhitespace(text, ref after);
                    if (after + 1 < text.Length && IsLambdaArrow(text, after))
                    {
                        foreach (var segment in SplitTopLevelByComma(text[(i + 1)..close]))
                        {
                            var pname = TryParseDeclarationName(segment, out _);
                            if (pname != null) excluded.Add(pname);
                        }
                    }
                }
            }
            if (IsIdentifierStart(ch) && AtIdentifierBoundaryBefore(text, i))
            {
                var nameEnd = i + 1;
                while (nameEnd < text.Length && IsIdentifierChar(text[nameEnd])) nameEnd++;
                var name = text[i..nameEnd];
                var precededByDot = i > 0 && text[i - 1] == '.';
                var afterName = nameEnd;
                SkipWhitespace(text, ref afterName);
                var followedByParen = afterName < text.Length && text[afterName] == '(';
                if (!precededByDot)
                {
                    if (name == "for" && followedByParen)
                    {
                        // I7：raw 经典 for 头声明段变量（for (int i = 0, j = 1; ...)）
                        if (excluded != null)
                        {
                            var close = FindMatchingParen(text, afterName);
                            if (close >= 0)
                            {
                                var header = text[(afterName + 1)..close];
                                var semi = IndexOfTopLevelSemicolon(header);
                                var init = semi < 0 ? header : header[..semi];
                                var names = new Dictionary<string, string>(StringComparer.Ordinal);
                                CollectForInitDeclarations(init, names);
                                excluded.UnionWith(names.Keys);
                            }
                        }
                    }
                    if (!followedByParen && excluded != null)
                    {
                        // I8：raw 单参数 lambda 形态 ident -> / ident =>
                        if (afterName + 1 < text.Length && IsLambdaArrow(text, afterName))
                        {
                            excluded.Add(name);
                        }
                    }
                }
                if (!precededByDot && !followedByParen)
                {
                    if (excluded == null || !excluded.Contains(name))
                    {
                        if (context.InstanceFieldTypes.ContainsKey(name))
                        {
                            sb.Append("this.").Append(name);
                            i = nameEnd;
                            continue;
                        }
                        if (context.StaticFieldTypes.ContainsKey(name))
                        {
                            sb.Append(context.ClassName).Append('.').Append(name);
                            i = nameEnd;
                            continue;
                        }
                    }
                }
            }
            sb.Append(ch);
            i++;
        }
        return sb.ToString();
    }

    /// <summary>
    /// 结构化表达式中的裸字段标识符 → this./类名. 成员访问（TS2663）；排除参数/局部变量。
    /// </summary>
    private JavaExpression? QualifyIdentifier(string name)
    {
        if (_classStack.Count == 0) return null;
        var context = _classStack.Peek();
        if (_methodStack.Count > 0 && _methodStack.Peek().NonFieldNames.Contains(name)) return null;
        if (_shadowStack.Count > 0 && _shadowStack.Peek().Contains(name)) return null;   // I8：lambda 参数遮蔽
        if (context.InstanceFieldTypes.ContainsKey(name))
        {
            return new JavaMemberAccessExpression { Target = new JavaThisExpression(), MemberName = name };
        }
        if (context.StaticFieldTypes.ContainsKey(name))
        {
            return new JavaMemberAccessExpression
            {
                Target = new JavaIdentifierExpression(context.ClassName),
                MemberName = name,
            };
        }
        return null;
    }

    // ─── 文本扫描工具 ─────────────────────────────────────────────────

    private static bool IsIdentifierStart(char c) => char.IsLetter(c) || c == '_' || c == '$';

    private static bool IsIdentifierChar(char c) => char.IsLetterOrDigit(c) || c == '_' || c == '$';

    /// <summary>调用名前的标识符边界（前一个字符不是标识符字符且不是点号）。</summary>
    private static bool AtIdentifierBoundaryBefore(string text, int index)
    {
        if (index == 0) return true;
        var prev = text[index - 1];
        return !IsIdentifierChar(prev);
    }

    /// <summary>
    /// 判断调用是否为 this./super./裸调用（隐式 this）：裸调用与非 this/super 点号目标
    /// 走不同解析路径（裸/this/super 按当前类型 + 基类链，其他按目标类型解析，C1）。
    /// </summary>
    private static bool IsThisOrSuperTarget(string text, int nameStart)
    {
        if (nameStart == 0) return true;
        if (text[nameStart - 1] != '.') return true;
        var identEnd = nameStart - 1;
        var identStart = identEnd;
        while (identStart > 0 && IsIdentifierChar(text[identStart - 1])) identStart--;
        var target = text[identStart..identEnd];
        return target == "this" || target == "super";
    }

    /// <summary>跳过自 start 起的字符串/字符字面量（含反斜杠转义），返回闭合引号后一位置。</summary>
    private static int SkipQuotedLiteral(string text, int start)
    {
        var quote = text[start];
        var i = start + 1;
        while (i < text.Length)
        {
            if (text[i] == '\\' && i + 1 < text.Length)
            {
                i += 2;
                continue;
            }
            if (text[i] == quote) return i + 1;
            i++;
        }
        return text.Length;
    }

    /// <summary>跳过自 start 起的 // 行注释或 /* */ 块注释，返回注释后一位置。</summary>
    private static int SkipComment(string text, int start)
    {
        if (start + 1 < text.Length && text[start + 1] == '/')
        {
            var end = text.IndexOf('\n', start + 2);
            return end < 0 ? text.Length : end + 1;
        }
        var close = text.IndexOf("*/", start + 2, StringComparison.Ordinal);
        return close < 0 ? text.Length : close + 2;
    }

    /// <summary>从 openIndex 起的 '(' 找匹配的 ')'（跳过字符串/字符字面量），返回下标；无匹配返回 -1。</summary>
    private static int FindMatchingParen(string text, int openIndex)
    {
        var depth = 0;
        for (var i = openIndex; i < text.Length; i++)
        {
            var ch = text[i];
            if (ch == '"' || ch == '\'')
            {
                i = SkipQuotedLiteral(text, i) - 1;
                continue;
            }
            if (ch == '(') depth++;
            else if (ch == ')')
            {
                depth--;
                if (depth == 0) return i;
            }
        }
        return -1;
    }

    /// <summary>从 closeIndex（')' 或 ']'）反向找匹配的 '(' / '['，返回下标；无匹配返回 -1。</summary>
    private static int FindMatchingOpenBackward(string text, int closeIndex, char open, char close)
    {
        var depth = 0;
        for (var i = closeIndex; i >= 0; i--)
        {
            var ch = text[i];
            if (ch == '"' || ch == '\'')
            {
                i = SkipQuotedLiteralBackward(text, i);
                if (i < 0) return -1;
                continue;
            }
            if (ch == close) depth++;
            else if (ch == open)
            {
                depth--;
                if (depth == 0) return i;
            }
        }
        return -1;
    }

    /// <summary>从闭引号 end 反向找开引号下标（跳过转义），无匹配返回 -1。</summary>
    private static int SkipQuotedLiteralBackward(string text, int end)
    {
        var quote = text[end];
        var i = end - 1;
        while (i >= 0)
        {
            if (text[i] == '\\')
            {
                i -= 2;
                continue;
            }
            if (text[i] == quote) return i;
            i--;
        }
        return -1;
    }

    /// <summary>实参文本是否为单个顶层实参（无顶层逗号）。</summary>
    private static bool IsSingleTopLevelArg(string argText)
        => CountTopLevelArgs(argText) == 1;

    /// <summary>实参文本的顶层实参个数（空白 → 0；其余为顶层逗号分隔计数 + 1；R-6 调用段键控）。</summary>
    private static int CountTopLevelArgs(string argText)
    {
        if (string.IsNullOrWhiteSpace(argText)) return 0;
        var count = 1;
        var depth = 0;
        for (var i = 0; i < argText.Length; i++)
        {
            var ch = argText[i];
            if (ch == '"' || ch == '\'')
            {
                i = SkipQuotedLiteral(argText, i) - 1;
                continue;
            }
            switch (ch)
            {
                case '(':
                case '[':
                case '{':
                case '<':
                    depth++;
                    break;
                case ')':
                case ']':
                case '}':
                case '>':
                    depth--;
                    break;
                default:
                    if (ch == ',' && depth == 0) count++;
                    break;
            }
        }
        return count;
    }
