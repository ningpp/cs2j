    [Fact]
    public void Structured_Lambda_Parameter_Is_Not_Qualified()
    {
        var cls = ClassWith("Demo", fields: [BackingField("x")]);
        cls.Methods.Add(new JavaMethodDeclaration
        {
            Name = "getCount",
            ReturnType = "int",
            Modifiers = JavaModifiers.Public,
            IsAutoGenerated = true,
            StructuredBody = new JavaMethodBody(
            [
                new JavaExpressionStatement(new JavaMethodCallExpression
                {
                    MethodName = "apply",
                    Arguments =
                    {
                        new JavaLambdaExpression
                        {
                            Parameters = { "x" },
                            ExpressionBody = new JavaRawExpression("x * 2"),
                        },
                    },
                }),
            ]),
        });

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(cls));

        var stmt = Assert.IsType<JavaExpressionStatement>(cls.Methods.Single(m => m.Name == "getCount").StructuredBody!.Statements[0]);
        var call = Assert.IsType<JavaMethodCallExpression>(stmt.Expression);
        var lambda = Assert.IsType<JavaLambdaExpression>(call.Arguments[0]);
        Assert.Equal("x * 2", Assert.IsType<JavaRawExpression>(lambda.ExpressionBody).Code);
    }
