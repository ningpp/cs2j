    [Fact]
    public void Chained_Dot_Target_Structured_Is_Rewritten()
    {
        var clsA = ClassWith("A", fields: [BackingField("X")], methods: [AutoGetter("X"), AutoSetter("X")]);
        var clsB = ClassWith("B", fields: [new JavaFieldDeclaration { Name = "a", Type = "A", Modifiers = JavaModifiers.Private }]);
        var use = new JavaMethodDeclaration
        {
            Name = "use",
            ReturnType = "int",
            Modifiers = JavaModifiers.Public,
            Parameters = { new JavaParameter("B", "b") },
            StructuredBody = new JavaMethodBody(
            [
                new JavaExpressionStatement(new JavaMethodCallExpression
                {
                    Target = new JavaMemberAccessExpression
                    {
                        Target = new JavaIdentifierExpression("b"),
                        MemberName = "a",
                    },
                    MethodName = "getX",
                }),
            ]),
        };
        clsB.Methods.Add(use);

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(clsA, clsB));

        var expr = Assert.IsType<JavaExpressionStatement>(use.StructuredBody!.Statements[0]).Expression;
        var access = Assert.IsType<JavaMemberAccessExpression>(expr);
        Assert.Equal("X", access.MemberName);
        var inner = Assert.IsType<JavaMemberAccessExpression>(access.Target);
        Assert.Equal("a", inner.MemberName);
        Assert.IsType<JavaIdentifierExpression>(inner.Target);
    }

    [Fact]
    public void Deep_Chain_With_Unregistered_Leaf_Is_Not_Rewritten()
    {
        // Other.getValue 是用户方法（未注册）；链末端类型未注册访问器 → 保守不改写
        var other = ClassWith("Other", methods:
        [
            new JavaMethodDeclaration
            {
                Name = "getValue",
                ReturnType = "int",
                Modifiers = JavaModifiers.Public,
                Body = "return 1;",
                IsAutoGenerated = false,
            },
        ]);
        var middle = ClassWith("Middle", fields: [new JavaFieldDeclaration { Name = "o", Type = "Other", Modifiers = JavaModifiers.Private }]);
        var demo = ClassWith("Demo", fields: [new JavaFieldDeclaration { Name = "m", Type = "Middle", Modifiers = JavaModifiers.Private }]);
        demo.Methods.Add(new JavaMethodDeclaration
        {
            Name = "use",
            ReturnType = "int",
            Modifiers = JavaModifiers.Public,
            Parameters = { new JavaParameter("Demo", "d") },
            StructuredBody = new JavaMethodBody([new JavaRawStatement("return d.m.o.getValue();")]),
        });

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(other, middle, demo));

        Assert.Equal("return d.m.o.getValue();", RawCode(demo, "use"));
    }

    [Fact]
    public void Inherited_Field_Target_Is_Rewritten()
    {
        // 链段成员解析沿基类链回退：d.a 中 a 是基类 Base 的字段
        var result = Convert("""
class A
{
    int X { get; set; }
}
