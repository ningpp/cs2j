    }

    // ─── R1 + I6：virtual/override 统一访问器对（禁用字段简化） ───────

    [Fact]
    public void Virtual_Base_And_Override_Derived_Emits_Accessor_Pair()
    {
        var result = Convert("""
class Base
{
    public virtual int X { get; set; }
}
class Derived : Base
{
    public override int X { get; set; }
}
""");
        Assert.True(result.Success);
        // 基类 virtual 属性参与继承 → 禁字段简化 → 基类/派生均为访问器对（TS2611 消除）
        Assert.DoesNotContain("public X: number", result.GeneratedCode);
        Assert.Contains("get X(): number {", result.GeneratedCode);
        Assert.Contains("set X(value: number) {", result.GeneratedCode);
        AssertCompiles(result.GeneratedCode);
    }

    [Fact]
    public void Virtual_Base_Property_Is_Not_Field_Simplified_Component()
    {
        var baseCls = ClassWith("Base", fields: [BackingField("X")], methods: [AutoGetter("X"), AutoSetter("X")]);
        var derived = ClassWith("Derived", extends: "Base", fields: [BackingField("X")],
            methods: [AutoGetter("X", extraModifiers: JavaModifiers.Override), AutoSetter("X", extraModifiers: JavaModifiers.Override)]);

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(baseCls, derived));

        // 派生 override 存在 → 基类同名属性参与继承 → 基类不得字段简化
        var baseGetter = baseCls.Methods.Single(m => m.Name == "getX");
        Assert.Equal(TsAccessorRole.GetterSetter, rewriter.Roles[baseGetter]);
        Assert.True(baseCls.Methods.Any(m => m.Name == "getX"));   // 方法未被移除
    }

    // ─── R2：super 按基类成员形态改写 ────────────────────────────────

    [Fact]
    public void Super_Accessor_Base_Keeps_Super_Property()
    {
        var result = Convert("""
class Base
{
    public virtual int Y { get; set; }
}
class Derived : Base
{
    int _z;
    public override int Y { get { return base.Y + _z; } set { base.Y = value; } }
}
""");
        Assert.True(result.Success);
        // 基类 Y 是重建后的访问器 → super.Y 保留（无递归；TS 允许 super 访问基类访问器）
        Assert.Contains("return super.Y + this._z;", result.GeneratedCode);
        Assert.Contains("super.Y = value;", result.GeneratedCode);
        Assert.DoesNotContain("return this.Y + this._z;", result.GeneratedCode);
        AssertCompiles(result.GeneratedCode);
    }

    [Fact]
    public void Super_Structured_Accessor_Base_Keeps_Super()
    {
        var baseCls = ClassWith("Base", fields: [BackingField("Y")], methods: [AutoGetter("Y"), AutoSetter("Y")]);
        var derived = ClassWith("Derived", extends: "Base", fields: [BackingField("Y")]);
        derived.Methods.Add(new JavaMethodDeclaration
        {
            Name = "use",
            ReturnType = "int",
            Modifiers = JavaModifiers.Public,
            StructuredBody = new JavaMethodBody(
            [
                new JavaExpressionStatement(new JavaMethodCallExpression
                {
                    Target = new JavaThisExpression { IsSuper = true },
                    MethodName = "getY",
                }),
            ]),
        });
        derived.Methods.Add(AutoGetter("Y", extraModifiers: JavaModifiers.Override));
        derived.Methods.Add(AutoSetter("Y", extraModifiers: JavaModifiers.Override));

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(baseCls, derived));

        // 派生 override 存在 → 基类访问器形态 → super 目标保留
        var expr = Assert.IsType<JavaExpressionStatement>(derived.Methods.Single(m => m.Name == "use").StructuredBody!.Statements[0]).Expression;
        var access = Assert.IsType<JavaMemberAccessExpression>(expr);
        Assert.Equal("Y", access.MemberName);
        var target = Assert.IsType<JavaThisExpression>(access.Target);
        Assert.True(target.IsSuper);
    }

    // ─── I7：for-init 局部变量排除（结构化 Initializer + raw for 头） ─

    [Fact]
    public void For_Init_Local_Is_Not_Qualified()
    {
        var result = Convert("""
class Counter
{
    int i;
    int Count
    {
        get
        {
            int sum = 0;
            for (var i = 0; i < 3; i++) { sum += i; }
            return sum;
        }
    }
}
""");
        Assert.True(result.Success);
        // for-init 声明变量 i 遮蔽字段：不得限定为 this.i（TS1005）
        Assert.Contains("for (let i: number = 0; i < 3; i++)", result.GeneratedCode);
        Assert.DoesNotContain("this.i", result.GeneratedCode);
        AssertCompiles(result.GeneratedCode);
    }

    [Fact]
    public void For_Init_Multi_Declarations_Are_Not_Qualified_Component()
    {
        var cls = ClassWith("Counter", fields: [BackingField("Count"), new JavaFieldDeclaration { Name = "i", Type = "int", Modifiers = JavaModifiers.Private }, new JavaFieldDeclaration { Name = "j", Type = "int", Modifiers = JavaModifiers.Private }]);
        cls.Methods.Add(new JavaMethodDeclaration
        {
            Name = "getCount",
            ReturnType = "int",
            Modifiers = JavaModifiers.Public,
            IsAutoGenerated = true,
            StructuredBody = new JavaMethodBody(
            [
                new JavaForStatement
                {
                    Initializer = "int i = 0, j = 1",
                    Increment = "i++",
                    Body = new JavaRawStatement("return i + j;"),
                },
            ]),
        });

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(cls));

        var forStmt = Assert.IsType<JavaForStatement>(cls.Methods.Single(m => m.Name == "getCount").StructuredBody!.Statements[0]);
        Assert.Equal("return i + j;", Assert.IsType<JavaRawStatement>(forStmt.Body).Code);
    }

