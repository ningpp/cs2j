    // ─── IR 构造辅助 ─────────────────────────────────────────────────

    private static JavaClassDeclaration ClassWith(
        string name = "Point",
        string? extends = null,
        List<JavaFieldDeclaration>? fields = null,
        List<JavaMethodDeclaration>? methods = null)
    {
        var cls = new JavaClassDeclaration
        {
            Name = name,
            Modifiers = JavaModifiers.Public,
            ExtendedType = extends,
        };
        if (fields != null) cls.Fields.AddRange(fields);
        if (methods != null) cls.Methods.AddRange(methods);
        return cls;
    }

    private static JavaMethodDeclaration AutoGetter(string propName, string returnType = "int",
        JavaModifiers extraModifiers = JavaModifiers.None)
    {
        var fieldName = char.ToLowerInvariant(propName[0]) + propName[1..];
        return new JavaMethodDeclaration
        {
            Name = "get" + propName,
            ReturnType = returnType,
            Modifiers = JavaModifiers.Public | extraModifiers,
            Body = $"return {fieldName};",
            IsAutoGenerated = true,
        };
    }

    private static JavaMethodDeclaration AutoSetter(string propName, string valueType = "int",
        JavaModifiers extraModifiers = JavaModifiers.None)
    {
        var fieldName = char.ToLowerInvariant(propName[0]) + propName[1..];
        return new JavaMethodDeclaration
        {
            Name = "set" + propName,
            ReturnType = "void",
            Modifiers = JavaModifiers.Public | extraModifiers,
            Body = $"this.{fieldName} = value;",
            Parameters = { new JavaParameter(valueType, "value") },
            IsAutoGenerated = true,
        };
    }

    private static JavaFieldDeclaration BackingField(string propName, string type = "int")
    {
        var fieldName = char.ToLowerInvariant(propName[0]) + propName[1..];
        return new JavaFieldDeclaration
        {
            Name = fieldName,
            Type = type,
            Modifiers = JavaModifiers.Private,
        };
    }

    private static JavaCompilationUnit UnitWith(params JavaTypeDeclaration[] types)
    {
        var unit = new JavaCompilationUnit();
        foreach (var t in types) unit.TypeDeclarations.Add(t);
        return unit;
    }

    // ─── P1：setter 参数 value 不得被字段限定误改 ─────────────────────

    [Fact]
    public void Setter_Parameter_Named_Like_Field_Is_Not_Qualified()
    {
        var result = Convert("""
class Point
{
    int value;
    int X { get; private set; }
}
""");
        Assert.True(result.Success);
        // setter 参数 value 与字段 value 同名：参数不得被限定为 this.value
        Assert.Contains("private set X(value: number)", result.GeneratedCode);
        Assert.Contains("this.x = value;", result.GeneratedCode);
        Assert.DoesNotContain("this.x = this.value", result.GeneratedCode);
        AssertCompiles(result.GeneratedCode);
    }

    [Fact]
    public void Setter_Parameter_Named_Like_Field_Is_Not_Qualified_Component()
    {
        var cls = ClassWith(
            fields: [BackingField("X"), BackingField("Value")],
            methods:
            [
                AutoGetter("X"),
                new JavaMethodDeclaration
                {
                    Name = "setX",
                    ReturnType = "void",
                    Modifiers = JavaModifiers.Private,
                    Body = "this.x = value;",
                    Parameters = { new JavaParameter("int", "value") },
                    IsAutoGenerated = true,
                },
            ]);

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(cls));

        var setter = cls.Methods.Single(m => m.Name == "setX");
        Assert.Equal("this.x = value;", setter.Body);
        // getter 体字段限定不受影响
        Assert.Equal("return this.x;", cls.Methods.Single(m => m.Name == "getX").Body);
    }

    // ─── C1：dot-target 无类型信息保守不改写 ──────────────────────────

    [Fact]
    public void Dot_Target_User_Method_Is_Not_Rewritten_Despite_Other_Class_Property()
    {
        var result = Convert("""
class Config
{
    int Value { get; set; }
}
class Service
{
    int GetValue() { return 1; }
    void SetValue(int v) { }
    int Use(Service s) { s.SetValue(3); return s.GetValue(); }
}
""");
        Assert.True(result.Success);
        // Config.Value 重建注册了 getValue/setValue；Service 用户方法同名不得被误改
        Assert.Contains("s.setValue(3);", result.GeneratedCode);
        Assert.Contains("return s.getValue();", result.GeneratedCode);
        Assert.DoesNotContain("s.Value", result.GeneratedCode);
        AssertCompiles(result.GeneratedCode);
    }

    [Fact]
    public void Dot_Target_With_Resolvable_Type_Is_Rewritten()
    {
        var result = Convert("""
class Config
{
    int Value { get; set; }
}
class Demo
{
    int Use(Config c) { return c.Value; }
}
""");
        Assert.True(result.Success);
        // c 参数类型 Config 可解析 → c.getValue() 改写为 c.Value
        Assert.Contains("return c.Value;", result.GeneratedCode);
        AssertCompiles(result.GeneratedCode);
    }

    [Fact]
    public void Dot_Target_Unknown_Or_Unregistered_Is_Not_Rewritten()
    {
        // WriteOnly：只写属性 setter 不注册 → w.setX(3) 保持方法调用
        var writeOnly = ClassWith(
            name: "WriteOnly",
            fields: [BackingField("X")],
            methods:
            [
                AutoSetter("X"),
                new JavaMethodDeclaration
                {
                    Name = "useW",
                    ReturnType = "void",
                    Modifiers = JavaModifiers.Public,
                    Parameters = { new JavaParameter("WriteOnly", "w") },
                    StructuredBody = new JavaMethodBody([new JavaRawStatement("w.setX(3);")]),
                },
            ]);

        // Stat：静态用户方法 getValue 不注册 → Stat.getValue() 保持方法调用
        var stat = ClassWith(
            name: "Stat",
            methods:
            [
                new JavaMethodDeclaration
                {
                    Name = "getValue",
                    ReturnType = "int",
                    Modifiers = JavaModifiers.Public | JavaModifiers.Static,
                    Body = "return 1;",
                    IsAutoGenerated = false,
                },
                new JavaMethodDeclaration
                {
                    Name = "useS",
                    ReturnType = "int",
                    Modifiers = JavaModifiers.Public,
                    StructuredBody = new JavaMethodBody([new JavaRawStatement("return Stat.getValue();")]),
                },
            ]);

        // 未知类型目标：无参数/字段/类型信息 → 保守不改写
        var unknown = ClassWith(
            name: "Unknown",
            methods:
            [
                new JavaMethodDeclaration
                {
                    Name = "useU",
                    ReturnType = "int",
                    Modifiers = JavaModifiers.Public,
                    StructuredBody = new JavaMethodBody([new JavaRawStatement("return unresolved.getValue();")]),
                },
            ]);

        // 正控：可解析类型且注册过 → 改写
        var config = ClassWith(
            name: "Config",
            fields: [BackingField("Value")],
            methods:
            [
                AutoGetter("Value"),
                AutoSetter("Value"),
                new JavaMethodDeclaration
                {
                    Name = "useC",
                    ReturnType = "int",
                    Modifiers = JavaModifiers.Public,
                    Parameters = { new JavaParameter("Config", "c") },
                    StructuredBody = new JavaMethodBody([new JavaRawStatement("return c.getValue();")]),
                },
            ]);

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(writeOnly, stat, unknown, config));

        Assert.Equal("w.setX(3);", RawCode(writeOnly, "useW"));
        Assert.Equal("return Stat.getValue();", RawCode(stat, "useS"));
        Assert.Equal("return unresolved.getValue();", RawCode(unknown, "useU"));
        Assert.Equal("return c.Value;", RawCode(config, "useC"));
    }

    private static string RawCode(JavaClassDeclaration cls, string methodName)
        => cls.Methods.Single(m => m.Name == methodName).StructuredBody!.Statements
            .Cast<JavaRawStatement>().Single().Code;

    // ─── I2：接口访问器调用改写 ───────────────────────────────────────

    [Fact]
    public void Interface_Accessor_Calls_Are_Rewritten_Readonly_Setter_Stays_Method()
    {
        var result = Convert("""
interface IShape
{
    int X { get; }
    int Y { get; set; }
}
class Demo
{
    int Sum(IShape s) { return s.X + s.Y; }
    void Set(IShape s, int v) { s.Y = v; }
}
""");
        Assert.True(result.Success);
        Assert.Contains("return s.X + s.Y;", result.GeneratedCode);
        Assert.Contains("s.Y = v;", result.GeneratedCode);
        AssertCompilesWithCompat(result.GeneratedCode);
    }

    [Fact]
    public void Interface_Accessor_Calls_Resolve_Interface_And_Implementing_Class()
    {
        var iface = new JavaInterfaceDeclaration
        {
            Name = "IShape",
            Modifiers = JavaModifiers.Public,
        };
        iface.Methods.Add(AutoGetter("X"));
        iface.Methods.Add(AutoGetter("Y"));
        iface.Methods.Add(AutoSetter("Y"));

        var circle = ClassWith(
            name: "Circle",
            fields: [BackingField("X"), BackingField("Y")],
            methods: [AutoGetter("X"), AutoSetter("X"), AutoGetter("Y"), AutoSetter("Y")]);

        var demo = ClassWith(
            name: "Demo",
            methods:
            [
                new JavaMethodDeclaration
                {
                    Name = "useI",
                    ReturnType = "int",
                    Modifiers = JavaModifiers.Public,
                    Parameters = { new JavaParameter("IShape", "s") },
                    StructuredBody = new JavaMethodBody(
                    [
                        new JavaRawStatement("return s.getX();"),
                        new JavaRawStatement("s.setX(3);"),
                        new JavaRawStatement("s.setY(5);"),
                    ]),
                },
                new JavaMethodDeclaration
                {
                    Name = "useC",
                    ReturnType = "int",
                    Modifiers = JavaModifiers.Public,
                    Parameters = { new JavaParameter("Circle", "c") },
                    StructuredBody = new JavaMethodBody([new JavaRawStatement("return c.getY();")]),
                },
            ]);

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(iface, circle, demo));

        var useI = demo.Methods.Single(m => m.Name == "useI").StructuredBody!.Statements.Cast<JavaRawStatement>().ToList();
        Assert.Equal("return s.X;", useI[0].Code);          // 只读接口属性 getter → 成员访问
        Assert.Equal("s.setX(3);", useI[1].Code);           // 只读接口属性 setter 不注册 → 保持方法
        Assert.Equal("s.Y = 5;", useI[2].Code);             // get+set 接口属性 → 赋值
        Assert.Equal("return c.Y;", RawCode(demo, "useC")); // 实现类自身访问器 → 类上下文改写
        // 接口访问器不进 roles（Task 15 合并发射）；Circle 自动对 → 字段简化角色
        Assert.All(iface.Methods, m => Assert.False(rewriter.Roles.ContainsKey(m)));
    }

    // ─── I3：super 目标改写为 this ────────────────────────────────────

    [Fact]
    public void Super_Property_Access_Is_Rewritten_To_This()
    {
        var result = Convert("""
class Base
{
    public int X { get; set; }
    public int Read() { return X; }
}
class Derived : Base
{
    int UseBase() { return base.X; }
    void SetBase(int v) { base.X = v; }
}
""");
        Assert.True(result.Success);
        Assert.Contains("return this.X;", result.GeneratedCode);
        Assert.Contains("this.X = v;", result.GeneratedCode);
        Assert.DoesNotContain("super.X", result.GeneratedCode);
        AssertCompiles(result.GeneratedCode);
    }

    [Fact]
    public void Super_Target_Structured_Call_Is_Rewritten_To_This()
    {
        var baseCls = ClassWith(
            name: "Base",
            fields: [BackingField("X")],
            methods: [AutoGetter("X"), AutoSetter("X")]);

        var derived = ClassWith(
            name: "Derived",
            extends: "Base",
            methods:
            [
                new JavaMethodDeclaration
                {
                    Name = "use",
                    ReturnType = "int",
                    Modifiers = JavaModifiers.Public,
                    StructuredBody = new JavaMethodBody(
                    [
                        new JavaExpressionStatement(new JavaMethodCallExpression
                        {
                            Target = new JavaThisExpression { IsSuper = true },
                            MethodName = "getX",
                        }),
                        new JavaRawStatement("super.setX(7);"),
                    ]),
                },
            ]);

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(baseCls, derived));

        var stmts = derived.Methods.Single(m => m.Name == "use").StructuredBody!.Statements;
        var access = Assert.IsType<JavaMemberAccessExpression>(Assert.IsType<JavaExpressionStatement>(stmts[0]).Expression);
        Assert.Equal("X", access.MemberName);
        Assert.IsType<JavaThisExpression>(access.Target);
        Assert.False(((JavaThisExpression)access.Target).IsSuper);   // super → this
        Assert.Equal("this.X = 7;", Assert.IsType<JavaRawStatement>(stmts[1]).Code);
    }

    // ─── I4：抽象访问器 → abstract get/set，派生覆盖匹配 ──────────────

    [Fact]
    public void Abstract_Accessors_Emit_Abstract_And_Overrides_Match()
    {
        var result = Convert("""
abstract class Shape
{
    public abstract int X { get; }
    public abstract int Y { get; set; }
}
class Point : Shape
{
    public override int X { get; }
    public override int Y { get; set; }
    public Point(int x) { X = x; }
}
""");
        Assert.True(result.Success);
        // 基类抽象访问器 → abstract 形态（无体）
        Assert.Contains("abstract get X(): number;", result.GeneratedCode);
        Assert.Contains("abstract get Y(): number;", result.GeneratedCode);
        Assert.Contains("abstract set Y(value: number);", result.GeneratedCode);
        // 派生 override 访问器（Override 修饰 → 不做字段简化）→ 访问器形态匹配
        Assert.Contains("get X(): number {", result.GeneratedCode);
        Assert.Contains("return this.x;", result.GeneratedCode);
        Assert.Contains("set Y(value: number) {", result.GeneratedCode);
        Assert.Contains("this.y = value;", result.GeneratedCode);
        Assert.DoesNotContain("abstract set X(", result.GeneratedCode);
        AssertCompiles(result.GeneratedCode);
    }

    [Fact]
    public void Abstract_Accessor_Names_Are_Registered_For_Class_Chain_Calls()
    {
        var shape = ClassWith(
            name: "Shape",
            methods:
            [
                AutoGetter("X", extraModifiers: JavaModifiers.Abstract),
                new JavaMethodDeclaration
                {
                    Name = "use",
                    ReturnType = "int",
                    Modifiers = JavaModifiers.Public,
                    StructuredBody = new JavaMethodBody([new JavaRawStatement("return getX();")]),
                },
            ]);

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(shape));

        var getter = shape.Methods.Single(m => m.Name == "getX");
        Assert.Equal(TsAccessorRole.Getter, rewriter.Roles[getter]);
        // 抽象类内裸调用 → this.X（抽象访问器可经 this 访问）
        Assert.Equal("return this.X;", RawCode(shape, "use"));
    }

