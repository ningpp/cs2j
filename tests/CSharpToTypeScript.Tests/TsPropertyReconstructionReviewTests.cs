    }

    [Fact]
    public void Structured_Accessor_Body_Local_Variables_Are_Not_Qualified()
    {
        var cls = ClassWith(
            fields: [BackingField("Count")],
            methods:
            [
                new JavaMethodDeclaration
                {
                    Name = "getP",
                    ReturnType = "int",
                    Modifiers = JavaModifiers.Public,
                    IsAutoGenerated = true,
                    StructuredBody = new JavaMethodBody(
                    [
                        new JavaVariableDeclarationStatement { Type = "int", Name = "count" },
                        new JavaRawStatement("return count;"),
                    ]),
                },
                new JavaMethodDeclaration
                {
                    Name = "getQ",
                    ReturnType = "int",
                    Modifiers = JavaModifiers.Public,
                    IsAutoGenerated = true,
                    StructuredBody = new JavaMethodBody([new JavaRawStatement("return count;")]),
                },
            ]);

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(cls));

        // 局部变量 count 遮蔽字段：getP 内不限定；getQ 内（无局部）限定为 this.count
        var p = cls.Methods.Single(m => m.Name == "getP").StructuredBody!.Statements;
        Assert.Equal("count", Assert.IsType<JavaVariableDeclarationStatement>(p[0]).Name);
        Assert.Equal("return count;", Assert.IsType<JavaRawStatement>(p[1]).Code);
        var q = cls.Methods.Single(m => m.Name == "getQ").StructuredBody!.Statements;
        Assert.Equal("return this.count;", Assert.IsType<JavaRawStatement>(q[0]).Code);
    }
