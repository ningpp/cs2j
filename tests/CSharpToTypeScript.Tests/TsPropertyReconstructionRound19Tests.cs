    // ─── 附带项：字段初始化器 FQCN 缩短（TS2304 'Microsoft'） ────────────

    /// <summary>
    /// 实证样例（CubicBezierSegment.ts:16-18 / Rail.ts / MinDistCurveCurve.ts 等 146 条
    /// TS2304 'Microsoft'）：EmitField 的初始化器归一化此前不传 mapType →
    /// NormalizeFqcnExpressions 因 mapType == null 整 pass 直通，raw 文本
    /// "new Microsoft.Msagl.Core.Geometry.Point()" 保留（语句路径经 TsStatementWriter
    /// 传 _exprWriter.MapType 已缩短）。修复：字段路径同样传入 mapType。
    /// </summary>
    [Fact]
    public void Field_Initializer_Fqcn_Is_Shortened_At_Emission()
    {
        var table = new TsMemberMappingTable(null, null);
        var imports = new TsImportCollector();
        var exprWriter = new TsExpressionWriter(table, imports);
        var memberWriter = new TsMemberWriter(new TsStatementWriter(exprWriter), exprWriter);
        var field = new JavaFieldDeclaration
        {
            Name = "l",
            Type = "Point",
            Modifiers = JavaModifiers.Private,
            Initializer = "new Microsoft.Msagl.Core.Geometry.Point()",
        };
        Assert.Equal("private l: Point = new Point();", memberWriter.EmitField(field, 0));
    }

