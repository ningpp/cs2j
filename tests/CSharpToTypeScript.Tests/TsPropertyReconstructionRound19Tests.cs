/// <summary>
/// Round 19：TS2551 getter/setter 形态调用点改写缺口三子根因 + 附带 FQCN 位：
/// A）raw 文本接收者类型解析对 FQCN（Microsoft.Msagl.Core.Geometry.Point.op_Subtract(...)）
///    逐段分解失败 → 变量登记 var → 调用点保守不改写（ResolveExpressionTextType 缺
///    整链扁平表查表，结构化路径 ResolveExpressionType 有）；
/// B）compat 集合/对类型（CsDictionary/CSharpList/CsKeyValuePair 等）内置方法
///    （get(k)/get(i)/getValue()/size()...）不在 MethodReturnTypes 注册表 → 链解析
///    在 compat 段返回 null → 后续访问器段不改写；
/// C）Create$N 工厂方法在注册表收集时尚未合成（TsCtorFactoryRewriter 晚于
///    TsPropertyReconstructionRewriter 运行）→ let g = Type.Create$N(...) 局部失效。
/// 附带：NormalizeFqcnExpressions 泛型实参位（after=='>'）直通 → TS2503；
/// 字段初始化器未接入 FQCN pass（EmitField 的 Normalize 未传 mapType）→ TS2304。
/// </summary>
public class TsPropertyReconstructionRound19Tests : TsConversionTestBase
{
    // ─── 辅助（与 Round17Tests 同构） ──────────────────────────────────

    private static JavaClassDeclaration ClassWith(
        string name,
        List<JavaFieldDeclaration>? fields = null,
        List<JavaMethodDeclaration>? methods = null)
    {
        var cls = new JavaClassDeclaration
        {
            Name = name,
            Modifiers = JavaModifiers.Public,
        };
        if (fields != null) cls.Fields.AddRange(fields);
        if (methods != null) cls.Methods.AddRange(methods);
        return cls;
    }

    private static JavaMethodDeclaration AutoGetter(string propName, string returnType = "int")
    {
        var fieldName = char.ToLowerInvariant(propName[0]) + propName[1..];
        return new JavaMethodDeclaration
        {
            Name = "get" + propName,
            ReturnType = returnType,
            Modifiers = JavaModifiers.Public,
            Body = $"return {fieldName};",
            IsAutoGenerated = true,
        };
    }

    private static JavaMethodDeclaration AutoSetter(string propName, string valueType = "int")
    {
        var fieldName = char.ToLowerInvariant(propName[0]) + propName[1..];
        return new JavaMethodDeclaration
        {
            Name = "set" + propName,
            ReturnType = "void",
            Modifiers = JavaModifiers.Public,
            Body = $"this.{fieldName} = value;",
            Parameters = { new JavaParameter(valueType, "value") },
            IsAutoGenerated = true,
        };
    }

    private static JavaFieldDeclaration BackingField(string propName, string type = "int")
    {
        var fieldName = char.ToLowerInvariant(propName[0]) + propName[1..];
        return new JavaFieldDeclaration
        {
            Name = fieldName,
            Type = type,
            Modifiers = JavaModifiers.Private,
        };
    }

    private static JavaCompilationUnit UnitWith(params JavaTypeDeclaration[] types)
    {
        var unit = new JavaCompilationUnit();
        foreach (var t in types) unit.TypeDeclarations.Add(t);
        return unit;
    }

    private static JavaCompilationUnit UnitWithPackage(string package, params JavaTypeDeclaration[] types)
    {
        var unit = new JavaCompilationUnit(package);
        foreach (var t in types) unit.TypeDeclarations.Add(t);
        return unit;
    }

    private static JavaMethodDeclaration MethodWithRawBody(
        string name, string paramName, string paramType, string returnType, params string[] rawStatements)
    {
        return new JavaMethodDeclaration
        {
            Name = name,
            ReturnType = returnType,
            Modifiers = JavaModifiers.Public,
            Parameters = { new JavaParameter(paramType, paramName) },
            StructuredBody = new JavaMethodBody(rawStatements.Select(s => new JavaRawStatement(s)).ToList<JavaStatement>()),
        };
    }

    private static JavaMethodDeclaration StaticMethodWithRawBody(
        string name, string returnType, params string[] rawStatements)
    {
        return new JavaMethodDeclaration
        {
            Name = name,
            ReturnType = returnType,
            Modifiers = JavaModifiers.Public | JavaModifiers.Static,
            StructuredBody = new JavaMethodBody(rawStatements.Select(s => new JavaRawStatement(s)).ToList<JavaStatement>()),
        };
    }

    private static List<string> RawCodes(TsPropertyReconstructionRewriter rewriter, JavaClassDeclaration cls, string methodName)
    {
        return cls.Methods.Single(m => m.Name == methodName).StructuredBody!.Statements
            .Cast<JavaRawStatement>().Select(s => s.Code).ToList();
    }

    // ─── 子根因 A：FQCN 接收者整链查扁平表 ─────────────────────────────

    /// <summary>
    /// 实证样例（ClosestPointOnCurve.cs：41 等 160 条）：raw 文本
    /// "var d = Microsoft.Msagl.Core.Geometry.Point.op_Subtract(a, b);" 的初始化
    /// 推断按点分链逐段解析（Microsoft → null → 整链失败 → d 登记 var），
    /// 后续 d.getLength() 保守不改写。修复：分解点分链前先查
    /// _typeContextsByName[整条文本]（与结构化路径 JavaRawExpression.ResolvedType
    /// → TryGetTypeContexts 全名键命中对齐），命中归一化为简单名。
    /// </summary>
    [Fact]
    public void Fqcn_Receiver_WholeName_Lookup_Resolves_Var_Local_Type()
    {
        var point = ClassWith("Point",
            fields: [BackingField("Length", "double")],
            methods:
            [
                AutoGetter("Length", "double"),
                new JavaMethodDeclaration
                {
                    Name = "op_Subtract",
                    ReturnType = "Point",
                    Modifiers = JavaModifiers.Public | JavaModifiers.Static,
                    Parameters = { new JavaParameter("Point", "a"), new JavaParameter("Point", "b") },
                    Body = "return null;",
                },
            ]);
        var user = ClassWith("ClosestPointOnCurve");
        user.Methods.Add(MethodWithRawBody("m", "pointA", "Point", "double",
            "var d = Microsoft.Msagl.Core.Geometry.Point.op_Subtract(pointA, pointB);",
            "d.getLength();"));

        var registry = TsPropertyReconstructionRewriter.CollectProjectContexts(
            [UnitWithPackage("Microsoft.Msagl.Core.Geometry", point)]);
        var rewriter = new TsPropertyReconstructionRewriter { ProjectContexts = registry };
        rewriter.VisitCompilationUnit(UnitWith(user));

        var codes = RawCodes(rewriter, user, "m");
        Assert.Equal("var d = Microsoft.Msagl.Core.Geometry.Point.op_Subtract(pointA, pointB);", codes[0]);
        Assert.Equal("d.Length;", codes[1]);
    }

    /// <summary>FQCN 接收者链上的访问器段：d.getLength() → d.Length（同一链路两段）。</summary>
    [Fact]
    public void Fqcn_Receiver_Paren_Chain_Getter_Is_Rewritten()
    {
        var point = ClassWith("Point",
            fields: [BackingField("Length", "double")],
            methods:
            [
                AutoGetter("Length", "double"),
                new JavaMethodDeclaration
                {
                    Name = "op_Subtract",
                    ReturnType = "Point",
                    Modifiers = JavaModifiers.Public | JavaModifiers.Static,
                    Parameters = { new JavaParameter("Point", "a"), new JavaParameter("Point", "b") },
                    Body = "return null;",
                },
            ]);
        var user = ClassWith("ClosestPointOnCurve");
        user.Methods.Add(MethodWithRawBody("m", "pointA", "Point", "double",
            "return (Microsoft.Msagl.Core.Geometry.Point.op_Subtract(pointA, pointB)).getLength();"));

        var registry = TsPropertyReconstructionRewriter.CollectProjectContexts(
            [UnitWithPackage("Microsoft.Msagl.Core.Geometry", point)]);
