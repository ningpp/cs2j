    // ─── IR 构造辅助（与 Review1/Review2 同构，保持文件独立） ──────────

    private static JavaClassDeclaration ClassWith(
        string name,
        string? extends = null,
        List<JavaFieldDeclaration>? fields = null,
        List<JavaMethodDeclaration>? methods = null)
    {
        var cls = new JavaClassDeclaration
        {
            Name = name,
            Modifiers = JavaModifiers.Public,
            ExtendedType = extends,
        };
        if (fields != null) cls.Fields.AddRange(fields);
        if (methods != null) cls.Methods.AddRange(methods);
        return cls;
    }

    private static JavaMethodDeclaration AutoGetter(string propName, string returnType = "int",
        JavaModifiers extraModifiers = JavaModifiers.None)
    {
        var fieldName = char.ToLowerInvariant(propName[0]) + propName[1..];
        return new JavaMethodDeclaration
        {
            Name = "get" + propName,
            ReturnType = returnType,
            Modifiers = JavaModifiers.Public | extraModifiers,
            Body = $"return {fieldName};",
            IsAutoGenerated = true,
        };
    }

    private static JavaMethodDeclaration AutoSetter(string propName, string valueType = "int",
        JavaModifiers extraModifiers = JavaModifiers.None)
    {
        var fieldName = char.ToLowerInvariant(propName[0]) + propName[1..];
        return new JavaMethodDeclaration
        {
            Name = "set" + propName,
            ReturnType = "void",
            Modifiers = JavaModifiers.Public | extraModifiers,
            Body = $"this.{fieldName} = value;",
            Parameters = { new JavaParameter(valueType, "value") },
            IsAutoGenerated = true,
        };
    }

    private static JavaFieldDeclaration BackingField(string propName, string type = "int")
    {
        var fieldName = char.ToLowerInvariant(propName[0]) + propName[1..];
        return new JavaFieldDeclaration
        {
            Name = fieldName,
            Type = type,
            Modifiers = JavaModifiers.Private,
        };
    }

    private static JavaCompilationUnit UnitWith(params JavaTypeDeclaration[] types)
    {
        var unit = new JavaCompilationUnit();
        foreach (var t in types) unit.TypeDeclarations.Add(t);
        return unit;
    }

    // ─── R-1：TryResolveAccessor 基类链递归（爷孙三层继承） ─────────────

    [Fact]
    public void Bare_Call_Through_Grandparent_Base_Is_Rewritten()
    {
        // 裸调用 getX() 在 C（C → B → A）：旧实现只查直接基类 B → 残留 getX()（TS2304）。
        // 完整管线中继承的裸属性读（return X;）在 HIR 不降级为 getX()（既有缺口，见类注释），
        // 故以 IR 级 raw 体回归本修复点。
        var clsA = ClassWith("A", fields: [BackingField("X")], methods: [AutoGetter("X"), AutoSetter("X")]);
        var clsB = ClassWith("B", extends: "A");
        var clsC = ClassWith("C", extends: "B");
        clsC.Methods.Add(new JavaMethodDeclaration
        {
            Name = "use",
            ReturnType = "int",
            Modifiers = JavaModifiers.Public,
            StructuredBody = new JavaMethodBody([new JavaRawStatement("return getX();")]),
        });

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(clsA, clsB, clsC));

        Assert.Equal("return this.X;",
            clsC.Methods.Single(m => m.Name == "use").StructuredBody!.Statements
                .Cast<JavaRawStatement>().Single().Code);
    }

    [Fact]
    public void This_Call_Through_Grandparent_Base_Is_Rewritten()
    {
        var result = Convert("""
class A
{
    int X { get; set; }
}
class B : A
{
}
class C : B
{
    int Read() { return this.X; }
}
""");
        Assert.True(result.Success);
        // this.getX() 在 C：C → B → A 基类链递归解析（旧实现只查直接基类 B）
        Assert.Contains("return this.X;", result.GeneratedCode);
        Assert.DoesNotContain("this.getX()", result.GeneratedCode);
        AssertCompiles(result.GeneratedCode);
    }

    [Fact]
    public void Base_Call_Through_Grandparent_Base_Keeps_Super_Accessor()
    {
        var result = Convert("""
class A
{
    public virtual int X { get; set; }
}
class B : A
{
}
class C : B
{
    public override int X { get; set; }
    int Read() { return base.X; }
}
""");
        Assert.True(result.Success);
        // base.X：C → B → A 递归解析；基类 A 的 X 是重建访问器 → super.X 保留（R2 形态判定）
        Assert.Contains("return super.X;", result.GeneratedCode);
        Assert.DoesNotContain("super.getX()", result.GeneratedCode);
        AssertCompiles(result.GeneratedCode);
    }

    [Fact]
    public void Base_Call_Through_Grandparent_Base_Field_Is_Rewritten_To_This()
    {
        var result = Convert("""
