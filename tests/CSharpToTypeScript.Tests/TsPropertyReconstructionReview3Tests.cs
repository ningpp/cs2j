        Assert.Contains("return this.Y;", result.GeneratedCode);
        Assert.DoesNotContain("super.getY()", result.GeneratedCode);
        AssertCompiles(result.GeneratedCode);
    }

    [Fact]
    public void Static_Property_Through_Derived_Class_Name_Is_Rewritten()
    {
        // 静态属性经派生类名访问 C.getStat()：末端查访问器需走基类链（C → B → A）。
        // 完整管线中 C.Stat 在 HIR 已被归一到声明类 A.getStat()（A 自身命中，非本修复点），
        // 故以 IR 级 raw 体回归派生类名形态。
        var clsA = ClassWith("A", fields: [new JavaFieldDeclaration { Name = "stat", Type = "int", Modifiers = JavaModifiers.Private | JavaModifiers.Static }]);
        clsA.Methods.Add(new JavaMethodDeclaration
        {
            Name = "getStat",
            ReturnType = "int",
            Modifiers = JavaModifiers.Public | JavaModifiers.Static,
            Body = "return stat;",
            IsAutoGenerated = true,
        });
        clsA.Methods.Add(new JavaMethodDeclaration
        {
            Name = "setStat",
            ReturnType = "void",
            Modifiers = JavaModifiers.Public | JavaModifiers.Static,
            Body = "this.stat = value;",
            Parameters = { new JavaParameter("int", "value") },
            IsAutoGenerated = true,
        });
        var clsB = ClassWith("B", extends: "A");
        var clsC = ClassWith("C", extends: "B");
        clsC.Methods.Add(new JavaMethodDeclaration
        {
            Name = "use",
            ReturnType = "int",
            Modifiers = JavaModifiers.Public,
            StructuredBody = new JavaMethodBody([new JavaRawStatement("return C.getStat();")]),
        });

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(clsA, clsB, clsC));

        Assert.Equal("return C.Stat;",
            clsC.Methods.Single(m => m.Name == "use").StructuredBody!.Statements
                .Cast<JavaRawStatement>().Single().Code);
    }

    [Fact]
    public void Static_Property_Inherited_Access_Emits_Declaring_Class_Guard()
    {
        // 完整管线守卫：C.Stat 在 HIR 归一为 A.getStat() → 改写为 A.Stat（声明类），tsc 过
        var result = Convert("""
class A
{
    public static int Stat { get; set; }
}
class B : A
{
}
class C : B
{
    int Read() { return C.Stat; }
}
""");
        Assert.True(result.Success);
        Assert.Contains("return A.Stat;", result.GeneratedCode);
        Assert.DoesNotContain("getStat()", result.GeneratedCode);
        AssertCompiles(result.GeneratedCode);
    }

    [Fact]
    public void Interface_Property_Through_Intermediate_Base_Is_Rewritten()
    {
        var result = Convert("""
interface IShape
{
    int X { get; }
}
interface IMid : IShape
{
}
class Base : IShape
{
    public int X { get; }
}
class Mid : Base
{
}
class Leaf : Mid
{
}
class Demo
{
    int Sum(IMid m) { return m.X; }
    int Sum2(Mid m2) { return m2.X; }
    int Sum3(Leaf l) { return l.X; }
}
""");
        Assert.True(result.Success);
        // m.X：接口继承链 IMid → IShape（中间基类为接口）；
        // m2.X：类链 Mid → Base（Base 实现接口属性）；
        // l.X：爷孙链 Leaf → Mid → Base
        Assert.Contains("return m.X;", result.GeneratedCode);
        Assert.Contains("return m2.X;", result.GeneratedCode);
        Assert.Contains("return l.X;", result.GeneratedCode);
        Assert.DoesNotContain("m.getX()", result.GeneratedCode);
        Assert.DoesNotContain("m2.getX()", result.GeneratedCode);
        AssertCompiles(result.GeneratedCode);
    }

    [Fact]
    public void Bare_Structured_Call_Through_Grandparent_Base_Is_Rewritten()
    {
        var clsA = ClassWith("A", fields: [BackingField("X")], methods: [AutoGetter("X"), AutoSetter("X")]);
        var clsB = ClassWith("B", extends: "A");
        var clsC = ClassWith("C", extends: "B");
        clsC.Methods.Add(new JavaMethodDeclaration
        {
            Name = "use",
            ReturnType = "int",
            Modifiers = JavaModifiers.Public,
            StructuredBody = new JavaMethodBody(
            [
                new JavaExpressionStatement(new JavaMethodCallExpression
                {
                    Target = null,
                    MethodName = "getX",
                }),
            ]),
        });

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(clsA, clsB, clsC));

        // 结构化裸调用 getX 在 C 中：C → B → A 递归解析 → this.X
        var expr = Assert.IsType<JavaExpressionStatement>(clsC.Methods.Single(m => m.Name == "use").StructuredBody!.Statements[0]).Expression;
        var access = Assert.IsType<JavaMemberAccessExpression>(expr);
        Assert.Equal("X", access.MemberName);
        Assert.IsType<JavaThisExpression>(access.Target);
    }

    // ─── R-2：用户方法返回类型参与链式解析（raw + 结构化） ─────────────

    [Fact]
    public void Method_Return_Chain_Is_Rewritten()
    {
        var result = Convert("""
class A
{
    int X { get; set; }
}
class B
{
    public A a = new A();
}
class D
{
    B GetB() { return new B(); }
    int Read(D d) { return d.GetB().a.X; }
}
""");
        Assert.True(result.Success);
        // d.getB() 是用户方法（非访问器）：方法返回类型 B 参与链式解析 → 末端 getX 改写
        Assert.Contains("return d.getB().a.X;", result.GeneratedCode);
        Assert.DoesNotContain("getX()", result.GeneratedCode);
        AssertCompiles(result.GeneratedCode);
    }

    [Fact]
    public void Method_Return_Interface_Chain_Is_Rewritten()
    {
        var result = Convert("""
interface I
{
    int X { get; }
}
class Impl : I
{
    public int X { get; }
}
class D
{
    I GetI() { return new Impl(); }
    int Read(D d) { return d.GetI().X; }
}
""");
        Assert.True(result.Success);
        // 方法返回接口类型：getI() → I → I 的接口访问器注册 → getX 改写
        Assert.Contains("return d.getI().X;", result.GeneratedCode);
        Assert.DoesNotContain("d.getI().getX()", result.GeneratedCode);
        AssertCompiles(result.GeneratedCode);
    }

    [Fact]
    public void Method_Return_Chain_Unresolvable_Leaf_Is_Conservative()
    {
        var clsB = ClassWith("B");
        var clsD = ClassWith("D");
        clsD.Methods.Add(new JavaMethodDeclaration
        {
            Name = "getB",
            ReturnType = "B",
            Modifiers = JavaModifiers.Public,
            Body = "return new B();",
        });
        clsD.Methods.Add(new JavaMethodDeclaration
        {
            Name = "use",
            ReturnType = "int",
            Modifiers = JavaModifiers.Public,
            Parameters = { new JavaParameter("D", "d") },
            StructuredBody = new JavaMethodBody([new JavaRawStatement("return d.getB().getX();")]),
        });

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(clsB, clsD));

        // getB() → B 可解析，但 B 未注册 getX → 保守保留方法调用（不得误改）
        Assert.Equal("return d.getB().getX();",
            clsD.Methods.Single(m => m.Name == "use").StructuredBody!.Statements
                .Cast<JavaRawStatement>().Single().Code);
    }

    [Fact]
    public void Method_Return_Chain_Structured_Is_Rewritten()
    {
        var clsA = ClassWith("A", fields: [BackingField("X")], methods: [AutoGetter("X"), AutoSetter("X")]);
        var clsB = ClassWith("B", fields: [new JavaFieldDeclaration { Name = "a", Type = "A", Modifiers = JavaModifiers.Private }]);
        var clsD = ClassWith("D");
        clsD.Methods.Add(new JavaMethodDeclaration
        {
            Name = "getB",
            ReturnType = "B",
            Modifiers = JavaModifiers.Public,
            Body = "return new B();",
        });
        clsD.Methods.Add(new JavaMethodDeclaration
        {
            Name = "use",
            ReturnType = "int",
            Modifiers = JavaModifiers.Public,
            Parameters = { new JavaParameter("D", "d") },
            StructuredBody = new JavaMethodBody(
            [
                new JavaExpressionStatement(new JavaMethodCallExpression
                {
                    Target = new JavaMemberAccessExpression
                    {
                        Target = new JavaMethodCallExpression
                        {
                            Target = new JavaIdentifierExpression("d"),
                            MethodName = "getB",
                        },
                        MemberName = "a",
                    },
                    MethodName = "getX",
                }),
            ]),
        });

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(clsA, clsB, clsD));

        // 结构化链 d.getB().a.getX()：getB 用户方法返回类型 B → a:A → getX 改写为成员访问
        var expr = Assert.IsType<JavaExpressionStatement>(clsD.Methods.Single(m => m.Name == "use").StructuredBody!.Statements[0]).Expression;
        var access = Assert.IsType<JavaMemberAccessExpression>(expr);
        Assert.Equal("X", access.MemberName);
        var inner = Assert.IsType<JavaMemberAccessExpression>(access.Target);
        Assert.Equal("a", inner.MemberName);
        var call = Assert.IsType<JavaMethodCallExpression>(inner.Target);
        Assert.Equal("getB", call.MethodName);
        Assert.IsType<JavaIdentifierExpression>(call.Target);
    }
