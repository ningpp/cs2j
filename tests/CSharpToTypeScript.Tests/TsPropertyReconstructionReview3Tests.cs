/// 先写失败测试（红），修复后全绿；完整转换用例含 L3 tsc。
/// 实测注记：HIR 对继承的裸属性读/写（return X; / X = 5;）不降级为 getX()/setX()
/// （同声明类才降级），故"裸调用"以 IR 级 getX() 调用回归覆盖（见各测试注释）。
