    // ─── IR 构造辅助（与 Review1/Review2/Review3 同构，保持文件独立） ──────────

    private static JavaClassDeclaration ClassWith(
        string name,
        string? extends = null,
        List<JavaFieldDeclaration>? fields = null,
        List<JavaMethodDeclaration>? methods = null)
    {
        var cls = new JavaClassDeclaration
        {
            Name = name,
            Modifiers = JavaModifiers.Public,
            ExtendedType = extends,
        };
        if (fields != null) cls.Fields.AddRange(fields);
        if (methods != null) cls.Methods.AddRange(methods);
        return cls;
    }

    private static JavaMethodDeclaration AutoGetter(string propName, string returnType = "int",
        JavaModifiers extraModifiers = JavaModifiers.None)
    {
        var fieldName = char.ToLowerInvariant(propName[0]) + propName[1..];
        return new JavaMethodDeclaration
        {
            Name = "get" + propName,
            ReturnType = returnType,
            Modifiers = JavaModifiers.Public | extraModifiers,
            Body = $"return {fieldName};",
            IsAutoGenerated = true,
        };
    }

    private static JavaMethodDeclaration AutoSetter(string propName, string valueType = "int",
        JavaModifiers extraModifiers = JavaModifiers.None)
    {
        var fieldName = char.ToLowerInvariant(propName[0]) + propName[1..];
        return new JavaMethodDeclaration
        {
            Name = "set" + propName,
            ReturnType = "void",
            Modifiers = JavaModifiers.Public | extraModifiers,
            Body = $"this.{fieldName} = value;",
            Parameters = { new JavaParameter(valueType, "value") },
            IsAutoGenerated = true,
        };
    }

    private static JavaFieldDeclaration BackingField(string propName, string type = "int")
    {
        var fieldName = char.ToLowerInvariant(propName[0]) + propName[1..];
        return new JavaFieldDeclaration
        {
            Name = fieldName,
            Type = type,
            Modifiers = JavaModifiers.Private,
        };
    }

    private static JavaMethodDeclaration UserMethod(
        string name, string returnType, string body, params JavaParameter[] parameters)
    {
        var method = new JavaMethodDeclaration
        {
            Name = name,
            ReturnType = returnType,
            Modifiers = JavaModifiers.Public,
            Body = body,
        };
        foreach (var parameter in parameters) method.Parameters.Add(parameter);
        return method;
    }

    private static JavaCompilationUnit UnitWith(params JavaTypeDeclaration[] types)
    {
        var unit = new JavaCompilationUnit();
        foreach (var t in types) unit.TypeDeclarations.Add(t);
        return unit;
    }

    /// <summary>运行 rewriter 并返回指定方法结构化体首条 raw 语句文本。</summary>
    private static string RewrittenRawStatement(JavaCompilationUnit unit, string className, string methodName)
    {
        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(unit);
        var cls = unit.TypeDeclarations.OfType<JavaClassDeclaration>().Single(c => c.Name == className);
        return cls.Methods.Single(m => m.Name == methodName).StructuredBody!.Statements
            .Cast<JavaRawStatement>().Single().Code;
    }

    // ─── C1：循环继承（IR 防御）→ 不得栈溢出崩溃，保守不改写 ─────────────

    [Fact]
    public void Self_Extending_Class_Call_Site_Does_Not_Stack_Overflow()
    {
        // class A : A（IR 级自环）：TryResolveAccessorInContext 自递归 → 旧实现 StackOverflow
        var clsA = ClassWith("A", extends: "A");
        clsA.Methods.Add(new JavaMethodDeclaration
        {
            Name = "use",
            ReturnType = "int",
            Modifiers = JavaModifiers.Public,
            StructuredBody = new JavaMethodBody([new JavaRawStatement("return getX();")]),
        });

        var code = RewrittenRawStatement(UnitWith(clsA), "A", "use");

        // 防御：不得崩溃；解析不出 → 保守保留方法调用
        Assert.Equal("return getX();", code);
    }

    [Fact]
    public void Mutually_Cyclic_Bases_Call_Site_Does_Not_Stack_Overflow()
    {
        // class A : B / class B : A（IR 级环）：A → B → A 无限递归
        var clsA = ClassWith("A", extends: "B");
        var clsB = ClassWith("B", extends: "A");
        var clsC = ClassWith("C", extends: "A");
        clsC.Methods.Add(new JavaMethodDeclaration
        {
            Name = "use",
            ReturnType = "int",
            Modifiers = JavaModifiers.Public,
            StructuredBody = new JavaMethodBody([new JavaRawStatement("return getX();")]),
        });

        var code = RewrittenRawStatement(UnitWith(clsA, clsB, clsC), "C", "use");

        Assert.Equal("return getX();", code);
    }

    [Fact]
    public void Cyclic_Bases_Member_Resolution_Does_Not_Stack_Overflow()
    {
        // 链式段解析 ResolveMemberTypeInContext 遇环：d.nope 在 A → B → A 递归
        var clsA = ClassWith("A", extends: "B");
        var clsB = ClassWith("B", extends: "A");
        var clsD = ClassWith("D");
        clsD.Methods.Add(new JavaMethodDeclaration
        {
            Name = "use",
            ReturnType = "int",
            Modifiers = JavaModifiers.Public,
            Parameters = { new JavaParameter("A", "d") },
            StructuredBody = new JavaMethodBody([new JavaRawStatement("return d.nope.getX();")]),
        });

        var code = RewrittenRawStatement(UnitWith(clsA, clsB, clsD), "D", "use");

        // 不可解析段 → 保守保持方法调用
        Assert.Equal("return d.nope.getX();", code);
    }

    [Fact]
    public void Cyclic_Bases_Raw_Dot_Target_Does_Not_Stack_Overflow()
    {
        // 末端访问器查注册 TryResolveAccessorInContext 遇环：d 可解析为 A，末端 getX 沿 A→B→A
        var clsA = ClassWith("A", extends: "B");
