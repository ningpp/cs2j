    // ─── R-6：同名重载方法返回类型按"方法名 + 参数个数"键控 ─────────────

    [Fact]
    public void Overloaded_Method_Return_Chain_Uses_Arity_Raw()
    {
        // B1 GetB()（B1 有 Y）/ B2 GetB(int)（B2 有 X）：旧实现 MethodReturnTypes["getB"]
        // 被后声明者覆盖 → d.getB().getY() 漏改写（TS2339）
        var clsB1 = ClassWith("B1", fields: [BackingField("Y")], methods: [AutoGetter("Y"), AutoSetter("Y")]);
        var clsB2 = ClassWith("B2", fields: [BackingField("X")], methods: [AutoGetter("X"), AutoSetter("X")]);
        var clsD = ClassWith("D");
        clsD.Methods.Add(UserMethod("getB", "B1", "return new B1();"));
        clsD.Methods.Add(UserMethod("getB", "B2", "return new B2();", new JavaParameter("int", "i")));
        clsD.Methods.Add(new JavaMethodDeclaration
        {
            Name = "use",
            ReturnType = "int",
            Modifiers = JavaModifiers.Public,
            Parameters = { new JavaParameter("D", "d") },
            StructuredBody = new JavaMethodBody(
            [
                new JavaRawStatement("return d.getB().getY();"),
                new JavaRawStatement("return d.getB(1).getX();"),
            ]),
        });

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(clsB1, clsB2, clsD));
        var statements = clsD.Methods.Single(m => m.Name == "use").StructuredBody!.Statements
            .Cast<JavaRawStatement>().ToList();

        // 0 参 → B1（Y 命中）；1 参 → B2（X 命中）
        Assert.Equal("return d.getB().Y;", statements[0].Code);
        Assert.Equal("return d.getB(1).X;", statements[1].Code);
    }

    [Fact]
    public void Overloaded_Method_Return_Chain_Uses_Arity_Structured()
    {
        // 结构化 JavaMethodCallExpression 分支同样按实参个数消歧（R-6 随 R-2 结构化分支落地）
        var clsB1 = ClassWith("B1", fields: [BackingField("Y")], methods: [AutoGetter("Y"), AutoSetter("Y")]);
        var clsB2 = ClassWith("B2", fields: [BackingField("X")], methods: [AutoGetter("X"), AutoSetter("X")]);
        var clsD = ClassWith("D");
        clsD.Methods.Add(UserMethod("getB", "B1", "return new B1();"));
        clsD.Methods.Add(UserMethod("getB", "B2", "return new B2();", new JavaParameter("int", "i")));
        clsD.Methods.Add(new JavaMethodDeclaration
        {
            Name = "use",
            ReturnType = "int",
            Modifiers = JavaModifiers.Public,
            Parameters = { new JavaParameter("D", "d") },
            StructuredBody = new JavaMethodBody(
            [
                new JavaExpressionStatement(new JavaMethodCallExpression
                {
                    Target = new JavaMethodCallExpression
                    {
                        Target = new JavaIdentifierExpression("d"),
                        MethodName = "getB",
                        Arguments = { new JavaLiteralExpression("1") },
                    },
                    MethodName = "getX",
                }),
            ]),
        });

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(clsB1, clsB2, clsD));

        // d.getB(1)（1 参 → B2）→ 末端 getX 改写为成员访问 X
        var expr = Assert.IsType<JavaExpressionStatement>(clsD.Methods.Single(m => m.Name == "use").StructuredBody!.Statements[0]).Expression;
        var access = Assert.IsType<JavaMemberAccessExpression>(expr);
        Assert.Equal("X", access.MemberName);
        var call = Assert.IsType<JavaMethodCallExpression>(access.Target);
        Assert.Equal("getB", call.MethodName);
        Assert.Single(call.Arguments);
    }

    [Fact]
    public void Same_Arity_Overloads_With_Different_Types_Stay_Conservative()
    {
        // getB(int) → B2（X）/ getB(string) → B1（Y）同参个数不同参数类型：静态无法判定
        // → 不登记（宁可不改不可误改）；旧实现后声明者覆盖 → d.getB(1).getY() 误改写为
        // d.getB(1).Y（运行期 undefined，C1 类）
        var clsB1 = ClassWith("B1", fields: [BackingField("Y")], methods: [AutoGetter("Y"), AutoSetter("Y")]);
        var clsB2 = ClassWith("B2", fields: [BackingField("X")], methods: [AutoGetter("X"), AutoSetter("X")]);
        var clsD = ClassWith("D");
        // 危险顺序：getB(int)（B2）先声明，getB(string)（B1）后声明 → 旧实现键被 B1 覆盖
        clsD.Methods.Add(UserMethod("getB", "B2", "return new B2();", new JavaParameter("int", "i")));
        clsD.Methods.Add(UserMethod("getB", "B1", "return new B1();", new JavaParameter("string", "s")));
        clsD.Methods.Add(new JavaMethodDeclaration
        {
            Name = "use",
            ReturnType = "int",
            Modifiers = JavaModifiers.Public,
            Parameters = { new JavaParameter("D", "d") },
            StructuredBody = new JavaMethodBody([new JavaRawStatement("return d.getB(1).getY();")]),
        });

        var code = RewrittenRawStatement(UnitWith(clsB1, clsB2, clsD), "D", "use");

        // 歧义 → 保守保留方法调用
        Assert.Equal("return d.getB(1).getY();", code);
    }

    [Fact]
    public void Overloaded_Method_Return_Chain_Full_Pipeline()
    {
        // 完整管线（Task 23 起重载重命名生效：GetB(int) → getB_number，调用点同步）
        var result = Convert("""
class B1
{
    public int Y { get; set; }
}
class B2
{
    public int X { get; set; }
}
class D
{
    B1 GetB() { return new B1(); }
    B2 GetB(int i) { return new B2(); }
    int Read(D d) { return d.GetB().Y + d.GetB(1).X; }
}
""");
        Assert.True(result.Success);
        // 0 参调用点保留 getB() → B1.Y；1 参调用点改写为 getB_number(1) → B2.X
        Assert.Contains("d.getB().Y", result.GeneratedCode);
        Assert.Contains("d.getB_number(1).X", result.GeneratedCode);
        Assert.DoesNotContain("getY()", result.GeneratedCode);
        Assert.DoesNotContain("getX()", result.GeneratedCode);
    }

    // ─── R-7：方法返回数组 + 下标链（getA()[0]）漏改 ────────────────────

    [Fact]
    public void Array_Return_Method_Chain_Is_Rewritten()
    {
        // A[] GetA()：旧实现 ExtractRawChainSegments 要求 '[' 前为标识符字符，
        // getA()[0] 的 ')' 导致返回 null → 保守保留 getX()（TS2339）
        var clsA = ClassWith("A", fields: [BackingField("X")], methods: [AutoGetter("X"), AutoSetter("X")]);
        var clsD = ClassWith("D");
        clsD.Methods.Add(UserMethod("getA", "A[]", "return new A[1];"));
        clsD.Methods.Add(new JavaMethodDeclaration
        {
            Name = "use",
            ReturnType = "int",
            Modifiers = JavaModifiers.Public,
            Parameters = { new JavaParameter("D", "d") },
            StructuredBody = new JavaMethodBody([new JavaRawStatement("return d.getA()[0].getX();")]),
        });

        var code = RewrittenRawStatement(UnitWith(clsA, clsD), "D", "use");

        Assert.Equal("return d.getA()[0].X;", code);
    }

