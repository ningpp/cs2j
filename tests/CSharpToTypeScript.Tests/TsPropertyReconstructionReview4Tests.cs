/// <summary>
/// Task 16 四审回归测试（C1：循环继承输入栈溢出崩溃；R-6：同名重载方法返回类型
/// 字典覆盖——键改为"方法名 + 参数个数"；R-7：方法返回数组 + 下标链漏改）：
/// 先写失败测试（红），修复后全绿。循环继承在 C# 语法不可达（编译器拒绝），
/// 属 IR 级防御缺口，故以 IR 构造回归（不得崩溃 + 保守不改写）。
