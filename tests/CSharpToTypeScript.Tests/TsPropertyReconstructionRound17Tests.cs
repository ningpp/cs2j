    public void CrossFile_Accessor_Body_Field_Receiver_Is_Rewritten()
    {
        var edgeGeometry = ClassWith("EdgeGeometry",
            methods: [AutoGetter("SourcePort", "Port"), AutoSetter("SourcePort", "Port")]);
        var edge = ClassWith("Edge",
            fields: [BackingField("EdgeGeometry", "EdgeGeometry")],
            methods:
            [
                new JavaMethodDeclaration
                {
                    Name = "getEdgeGeometry",
                    ReturnType = "EdgeGeometry",
