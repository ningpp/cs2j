using CSharpToJava.Core.Java;
using CSharpToJava.Core.TypeScript;
using CSharpToJava.Core.TypeScript.Rewriters;

namespace CSharpToTypeScript.Tests;

/// <summary>
/// Task 16：TsPropertyReconstructionRewriter 组件级单测（IR 直构）。
/// 覆盖：get/set 配对、调用点改写（结构化 + raw 文本）、只读属性不生成 setter、
/// 非自动生成访问器形态不误改。
/// </summary>
public class TsPropertyReconstructionTests
{
    private static JavaClassDeclaration ClassWith(
        List<JavaFieldDeclaration>? fields = null,
        List<JavaMethodDeclaration>? methods = null)
    {
        var cls = new JavaClassDeclaration
        {
            Name = "Point",
            Modifiers = JavaModifiers.Public,
        };
        if (fields != null) cls.Fields.AddRange(fields);
        if (methods != null) cls.Methods.AddRange(methods);
        return cls;
    }

    private static JavaMethodDeclaration AutoGetter(string propName, string returnType = "int")
    {
        var fieldName = char.ToLowerInvariant(propName[0]) + propName[1..];
        return new JavaMethodDeclaration
        {
            Name = "get" + propName,
            ReturnType = returnType,
            Modifiers = JavaModifiers.Public,
            Body = $"return {fieldName};",
            IsAutoGenerated = true,
        };
    }

    private static JavaMethodDeclaration AutoSetter(string propName, string valueType = "int")
    {
        var fieldName = char.ToLowerInvariant(propName[0]) + propName[1..];
        return new JavaMethodDeclaration
        {
            Name = "set" + propName,
            ReturnType = "void",
            Modifiers = JavaModifiers.Public,
            Body = $"this.{fieldName} = value;",
            Parameters = { new JavaParameter(valueType, "value") },
            IsAutoGenerated = true,
        };
    }

    private static JavaFieldDeclaration BackingField(string propName, string type = "int")
    {
        var fieldName = char.ToLowerInvariant(propName[0]) + propName[1..];
        return new JavaFieldDeclaration
        {
            Name = fieldName,
            Type = type,
            Modifiers = JavaModifiers.Private,
        };
    }

    private static JavaCompilationUnit UnitWith(JavaClassDeclaration cls)
    {
        var unit = new JavaCompilationUnit();
        unit.TypeDeclarations.Add(cls);
        return unit;
    }

    private static string EmitType(JavaClassDeclaration cls, IReadOnlyDictionary<JavaMethodDeclaration, TsAccessorRole> roles)
    {
        var table = new TsMemberMappingTable(null, null);
        var imports = new TsImportCollector();
        var emitter = new TypeScriptEmitter(roles);
        return emitter.EmitType(cls, table, imports);
    }

    [Fact]
    public void Auto_Getter_Setter_Pair_Is_Simplified_To_Public_Field()
    {
        var cls = ClassWith(
            fields: [BackingField("X")],
            methods: [AutoGetter("X"), AutoSetter("X")]);

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(cls));

        // 自动 get;set; 配对 → 方法移除、后备字段提升为属性字段（PascalCase、可见性取 getter），
        // 侧表记录 Field 角色（方法节点虽已移除，角色仍可查）
        Assert.Empty(cls.Methods);
        var field = Assert.Single(cls.Fields);
        Assert.Equal("X", field.Name);
        Assert.Equal(JavaModifiers.Public, field.Modifiers & JavaModifiers.Public);
        Assert.Equal(2, rewriter.Roles.Count);
        Assert.All(rewriter.Roles.Values, r => Assert.Equal(TsAccessorRole.Field, r));
    }

    [Fact]
    public void Getter_Setter_Call_Sites_Are_Rewritten_To_Member_Access_And_Assignment()
    {
        var cls = ClassWith(
            fields: [BackingField("X")],
            methods:
            [
                AutoGetter("X"),
                AutoSetter("X"),
                new JavaMethodDeclaration
                {
                    Name = "use",
                    ReturnType = "int",
                    Modifiers = JavaModifiers.Public,
                    StructuredBody = new JavaMethodBody(
                    [
                        new JavaExpressionStatement(new JavaMethodCallExpression
                        {
                            Target = new JavaThisExpression(),
                            MethodName = "getX",
                        }),
                        new JavaExpressionStatement(new JavaMethodCallExpression
                        {
                            Target = new JavaThisExpression(),
                            MethodName = "setX",
                            Arguments = { new JavaIdentifierExpression("v") },
                        }),
                        new JavaRawStatement("this.setX(x);"),
                        new JavaRawStatement("return getX();"),
                    ]),
                },
            ]);

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(cls));

        var stmts = cls.Methods.Single(m => m.Name == "use").StructuredBody!.Statements;
        Assert.IsType<JavaMemberAccessExpression>(Assert.IsType<JavaExpressionStatement>(stmts[0]).Expression);
        var assignment = Assert.IsType<JavaAssignmentExpression>(Assert.IsType<JavaExpressionStatement>(stmts[1]).Expression);
        Assert.Equal("X", Assert.IsType<JavaMemberAccessExpression>(assignment.Target).MemberName);
        Assert.Equal("this.X = x;", Assert.IsType<JavaRawStatement>(stmts[2]).Code);
        Assert.Equal("return this.X;", Assert.IsType<JavaRawStatement>(stmts[3]).Code);
    }

    [Fact]
    public void Read_Only_Property_Emits_Getter_Without_Setter()
    {
        var cls = ClassWith(
            fields: [BackingField("X")],
            methods: [AutoGetter("X")]);

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(cls));

        var role = Assert.Single(rewriter.Roles.Values);
        Assert.Equal(TsAccessorRole.Getter, role);
        // 只读：后备字段保留，不生成 setter
        Assert.Single(cls.Fields);
        Assert.Single(cls.Methods);

        var code = EmitType(cls, rewriter.Roles);
        Assert.Contains("get X(): number", code);
        Assert.DoesNotContain("set X(", code);
        Assert.Contains("private x: number", code);
    }

    [Fact]
    public void User_Method_With_Accessor_Like_Name_Is_Not_Reconstructed()
    {
        var cls = ClassWith(
            methods:
            [
                new JavaMethodDeclaration
                {
                    Name = "getURL",
                    ReturnType = "string",
                    Modifiers = JavaModifiers.Public,
                    Body = "return \"\";",
                    IsAutoGenerated = false,
                },
                new JavaMethodDeclaration
                {
                    Name = "use",
                    ReturnType = "string",
                    Modifiers = JavaModifiers.Public,
                    StructuredBody = new JavaMethodBody(
                    [
                        new JavaRawStatement("return this.getURL();"),
                    ]),
                },
            ]);

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(cls));

        Assert.Empty(rewriter.Roles);
        Assert.Equal(2, cls.Methods.Count);
        Assert.Contains("return this.getURL();", cls.Methods.Single(m => m.Name == "use").StructuredBody!.Statements.Cast<JavaRawStatement>().Single().Code);
    }

    [Fact]
    public void Write_Only_Setter_Call_Is_Not_Rewritten_When_Another_Class_Has_Same_Property()
    {
        // 跨类同名访问器：Point.X（get;set; 字段简化）注册了全局 setX；
        // WriteOnly.X（只写）保留 setX 方法，其类内裸调用不得被全局集合误改
        var point = ClassWith(
            fields: [BackingField("X")],
            methods: [AutoGetter("X"), AutoSetter("X")]);
        var writeOnly = ClassWith(
            fields: [BackingField("X")],
            methods:
            [
                AutoSetter("X"),
                new JavaMethodDeclaration
                {
                    Name = "use",
                    ReturnType = "void",
                    Modifiers = JavaModifiers.Public,
                    StructuredBody = new JavaMethodBody(
                    [
                        new JavaRawStatement("setX(v);"),
                    ]),
                },
            ]);

        var unit = new JavaCompilationUnit();
        unit.TypeDeclarations.Add(point);
        unit.TypeDeclarations.Add(writeOnly);

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(unit);

        var writeOnlySetter = writeOnly.Methods.Single(m => m.Name == "setX");
        Assert.Equal(TsAccessorRole.WriteOnly, rewriter.Roles[writeOnlySetter]);
        Assert.Equal("setX(v);", writeOnly.Methods.Single(m => m.Name == "use").StructuredBody!.Statements.Cast<JavaRawStatement>().Single().Code);
    }

    [Fact]
    public void Explicit_Interface_Implementation_Accessor_Is_Not_Reconstructed()
    {
        var cls = ClassWith(
            fields: [BackingField("X")],
            methods:
            [
                new JavaMethodDeclaration
                {
                    Name = "getX",
                    ReturnType = "int",
                    Modifiers = JavaModifiers.Public,
                    Body = "return x;",
                    IsAutoGenerated = true,
                    IsExplicitInterfaceImplementation = true,
                },
                new JavaMethodDeclaration
                {
                    Name = "setX",
                    ReturnType = "void",
                    Modifiers = JavaModifiers.Public,
                    Body = "this.x = value;",
                    Parameters = { new JavaParameter("int", "value") },
                    IsAutoGenerated = true,
                    IsExplicitInterfaceImplementation = true,
                },
            ]);

        var rewriter = new TsPropertyReconstructionRewriter();
        rewriter.VisitCompilationUnit(UnitWith(cls));

        Assert.Empty(rewriter.Roles);
        Assert.Equal(2, cls.Methods.Count);
        Assert.Equal("x", Assert.Single(cls.Fields).Name);
    }
}
