using CSharpToJava.Core.Context;
using CSharpToJava.Core.Pipeline;
using Xunit;

namespace CSharpToJava.Tests;

/// <summary>
/// Tests that LINQ rewrite inside C# local functions correctly captures
/// variables from the enclosing method scope. The LinqRewriter generates
/// ProceduralLinq helper methods, and when the enclosing local function
/// is hoisted to class level, the ProceduralLinq helper must also receive
/// the captured variables as parameters.
/// </summary>
public class LinqLocalFunctionCaptureTests
{
    [Fact]
    public void LinqInsideLocalFunction_CapturesOuterMethodLocal()
    {
        // Reproduces NetworkSimplexMatrixTest pattern:
        // BruteForceMinimumWeight has a local function Search that uses LINQ
        // referencing 'layers' (an outer method local) inside the lambda.
        var csharp = @"
using System;
using System.Collections.Generic;
using System.Linq;

public class C
{
    static int BruteForce(IReadOnlyList<Edge> edges, int nodeCount)
    {
        int maxLayer = edges.Sum(e => e.Separation);
        var layers = new int[nodeCount];
        int best = int.MaxValue;

        void Search(int v)
        {
            if (v == nodeCount)
            {
                if (edges.All(e => layers[e.Source] - layers[e.Target] >= e.Separation))
                {
                    int objective = edges.Sum(e => e.Weight * (layers[e.Source] - layers[e.Target]));
                    best = Math.Min(best, objective);
                }
                return;
            }
            int min = v == 0 ? 0 : -maxLayer;
            int max = v == 0 ? 0 : maxLayer;
            for (int layer = min; layer <= max; layer++)
            {
                layers[v] = layer;
                Search(v + 1);
            }
        }

        Search(0);
        return best;
    }
}

public class Edge
{
    public int Source { get; set; }
    public int Target { get; set; }
    public int Weight { get; set; }
    public int Separation { get; set; }
}";

        var result = Convert(csharp);
        Assert.True(result.Success, result.GeneratedCode ?? string.Join("\n", result.Diagnostics));
        var code = result.GeneratedCode ?? "";

        // Print the generated code for debugging
        // Assert.Contains("DEBUG_OUTPUT_BELOW", code + "DEBUG_OUTPUT_BELOW");
        // System.Console.WriteLine("=== Generated Code ===");
        // System.Console.WriteLine(code);

        // The ProceduralLinq methods should receive 'layers' as a parameter.
        // After hoisting, the local function Search becomes search(int, ...) with
        // _cs2j_cap_layers as a captured parameter. The ProceduralLinq helper methods
        // generated by LinqRewriter must also receive layers (or _cs2j_cap_layers).
        Assert.Contains("ProceduralLinq", code);
        // Check that layers appears as a parameter in the ProceduralLinq method signature.
        // It might be named 'layers' or '_cs2j_cap_layers' depending on whether the
        // LinqRewriter captures it before or after the local function hoisting renames it.
        Assert.Matches(@"ProceduralLinq\d*\s*\([^)]*(layers|_cs2j_cap_layers)[^)]*\)", code);
    }

    private static ConversionResult Convert(string sourceCode)
    {
        var pipeline = new ConversionPipeline();
        return pipeline.Convert(new ConversionRequest
        {
            SourceCode = sourceCode,
            FileName = "Test.cs",
            Options = new ConversionOptions
            {
                TypeMappingConfigPath = Path.Combine(AppContext.BaseDirectory, "config", "TypeMappings.json"),
                PreferStreamApi = false,
            },
        });
    }
}
